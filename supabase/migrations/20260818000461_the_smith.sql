begin
  select string_agg(format('%s (%s of %s)', g.name,
           trim(to_char(coalesce(ps.qty, 0), 'FM999999.99')),
           trim(to_char(gr.qty * p_qty, 'FM999999.99'))), ', ' order by g.name)
