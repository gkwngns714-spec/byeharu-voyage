     or (select md5(string_agg(to_jsonb(c)::text, '|' order by c.class_code, c.good_id)) from public.hull_recipe_goods c where c.class_code in (select code from live_classes_0135)) <> (select recipe_goods_hash from before_0135)
     or (select md5(string_agg(to_jsonb(c)::text, '|' order by c.class_code, c.item_code)) from public.hull_recipe_items c) <> (select recipe_items_hash from before_0135)
     or (select md5(string_agg(to_jsonb(c)::text, '|' order by c.class_code, c.slot, c.min_level)) from public.class_slot_unlocks c) <> (select unlocks_hash from before_0135)
     or (select string_agg(pg_get_constraintdef(k.oid), ' | ' order by k.conname) from pg_constraint k where k.conrelid = 'public.ship_classes'::regclass) <> (select classes_checks from before_0135) then
    raise exception '0135 self-assert FAIL: a live hull''s row moved (class, profile, racks, cabins, recipe, fittings, unlocks or constraints)';
  end if;
  if (select count(*) from live_classes_0135) <> 3 then
    raise exception '0135 self-assert FAIL: % live hull(s) found, expected the three', (select count(*) from live_classes_0135);
  end if;

