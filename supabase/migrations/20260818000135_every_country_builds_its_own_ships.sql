    from jsonb_each_text(v_p->'lit0') e
   where split_part(e.value, ':', 1) <> 'E_NEEDS_SKILL'
      or position('ship skills are not in use yet' in e.value) <> 0
      or (v_p->'unmet0'->>e.key)::int <> (select count(*) from public.skill_requirements r where r.subject_kind = 'hull' and r.subject_code = e.key);
  if v_bad <> 0 or (select count(*) from jsonb_object_keys(v_p->'lit0')) <> 52 then
    raise exception '0135 self-assert FAIL: lit without skills, % new hull(s) not refused with every requirement: %', v_bad, v_list;
