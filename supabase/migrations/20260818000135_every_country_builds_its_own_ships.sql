-- The hot reads, timed: every merchant hull's speed + hold (the arrivals' per-hull reads), ship_stats
-- and ship_view, and a fixed grid of quotes. Two passes; the faster is kept. Answers hashed.
create temp table hot_hulls_0135 on commit drop as
select s.id from public.ships s join public.players p on p.id = s.player_id where p.is_npc;

create temp table quote_grid_0135 on commit drop as
select ps.port_id, ps.good_id, x.qty, x.side, f.id as fleet
  from (select ps0.*, row_number() over (order by ps0.port_id, ps0.good_id) as k from public.port_specialties ps0) ps
  left join lateral (select fl.id from public.fleets fl where fl.port_id = ps.port_id and fl.status = 'DOCKED'
                      order by fl.id limit 1) f on true
 cross join (values (40::numeric, 'buy'), (40::numeric, 'sell')) x(qty, side)
 where ps.k % 3 = 0;

create temp table reads_0135 (phase text, what text, n bigint, ms numeric, answer text) on commit drop;
create or replace function pg_temp.time_reads_0135(p_phase text)
returns void
language plpgsql
as $$
declare
  v_t0   timestamptz;
  v_ms   numeric;
  v_best numeric;
  v_ans  text;
  v_pass int;
  w      text;
begin
  foreach w in array array['speed+hold', 'ship_stats', 'ship_view', 'quotes'] loop
    v_best := null;
    for v_pass in 1 .. 2 loop
      v_t0 := clock_timestamp();
      if w = 'speed+hold' then
        select md5(string_agg(voyage.ship_speed(h.id)::text || '/' || public.ship_hold_capacity(h.id)::text, '|' order by h.id))
          into v_ans from hot_hulls_0135 h;
      elsif w = 'ship_stats' then
        select md5(string_agg(world.ship_stats(h.id)::text, '|' order by h.id)) into v_ans from hot_hulls_0135 h;
      elsif w = 'ship_view' then
        select md5(string_agg(world.ship_view(h.id)::text, '|' order by h.id)) into v_ans from hot_hulls_0135 h;
      else
        select md5(string_agg(to_jsonb(q)::text, '|' order by g.port_id, g.good_id, g.side))
          into v_ans
          from quote_grid_0135 g
         cross join lateral world.quote(g.port_id, g.good_id, g.qty, g.side, null, g.fleet) q;
      end if;
      v_ms := round(extract(epoch from clock_timestamp() - v_t0) * 1000, 1);
      v_best := least(coalesce(v_best, v_ms), v_ms);
    end loop;
    insert into reads_0135 values (p_phase, w,
      case when w = 'quotes' then (select count(*) from quote_grid_0135) else (select count(*) from hot_hulls_0135) end,
      v_best, v_ans);
  end loop;
end $$;

