     or (v_p->>'lever_yard')::bigint <> 2 * (v_p->>'lever_fluyt_recipe')::bigint
     or (v_p->>'lever_barca_yard')::bigint <> 6000 then
    raise exception '0135 self-assert FAIL: hull_labour_mult 2.0 did not double the labour (door %, yard %, barca %)',
      v_p->>'lever_fluyt', v_p->>'lever_yard', v_p->>'lever_barca_yard';
