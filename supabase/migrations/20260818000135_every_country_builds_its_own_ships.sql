    raise exception '0135 self-assert FAIL: % hull fitting(s) can be made in no city', v_bad;
  end if;
  if not exists (select 1 from public.port_buildings where kind = 'building_yard' and tier = 1)
     or not exists (select 1 from public.port_buildings where kind = 'building_yard' and tier >= 3) then
    raise exception '0135 self-assert FAIL: the build yards'' tiers no longer differ';
  end if;
  select count(*), string_agg(x.class_code, ',' order by x.class_code) into v_bad, v_list from (
