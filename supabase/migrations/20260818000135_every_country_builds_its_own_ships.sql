-- ── 0. HELPERS (pg_temp, gone at commit) ───────────────────────────────────────────────────────
-- One BUILD through the one door, undone at once: the fleet is docked at p_yard, the purse read
-- before and after; returns 'ok:<ducats paid>' or the refusal 'E_CODE: sentence'. A lock the live
-- world holds (55P03 / 40P01) is not an answer: retried, then LOCK CONTENTION.
create or replace function pg_temp.try_build_0135(p_player uuid, p_fleet uuid, p_class text, p_yard uuid)
returns text
language plpgsql
as $$
declare
  v_msg   text;
  v_state text;
  v_try   int := 0;
  v_paid  bigint;
begin
  update public.fleets set port_id = p_yard, status = 'DOCKED' where id = p_fleet;
  loop
    v_try := v_try + 1;
    v_msg := null;
    v_state := null;
    begin
      v_paid := (select ducats from public.players where id = p_player);
      perform cmd.do_build(p_fleet, jsonb_build_object('class', p_class, 'name', 'Prova ' || p_class));
      v_paid := v_paid - (select ducats from public.players where id = p_player);
      raise exception 'PROBE_UNDO_0135:%', v_paid;
    exception when others then
      get stacked diagnostics v_msg = message_text, v_state = returned_sqlstate;
    end;
    exit when v_state not in ('55P03', '40P01');
    if v_try >= 5 then
      raise exception '0135 self-assert FAIL: LOCK CONTENTION, not a result — BUILD % could not get its locks in 5 tries (%: %). Re-run the push.',
        p_class, v_state, v_msg;
    end if;
    perform pg_sleep(0.2);
  end loop;
  return case when v_msg like 'PROBE_UNDO_0135:%' then 'ok:' || split_part(v_msg, ':', 2) else v_msg end;
end $$;

