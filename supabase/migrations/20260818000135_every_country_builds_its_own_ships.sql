    raise exception '0135 self-assert FAIL: the yard screen does not open % new hull(s) at the yard the rule names: %', v_bad, v_list;
  end if;

  -- (g) 0068 + 0074 OVER EVERY ITEM. Every recipe 2-5 goods, every good SOLD somewhere, every item made at
  --     ≥ 1 workshop; every item buys a stat and spends one (the Figurehead base type, every grade, moves
  --     none — DESIGN 1.4); every item's rack has places on ≥ 1 hull; every item one rack, grade 1-5.
  select count(*) into v_bad from (select item_code, count(*) n from public.item_recipes group by item_code) x where x.n not between 2 and 5;
  if v_bad <> 0 then
