                            where p.size = 1 and cc.cabins <> 3) then
    raise exception '0135 self-assert FAIL: places do not grow with the size (% step(s)), or a small hull does not berth 3 captains', v_bad;
  end if;

  -- (i) THE REQUIREMENTS, by §4.4 and §6.2: every new hull carries its size's pattern (1 / 2 / 2 / 3 rows,
  --     its own line's hull skills, the heavy's role skill); the live three and the twelve G1 items none;
  --     every item row is its module skill at its grade or the base type's own second skill.
  select count(*), string_agg(c.code, ',' order by c.code) into v_bad, v_list
    from public.ship_classes c join public.class_profile p on p.class_code = c.code
   where c.code not in (select code from live_classes_0135)
     and ((select count(*) from public.skill_requirements r where r.subject_kind = 'hull' and r.subject_code = c.code)
            <> case p.size when 1 then 1 when 2 then 2 when 3 then 2 else 3 end
          or exists (select 1 from public.skill_requirements r join public.skill_profile pr on pr.skill_id = (select id from public.skills where code = r.skill_code)
                      where r.subject_kind = 'hull' and r.subject_code = c.code and pr.group_code = 'HULLS' and pr.line_code <> p.line_code)
          or not exists (select 1 from public.skill_requirements r
                          where r.subject_kind = 'hull' and r.subject_code = c.code and r.skill_code = p.line_code || '_' || upper(case p.size when 1 then 'small' when 2 then 'light' when 3 then 'medium' else 'heavy' end) and r.level = 1));
  if v_bad <> 0 then
    raise exception '0135 self-assert FAIL: % new hull(s) do not carry §4.4''s requirements: %', v_bad, v_list;
  end if;
  if exists (select 1 from public.skill_requirements r
              where (r.subject_kind = 'hull' and r.subject_code in (select code from live_classes_0135))
                 or (r.subject_kind = 'item' and r.subject_code in (select code from live_items_0135))) then
    raise exception '0135 self-assert FAIL: a live hull or G1 item needs a skill — §4.4 / §6.2 say nothing';
  end if;
  if (select count(*) from public.skill_requirements where subject_kind = 'hull') <> 102
     or (select count(*) from public.skill_requirements where subject_kind = 'item') <> 98
     or exists (select 1 from public.skill_requirements r where not exists (select 1 from public.skills s where s.code = r.skill_code))
     or exists (select 1 from public.skill_requirements r where r.subject_kind = 'hull' and not exists (select 1 from public.ship_classes c where c.code = r.subject_code))
     or exists (select 1 from public.skill_requirements r where r.subject_kind = 'item' and not exists (select 1 from public.item_kinds k where k.code = r.subject_code)) then
    raise exception '0135 self-assert FAIL: the requirement rows are not 102 hull + 98 item rows naming real skills and subjects';
  end if;

  -- (j) THE RE-CUTS reverse to their pre-images hunk by hunk; ACLs unmoved; no new entry point; the lever
  --     server-only; the posture (client write grants / executable writers) zero.
  for d in select * from defs_before_0135 loop
    v_def := replace(pg_get_functiondef(d.fn::regprocedure), E'\r', '');
    for h in select * from hunks_0135 where fn = d.fn order by n desc loop
      if (length(v_def) - length(replace(v_def, h.new, ''))) / length(h.new) <> 1 then
        raise exception '0135 self-assert FAIL: hunk % of % is not in the new body exactly once', h.n, d.fn;
      end if;
      v_def := replace(v_def, h.new, h.old);
    end loop;
    if v_def <> d.def then
      raise exception '0135 self-assert FAIL: % does not reverse to its pre-image — something beyond the hunks moved', d.fn;
    end if;
    if coalesce((select p.proacl::text from pg_proc p where p.oid = d.fn::regprocedure), '') <> d.acl then
      raise exception '0135 self-assert FAIL: the ACL of % moved', d.fn;
    end if;
  end loop;
  if (select count(*) from public.client_rpc_entry_points()) <> (select entry_points from before_0135)
     or has_function_privilege('authenticated', 'public.hull_labour(text)', 'execute')
     or has_function_privilege('anon', 'public.hull_labour(text)', 'execute')
     or (select count(*) from public.client_write_grants()) <> 0
     or (select count(*) from public.client_executable_writers()) <> 0 then
    raise exception '0135 self-assert FAIL: an entry point, the lever''s grant or the write posture moved';
  end if;

  -- (k) THE LEVER AT 1.0 IS THE PRE-IMAGE: every hull's labour is its recipe's ducats.
  if (select value from public.world_config where key = 'hull_labour_mult') <> '1.0'::jsonb
     or exists (select 1 from public.hull_recipes hr where public.hull_labour(hr.class_code) <> hr.ducats) then
