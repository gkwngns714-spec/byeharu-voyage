  if (select count(*) from public.ship_classes) <> (select classes from before_0135) + 52
     or (select count(*) from public.class_profile) <> (select profiles from before_0135) + 52
     or (select count(*) from public.class_slots) <> (select slots from before_0135) + 198
     or (select count(*) from public.class_cabins) <> (select cabins from before_0135) + 52
     or (select count(*) from public.hull_recipes) <> (select recipes from before_0135) + 52
     or (select count(*) from public.hull_recipe_goods) <> (select recipe_goods from before_0135) + 209
     or (select count(*) from public.hull_recipe_items) <> (select recipe_items from before_0135)
     or (select count(*) from public.item_kinds) <> (select kinds from before_0135) + 103
     or (select count(*) from public.item_profile) <> (select item_profiles from before_0135) + 103
     or (select count(*) from public.item_effects) <> (select effects from before_0135) + 285
     or (select count(*) from public.item_recipes) <> (select item_recipes from before_0135) + 338
     or (select count(*) from public.skill_requirements) <> (select requirements from before_0135) + 200
     or (select requirements from before_0135) <> 0 then
    raise exception '0135 self-assert FAIL: the catalogue counts are not the pre-image plus the generated rows (classes %, kinds %, requirements %)',
      (select count(*) from public.ship_classes), (select count(*) from public.item_kinds), (select count(*) from public.skill_requirements);
  end if;
  select count(*) into v_bad from public.ship_classes c
   where not exists (select 1 from public.class_profile p where p.class_code = c.code)
      or not exists (select 1 from public.class_cabins x where x.class_code = c.code)
      or not exists (select 1 from public.hull_recipes x where x.class_code = c.code)
      or not exists (select 1 from public.hull_recipe_goods x where x.class_code = c.code)
      or not exists (select 1 from public.class_slots x where x.class_code = c.code);
  select v_bad + count(*) into v_bad from public.item_kinds k
   where not exists (select 1 from public.item_profile p where p.item_code = k.code)
      or not exists (select 1 from public.item_recipes x where x.item_code = k.code);
  if v_bad <> 0 then
    raise exception '0135 self-assert FAIL: % hull(s) / item(s) lack a profile, cabins, recipe or racks', v_bad;
  end if;

  -- (d) THE HULL RULES over every class: guns = attack / 10 (0074's data rule, so the escort score of an
  --     unfitted hull is the class's); tier = least(size, 5) (0130); Hands = crew_max − ⌈crew_required / 2⌉ ≥ 0;
  --     yard tier by size; the new hulls T1 and built only in their line's countries.
  select count(*), string_agg(c.code, ',' order by c.code) into v_bad, v_list
    from public.ship_classes c join public.class_profile p on p.class_code = c.code
    join public.hull_recipes hr on hr.class_code = c.code
   where c.guns * 10 <> c.attack or c.tier <> least(p.size, 5)
      or c.crew_max - (c.crew_required + 1) / 2 < 0
      or hr.yard_tier <> case p.size when 1 then 1 when 2 then 2 else 3 end
      or (c.code not in (select code from live_classes_0135) and (p.tech <> 'T1' or p.any_yard));
  if v_bad <> 0 then
    raise exception '0135 self-assert FAIL: % class(es) break guns = attack / 10, tier = size, the Hands budget, the yard tier by size or T1 / own-country: %', v_bad, v_list;
  end if;

  -- (e) 0072 (b)(c)(d) OVER EVERY HULL. (b) every material is SOLD somewhere, every hull fitting MADE
  --     somewhere; (c) build yards of tier 1 and of tier 3 both exist; (d) every hull's materials fit the
  --     storage of a yard where it can be built (its tier and its line's countries).
  select count(*), string_agg(distinct g.code, ',') into v_bad, v_list
    from public.hull_recipe_goods hg join public.goods g on g.id = hg.good_id
   where not exists (select 1 from public.port_goods pg join public.ports p on p.id = pg.port_id
                      where pg.good_id = hg.good_id and public.port_offers(p.id, hg.good_id));
  if v_bad <> 0 then
    raise exception '0135 self-assert FAIL: % hull material(s) are sold in NO city: %', v_bad, v_list;
  end if;
  select count(*) into v_bad from public.hull_recipe_items hi join public.item_kinds k on k.code = hi.item_code
   where not exists (select 1 from public.port_buildings b where b.kind = 'workstation' and b.tier >= k.ws_tier);
