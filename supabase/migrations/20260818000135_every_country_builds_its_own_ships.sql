     or (select md5(string_agg(to_jsonb(c)::text, '|' order by c.item_code)) from public.item_profile c where c.item_code in (select code from live_items_0135)) <> (select item_profile_hash from before_0135)
     or (select md5(string_agg(to_jsonb(c)::text, '|' order by c.item_code, c.stat)) from public.item_effects c where c.item_code in (select code from live_items_0135)) <> (select effects_hash from before_0135)
