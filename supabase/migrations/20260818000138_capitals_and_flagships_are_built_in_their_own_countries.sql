-- ── WHAT THIS FILE DOES ─────────────────────────────────────────────────────────────────────────
-- (1) THE 15 HULLS — generated by scripts/build-ships.mjs, the SAME generator as 0135 (one archetype
--     table × one line table, §4.2): four new archetypes (capital / flagship × trade / combat, solved
--     from §4.3's Wave B table; every one of the 15 rows equals the table in every stat column).
--     public.ship_classes (tier = least(size, 5) = 5, guns = attack / 10), class_profile (line, size
--     5 or 6, role, T1, deck, any_yard false), class_slots by RACK (+ 1 Flourish), class_cabins (7 a
