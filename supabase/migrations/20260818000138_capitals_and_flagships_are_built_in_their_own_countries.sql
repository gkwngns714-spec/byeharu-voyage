-- ── 0. HELPERS (pg_temp, gone at commit) ───────────────────────────────────────────────────────
-- One BUILD through the one door, undone at once: the fleet is docked at p_yard, the purse read
-- before and after; returns 'ok:<ducats paid>' or the refusal 'E_CODE: sentence'. A lock the live
-- world holds (55P03 / 40P01) is not an answer: retried, then LOCK CONTENTION.
create or replace function pg_temp.try_build_0138(p_player uuid, p_fleet uuid, p_class text, p_yard uuid)
returns text
language plpgsql
as $$
declare
  v_msg   text;
  v_state text;
  v_try   int := 0;
  v_paid  bigint;
begin
  update public.fleets set port_id = p_yard, status = 'DOCKED' where id = p_fleet;
  loop
    v_try := v_try + 1;
    v_msg := null;
    v_state := null;
    begin
      v_paid := (select ducats from public.players where id = p_player);
      perform cmd.do_build(p_fleet, jsonb_build_object('class', p_class, 'name', 'Prova ' || p_class));
      v_paid := v_paid - (select ducats from public.players where id = p_player);
      raise exception 'PROBE_UNDO_0138:%', v_paid;
    exception when others then
      get stacked diagnostics v_msg = message_text, v_state = returned_sqlstate;
    end;
    exit when v_state not in ('55P03', '40P01');
    if v_try >= 5 then
      raise exception '0138 self-assert FAIL: LOCK CONTENTION, not a result — BUILD % could not get its locks in 5 tries (%: %). Re-run the push.',
        p_class, v_state, v_msg;
    end if;
    perform pg_sleep(0.2);
  end loop;
  return case when v_msg like 'PROBE_UNDO_0138:%' then 'ok:' || split_part(v_msg, ':', 2) else v_msg end;
end $$;

-- The hot reads, timed (0135's gauge, unchanged): every merchant hull's speed + hold (the arrivals'
-- per-hull reads), ship_stats and ship_view, and a fixed grid of quotes. Two passes; the faster kept.
create temp table hot_hulls_0138 on commit drop as
select s.id from public.ships s join public.players p on p.id = s.player_id where p.is_npc;

create temp table quote_grid_0138 on commit drop as
select ps.port_id, ps.good_id, x.qty, x.side, f.id as fleet
  from (select ps0.*, row_number() over (order by ps0.port_id, ps0.good_id) as k from public.port_specialties ps0) ps
  left join lateral (select fl.id from public.fleets fl where fl.port_id = ps.port_id and fl.status = 'DOCKED'
                      order by fl.id limit 1) f on true
 cross join (values (40::numeric, 'buy'), (40::numeric, 'sell')) x(qty, side)
 where ps.k % 3 = 0;

create temp table reads_0138 (phase text, what text, n bigint, ms numeric, answer text) on commit drop;
-- Timed at PRODUCTION'S planner page cost, both phases alike (header, COST). Scoped to this pg_temp
-- function, gone at commit.
create or replace function pg_temp.time_reads_0138(p_phase text)
returns void
language plpgsql
set random_page_cost = 1.1
as $$
declare
  v_t0   timestamptz;
  v_ms   numeric;
  v_best numeric;
  v_ans  text;
  v_pass int;
  w      text;
begin
  foreach w in array array['speed+hold', 'ship_stats', 'ship_view', 'quotes'] loop
    v_best := null;
    for v_pass in 1 .. 2 loop
      v_t0 := clock_timestamp();
      if w = 'speed+hold' then
        select md5(string_agg(voyage.ship_speed(h.id)::text || '/' || public.ship_hold_capacity(h.id)::text, '|' order by h.id))
          into v_ans from hot_hulls_0138 h;
      elsif w = 'ship_stats' then
        select md5(string_agg(world.ship_stats(h.id)::text, '|' order by h.id)) into v_ans from hot_hulls_0138 h;
      elsif w = 'ship_view' then
        select md5(string_agg(world.ship_view(h.id)::text, '|' order by h.id)) into v_ans from hot_hulls_0138 h;
      else
        select md5(string_agg(to_jsonb(q)::text, '|' order by g.port_id, g.good_id, g.side))
          into v_ans
          from quote_grid_0138 g
         cross join lateral world.quote(g.port_id, g.good_id, g.qty, g.side, null, g.fleet) q;
      end if;
      v_ms := round(extract(epoch from clock_timestamp() - v_t0) * 1000, 1);
      v_best := least(coalesce(v_best, v_ms), v_ms);
    end loop;
    insert into reads_0138 values (p_phase, w,
      case when w = 'quotes' then (select count(*) from quote_grid_0138) else (select count(*) from hot_hulls_0138) end,
      v_best, v_ans);
  end loop;
end $$;

