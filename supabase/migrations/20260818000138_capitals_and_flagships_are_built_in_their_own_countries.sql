-- Wave B table, §4.4 the requirements, §10 risk 3 "the shed assert"). 0135 (S12) put the T1 core of
-- every line into the world, sizes small → heavy. This file adds the top of the grid: one capital per
-- line (eleven) and a flagship for each of the four great naval powers (PRT, ESP, ENG, OTT).
--
-- ── WHAT SAYS THE OPPOSITE TODAY, NAMED ─────────────────────────────────────────────────────────
--   * public.class_profile admits sizes 1-6 (0130) and the hull skills X_CAPITAL (0131) exist, but no
--     hull of size 5 or 6 does: Capital Hulls, Command and Fleet Command gate nothing a house can build.
--   * 0072 (d) "a hull fits in the shed it is built from": a flagship's size template (medium × 3,
--     §4.3) wants 1,071 tuns and the biggest shed in the world holds 750 (a tier-5 warehouse × 150,
