-- ── SELF-ASSERT ────────────────────────────────────────────────────────────────────────────────
do $$
declare
  v_bad    int;
  v_list   text;
  rb       record;
  ra       record;
  v_p      jsonb := (select j from probe_0138);
  v_new    int;
  v_yards  int;
  v_old    int := (select count(*) from live_classes_0138);
  v_timing text := '';
  v_shed   text;
begin
  -- (a) THE 55 HULLS ALREADY IN THE WORLD ARE UNTOUCHED: class, profile, rack, cabin, recipe and
  --     requirement rows hash as before; fittings, unlocks, items, effects and constraints as found.
  if (select md5(string_agg(to_jsonb(c)::text, '|' order by c.code)) from public.ship_classes c where c.code in (select code from live_classes_0138)) <> (select classes_hash from before_0138)
     or (select md5(string_agg(to_jsonb(c)::text, '|' order by c.class_code)) from public.class_profile c where c.class_code in (select code from live_classes_0138)) <> (select profile_hash from before_0138)
     or (select md5(string_agg(to_jsonb(c)::text, '|' order by c.class_code, c.slot)) from public.class_slots c where c.class_code in (select code from live_classes_0138)) <> (select slots_hash from before_0138)
     or (select md5(string_agg(to_jsonb(c)::text, '|' order by c.class_code)) from public.class_cabins c where c.class_code in (select code from live_classes_0138)) <> (select cabins_hash from before_0138)
     or (select md5(string_agg(to_jsonb(c)::text, '|' order by c.class_code)) from public.hull_recipes c where c.class_code in (select code from live_classes_0138)) <> (select recipes_hash from before_0138)
     or (select md5(string_agg(to_jsonb(c)::text, '|' order by c.class_code, c.good_id)) from public.hull_recipe_goods c where c.class_code in (select code from live_classes_0138)) <> (select recipe_goods_hash from before_0138)
     or (select md5(string_agg(to_jsonb(c)::text, '|' order by c.class_code, c.item_code)) from public.hull_recipe_items c) <> (select recipe_items_hash from before_0138)
     or (select md5(string_agg(to_jsonb(c)::text, '|' order by c.class_code, c.slot, c.min_level)) from public.class_slot_unlocks c) <> (select unlocks_hash from before_0138)
     or (select md5(string_agg(to_jsonb(c)::text, '|' order by c.subject_kind, c.subject_code, c.skill_code)) from public.skill_requirements c
          where c.subject_kind = 'item' or c.subject_code in (select code from live_classes_0138)) <> (select requirements_hash from before_0138)
     or (select md5(string_agg(to_jsonb(c)::text, '|' order by c.code)) from public.item_kinds c) <> (select kinds_hash from before_0138)
     or (select md5(string_agg(to_jsonb(c)::text, '|' order by c.item_code, c.stat)) from public.item_effects c) <> (select effects_hash from before_0138)
     or (select string_agg(pg_get_constraintdef(k.oid), ' | ' order by k.conname) from pg_constraint k where k.conrelid = 'public.ship_classes'::regclass) <> (select classes_checks from before_0138) then
    raise exception '0138 self-assert FAIL: a row of a hull already in the world moved (class, profile, racks, cabins, recipe, requirements), or an item, effect, unlock or constraint did';
  end if;
  if v_old = 0 or not exists (select 1 from live_classes_0138 where code = 'barca') then
    raise exception '0138 self-assert FAIL: the world held no hulls before this file (% found)', v_old;
  end if;

  -- (b) EXACTLY THE GENERATED ROWS LANDED (counts; the world guard holds every column to the generator).
  if (select count(*) from public.ship_classes) <> (select classes from before_0138) + 15
     or (select count(*) from public.class_profile) <> (select profiles from before_0138) + 15
     or (select count(*) from public.class_slots) <> (select slots from before_0138) + 75
     or (select count(*) from public.class_cabins) <> (select cabins from before_0138) + 15
     or (select count(*) from public.hull_recipes) <> (select recipes from before_0138) + 15
     or (select count(*) from public.hull_recipe_goods) <> (select recipe_goods from before_0138) + 60
     or (select count(*) from public.hull_recipe_items) <> (select recipe_items from before_0138)
     or (select count(*) from public.skill_requirements where subject_kind = 'hull') <> (select hull_requirements from before_0138) + 56
     or (select count(*) from public.skill_requirements where subject_kind = 'item') <> (select item_requirements from before_0138) then
    raise exception '0138 self-assert FAIL: the catalogue counts are not the pre-image plus the generated rows (classes %, hull requirements %)',
      (select count(*) from public.ship_classes), (select count(*) from public.skill_requirements where subject_kind = 'hull');
  end if;
  select count(*) into v_bad from public.ship_classes c
   where not exists (select 1 from public.class_profile p where p.class_code = c.code)
      or not exists (select 1 from public.class_cabins x where x.class_code = c.code)
      or not exists (select 1 from public.hull_recipes x where x.class_code = c.code)
      or not exists (select 1 from public.hull_recipe_goods x where x.class_code = c.code)
      or not exists (select 1 from public.class_slots x where x.class_code = c.code);
  if v_bad <> 0 then
    raise exception '0138 self-assert FAIL: % hull(s) lack a profile, cabins, recipe, materials or racks', v_bad;
  end if;
  -- the 15 are sizes 5 and 6 only: eleven capitals, one per line; four flagships, PRT ESP ENG OTT
  if (select count(*) from public.class_profile p where p.class_code not in (select code from live_classes_0138) and p.size = 5) <> 11
     or (select count(distinct p.line_code) from public.class_profile p where p.class_code not in (select code from live_classes_0138) and p.size = 5) <> 11
     or (select string_agg(p.line_code, ',' order by p.line_code) from public.class_profile p
          where p.class_code not in (select code from live_classes_0138) and p.size = 6) is distinct from 'ENG,ESP,OTT,PRT'
     or exists (select 1 from public.class_profile p where p.class_code not in (select code from live_classes_0138) and p.size not in (5, 6))
     or exists (select 1 from public.class_profile p where p.class_code in (select code from live_classes_0138) and p.size > 4) then
    raise exception '0138 self-assert FAIL: the new hulls are not 11 capitals (one per line) and 4 flagships (PRT ESP ENG OTT), or a size-5/6 hull existed before';
  end if;

  -- (c) THE HULL RULES over every class: guns = attack / 10; tier = least(size, 5); Hands = crew_max −
  --     ⌈crew_required / 2⌉ ≥ 0; yard tier by size (3 from medium up); the new hulls T1 and own-country.
  select count(*), string_agg(c.code, ',' order by c.code) into v_bad, v_list
    from public.ship_classes c join public.class_profile p on p.class_code = c.code
    join public.hull_recipes hr on hr.class_code = c.code
   where c.guns * 10 <> c.attack or c.tier <> least(p.size, 5)
      or c.crew_max - (c.crew_required + 1) / 2 < 0
      or hr.yard_tier <> case p.size when 1 then 1 when 2 then 2 else 3 end
      or (c.code not in (select code from live_classes_0138) and (p.tech <> 'T1' or p.any_yard));
  if v_bad <> 0 then
    raise exception '0138 self-assert FAIL: % class(es) break guns = attack / 10, tier = least(size, 5), the Hands budget, the yard tier by size or T1 / own-country: %', v_bad, v_list;
  end if;

  -- (d) 0072 (b)(c)(d) OVER EVERY HULL — and (d) is THE SHED ASSERT (§8 S14, §10 risk 3), NOT loosened:
  --     every material SOLD somewhere; build yards of tier 1 and of tier 3 both exist; every hull's
  --     goods fit the storage of a yard where it can be built (its tier and its line's countries).
  select count(*), string_agg(distinct g.code, ',') into v_bad, v_list
    from public.hull_recipe_goods hg join public.goods g on g.id = hg.good_id
   where not exists (select 1 from public.port_goods pg join public.ports p on p.id = pg.port_id
                      where pg.good_id = hg.good_id and public.port_offers(p.id, hg.good_id));
  if v_bad <> 0 then
    raise exception '0138 self-assert FAIL: % hull material(s) are sold in NO city: %', v_bad, v_list;
  end if;
  if not exists (select 1 from public.port_buildings where kind = 'building_yard' and tier = 1)
     or not exists (select 1 from public.port_buildings where kind = 'building_yard' and tier >= 3) then
    raise exception '0138 self-assert FAIL: the build yards'' tiers no longer differ';
  end if;
  select count(*), string_agg(x.class_code || ' ' || x.tons || ' t', ', ' order by x.class_code) into v_bad, v_list from (
    select hr.class_code, sum(hg.qty * g.bulk) as tons
      from public.hull_recipes hr
      join public.hull_recipe_goods hg on hg.class_code = hr.class_code
      join public.goods g on g.id = hg.good_id
     group by hr.class_code) x
   where x.tons > coalesce((select max(public.storage_cap(b.port_id)) from public.port_buildings b
                             join public.hull_recipes hr on hr.class_code = x.class_code
                            where b.kind = 'building_yard' and b.tier >= hr.yard_tier
                              and public.yard_wrong_country(b.port_id, x.class_code) is null), 0);
  if v_bad <> 0 then
    raise exception '0138 self-assert FAIL: % hull(s) want more than any storage where they can be built holds: %', v_bad, v_list;
  end if;
  -- the receipt prints each new hull's tonnage against its biggest shed
  select string_agg(x.class_code || ' ' || round(x.tons) || '/' || x.shed, ', ' order by x.class_code) into v_shed from (
    select hr.class_code, sum(hg.qty * g.bulk) as tons,
           (select max(public.storage_cap(b.port_id)) from public.port_buildings b
             where b.kind = 'building_yard' and b.tier >= hr.yard_tier
               and public.yard_wrong_country(b.port_id, hr.class_code) is null) as shed
      from public.hull_recipes hr
      join public.hull_recipe_goods hg on hg.class_code = hr.class_code
      join public.goods g on g.id = hg.good_id
     where hr.class_code not in (select code from live_classes_0138)
     group by hr.class_code) x;

  -- (e) EVERY HULL IS BUILDABLE AT ≥ 1 YARD OF ITS LINE — by the ONE yard rule (yard_wrong_country) and
  --     the tier, and the yard screen there agrees (tier_ok, no wrong_yard).
  select count(*), string_agg(c.code, ',' order by c.code) into v_bad, v_list
    from public.ship_classes c join public.hull_recipes hr on hr.class_code = c.code
   where not exists (select 1 from public.port_buildings b
                      where b.kind = 'building_yard' and b.tier >= hr.yard_tier
                        and public.yard_wrong_country(b.port_id, c.code) is null);
  if v_bad <> 0 then
    raise exception '0138 self-assert FAIL: % hull(s) can be built at no yard of their line: %', v_bad, v_list;
  end if;
  select count(*), string_agg(y.key, ',') into v_bad, v_list
    from jsonb_each_text(v_p->'yards') y
   where y.value is null
      or not exists (select 1 from yards_after_0138 a where a.port_id = y.value::uuid and a.class = y.key
                       and (a.entry->>'tier_ok')::boolean and a.entry->>'wrong_yard' is null);
  if v_bad <> 0 or (select count(*) from jsonb_each_text(v_p->'yards')) <> 15 then
    raise exception '0138 self-assert FAIL: the yard screen does not open % new hull(s) at the yard the rule names: %', v_bad, v_list;
  end if;

  -- (f) PLACES GROW WITH THE SIZE (0074 (c), over every hull, now through size 6): every hull of a size
  --     carries more places than every hull of the size below; cabins grow with it.
  select count(*) into v_bad from generate_series(1, 5) s
   where (select max(t) from (select sum(cs.count) t from public.class_slots cs join public.class_profile p on p.class_code = cs.class_code
                               where p.size = s group by cs.class_code) x)
      >= (select min(t) from (select sum(cs.count) t from public.class_slots cs join public.class_profile p on p.class_code = cs.class_code
                               where p.size = s + 1 group by cs.class_code) x)
      or (select max(cc.cabins) from public.class_cabins cc join public.class_profile p on p.class_code = cc.class_code where p.size = s)
      >= (select min(cc.cabins) from public.class_cabins cc join public.class_profile p on p.class_code = cc.class_code where p.size = s + 1);
  if v_bad <> 0 then
    raise exception '0138 self-assert FAIL: places or cabins do not grow with the size (% step(s))', v_bad;
  end if;

  -- (g) THE REQUIREMENTS, by §4.4: a capital X Heavy IV + X Capital I + Command III + role III; a
  --     flagship X Capital V + Fleet Command I + role V; the line's own hull skills, nothing else.
  select count(*), string_agg(c.code, ',' order by c.code) into v_bad, v_list
    from public.ship_classes c join public.class_profile p on p.class_code = c.code
   where c.code not in (select code from live_classes_0138)
     and (select string_agg(r.skill_code || ':' || r.level, ',' order by r.skill_code)
            from public.skill_requirements r where r.subject_kind = 'hull' and r.subject_code = c.code)
         is distinct from
         (select string_agg(x.skill || ':' || x.lvl, ',' order by x.skill) from (
            select * from (values
              (5, p.line_code || '_HEAVY', 4), (5, p.line_code || '_CAPITAL', 1), (5, 'COMMAND', 3),
              (5, case p.role when 'trade' then 'MERCHANT_SHIPS' when 'combat' then 'SHIPS_OF_WAR'
                              when 'explorer' then 'EXPLORERS' else 'ESCORT_SUPPORT' end, 3),
              (6, p.line_code || '_CAPITAL', 5), (6, 'FLEET_COMMAND', 1),
              (6, case p.role when 'trade' then 'MERCHANT_SHIPS' when 'combat' then 'SHIPS_OF_WAR'
                              when 'explorer' then 'EXPLORERS' else 'ESCORT_SUPPORT' end, 5)) v(size, skill, lvl)
             where v.size = p.size) x);
  if v_bad <> 0 then
    raise exception '0138 self-assert FAIL: % new hull(s) do not carry §4.4''s capital / flagship requirements: %', v_bad, v_list;
  end if;
  if exists (select 1 from public.skill_requirements r where not exists (select 1 from public.skills s where s.code = r.skill_code))
     or exists (select 1 from public.skill_requirements r where r.subject_kind = 'hull' and not exists (select 1 from public.ship_classes c where c.code = r.subject_code)) then
    raise exception '0138 self-assert FAIL: a requirement row names a skill or a hull that does not exist';
  end if;

  -- (h) NO BODY, ENTRY POINT OR GRANT MOVED: the client's entry points and the write posture as found.
  if (select count(*) from public.client_rpc_entry_points()) <> (select entry_points from before_0138)
     or (select count(*) from public.client_write_grants()) <> 0
     or (select count(*) from public.client_executable_writers()) <> 0 then
    raise exception '0138 self-assert FAIL: an entry point or the write posture moved';
  end if;
  if (select value from public.world_config where key = 'hull_labour_mult') <> '1.0'::jsonb
     or exists (select 1 from public.hull_recipes hr where public.hull_labour(hr.class_code) <> hr.ducats) then
    raise exception '0138 self-assert FAIL: hull_labour_mult is not 1.0, or a hull''s labour is not its recipe''s ducats';
  end if;

  -- (i) DARK = WHAT A COMPANY CAN DO TODAY.
  --   (1) every company, every hull already in the world: the unmet requirements as before (the pre-image);
  select count(*) into v_bad
    from needs_before_0138 nb join needs_after_0138 na on na.player = nb.player and na.code = nb.code
   where na.unmet <> nb.unmet or na.met <> (nb.unmet = 0);
  if v_bad <> 0 or (select count(*) from needs_before_0138) = 0 then
    raise exception '0138 self-assert FAIL: % company / old-hull pair(s) moved (or none was checked)', v_bad;
  end if;
  --   (2) every company, every NEW hull: closed, every requirement unmet (dark: no level counts) —
  --       counted against the companies needs_after_0138 itself read (a sign-up during the push cannot
  --       move either side);
  select count(*) into v_bad from needs_after_0138 na
   where not na.old
     and (na.met or na.unmet <> (select count(*) from public.skill_requirements r where r.subject_kind = 'hull' and r.subject_code = na.code));
  select count(*) into v_new from needs_after_0138 na where not na.old and not na.met;
  if v_bad <> 0 or v_new <> 15 * (select count(distinct player) from needs_after_0138) or v_new = 0 then
    raise exception '0138 self-assert FAIL: % company / new-hull pair(s) open dark; % closed, expected 15 × every company', v_bad, v_new;
  end if;
  --   (3) the yard screens: every old hull's entry at every yard = the pre-image; every new hull's entry
  --       not buildable, its `needs` the rule's sentence with the dark reason;
  select count(*) into v_yards from public.port_buildings where kind = 'building_yard';
  select count(*), string_agg(distinct b.class, ',') into v_bad, v_list
    from yards_before_0138 b
    left join yards_after_0138 a on a.port_id = b.port_id and a.class = b.class
   where a.entry is distinct from b.entry;
  if v_bad <> 0 or (select count(*) from yards_before_0138) <> v_old * v_yards or v_yards = 0 then
    raise exception '0138 self-assert FAIL: % old-hull yard entr(ies) moved (%), or the yards were not all read', v_bad, v_list;
  end if;
  select count(*) into v_bad from yards_after_0138 a
   where a.class not in (select code from live_classes_0138)
     and ((a.entry->>'buildable')::boolean or a.entry->>'needs' is null
          or position(' needs ' in a.entry->>'needs') = 0
          or position('ship skills are not in use yet' in a.entry->>'needs') = 0);
  if v_bad <> 0 or (select count(*) from yards_after_0138) <> (v_old + 15) * v_yards then
    raise exception '0138 self-assert FAIL: % new-hull yard entr(ies) are buildable or carry no needs sentence, dark', v_bad;
  end if;
  --   (4) the probe, through the door: every new hull refused E_NEEDS_SKILL dark at a yard of its line
  --       with everything to hand, with the dark reason; a barca built at Lisbon for 3,000 as before.
  select count(*), string_agg(e.key || ' ' || e.value, '; ') into v_bad, v_list
    from jsonb_each_text(v_p->'dark') e
   where split_part(e.value, ':', 1) <> 'E_NEEDS_SKILL' or position('ship skills are not in use yet' in e.value) = 0;
  if v_bad <> 0 or (select count(*) from jsonb_object_keys(v_p->'dark')) <> 15 then
    raise exception '0138 self-assert FAIL: dark, % new hull(s) were not refused E_NEEDS_SKILL with the dark reason: %', v_bad, v_list;
  end if;
  if v_p->>'dark_barca' <> 'ok:3000' then
    raise exception '0138 self-assert FAIL: dark, a barca at Lisbon answered % (expected built for 3,000)', v_p->>'dark_barca';
  end if;

  -- (j) LIT (rolled back): with no skills every new hull is refused naming EVERY requirement (Command /
  --     Fleet Command among them); with the skills every one is BUILT through the door, paying exactly
  --     its labour (the flagships' shed share included).
  select count(*), string_agg(e.key || ' ' || e.value, '; ') into v_bad, v_list
    from jsonb_each_text(v_p->'lit0') e
   where split_part(e.value, ':', 1) <> 'E_NEEDS_SKILL'
      or position('ship skills are not in use yet' in e.value) <> 0
      or (v_p->'unmet0'->>e.key)::int <> (select count(*) from public.skill_requirements r where r.subject_kind = 'hull' and r.subject_code = e.key);
  if v_bad <> 0 or (select count(*) from jsonb_object_keys(v_p->'lit0')) <> 15 then
    raise exception '0138 self-assert FAIL: lit without skills, % new hull(s) not refused with every requirement: %', v_bad, v_list;
  end if;
  select count(*), string_agg(e.key || ' ' || e.value, '; ') into v_bad, v_list
    from jsonb_each_text(v_p->'lit') e
    join public.hull_recipes hr on hr.class_code = e.key
   where e.value <> 'ok:' || hr.ducats;
  if v_bad <> 0 or (select count(*) from jsonb_object_keys(v_p->'lit')) <> 15 then
    raise exception '0138 self-assert FAIL: lit with the skills, % new hull(s) were not built for their labour: %', v_bad, v_list;
  end if;
  if public.skills_bite_on()
     or exists (select 1 from public.players where auth_uid = '00000000-0138-4000-8000-000000000001') then
    raise exception '0138 self-assert FAIL: the probe world was not rolled back (skills_bite or the company remain)';
  end if;

  -- (k) THE SERVED CATALOGUE: the snapshot serves every class with line, size, role and tech; each old
  --     class's entry is its pre-image.
  select count(*) into v_bad from jsonb_array_elements(world.snapshot()->'ship_classes') s
   where s->>'line' is null or s->>'size' is null or s->>'role' is null or s->>'tech' is null;
  if v_bad <> 0 or jsonb_array_length(world.snapshot()->'ship_classes') <> v_old + 15 then
    raise exception '0138 self-assert FAIL: the snapshot does not serve % classes with line / size / role / tech', v_old + 15;
  end if;
  select count(*) into v_bad from snapshot_before_0138 sb
   where (select s from jsonb_array_elements(world.snapshot()->'ship_classes') s where s->>'code' = sb.code)
         is distinct from sb.entry;
  if v_bad <> 0 or (select count(*) from snapshot_before_0138) <> v_old then
    raise exception '0138 self-assert FAIL: % old class(es) are served differently in the snapshot', v_bad;
  end if;

  -- (l) THE HOT READS: answers EQUAL (a hard refusal). The time is REPORTED, not gated.
  for rb in select * from reads_0138 where phase = 'before' loop
    select * into ra from reads_0138 where phase = 'after' and what = rb.what;
    v_timing := v_timing || format('%s %s ms → %s ms (%s%%, n %s); ', rb.what, rb.ms, ra.ms,
                                   case when rb.ms > 0 then to_char(round((ra.ms - rb.ms) / rb.ms * 100, 1), 'FMS990.0') else 'n/a' end,
                                   rb.n);
    if ra.answer is distinct from rb.answer then
      raise exception '0138 self-assert FAIL: the % answers moved', rb.what;
    end if;
  end loop;
  raise notice '0138 hot reads, faster of two passes, at production''s planner page cost 1.1 (this engine''s own: %), before → after (reported, not gated): %',
    current_setting('random_page_cost'), v_timing;
  if (select count(*) from reads_0138 where phase = 'after') <> 4 or (select n from reads_0138 where phase = 'before' and what = 'quotes') = 0 then
    raise exception '0138 self-assert FAIL: the hot reads were not all timed';
  end if;

  raise notice '0138 self-assert ok: CAPITALS AND FLAGSHIPS. UNTOUCHED: the % hulls already in the world (class, profile, racks, cabins, recipe, requirements), every item and effect, the unlocks and the constraints hash as before. LANDED: +15 classes / profiles / cabins / recipes (11 capitals, one per line; 4 flagships, PRT ESP ENG OTT), +75 rack rows, +60 hull materials, +56 hull requirements (capital: Heavy IV + Capital I + Command III + role III; flagship: Capital V + Fleet Command I + role V) — the world guard holds every column to scripts/build-ships.mjs. RULES: guns = attack / 10, tier = least(size, 5), Hands ≥ 0, yard tier 3, T1 and own-country; places and cabins grow with the size through 6. THE SHED (0072 (d), not loosened): every hull''s goods fit a storage where it can be built — new hulls t/shed: %. BUILDABLE at ≥ 1 yard of its line, the yard screen agrees. DARK (today): % company / old-hull pairs as before; % company / new-hull pairs closed; the yards serve every old hull as before (% entries) and every new hull closed with its needs sentence; through the door 15 refused E_NEEDS_SKILL, a barca built for 3,000. LIT (rolled back): no skills → 15 refused naming every requirement; with the skills → 15 BUILT, each paying its labour. No body, entry point or grant moved; the snapshot serves % classes, the old ones as before. HOT READS (equal answers; time reported, not gated): %. Rolled back.',
    v_old, v_shed, (select count(*) from needs_before_0138), v_new, (select count(*) from yards_before_0138), v_old + 15, v_timing;
end $$;
