--     the line's own goods). The VALUES below are the generator's `--sql B` output, pasted.
-- (2) IT FITS IN THE SHED (§8 S14's rule; 0072 (d) NOT loosened): where a hull's goods exceed the
--     shed, the generator scales every quantity down to fit (floored, proportions kept) and moves the
--     value taken out — each good at the middle of its baseValue band, §4.2's "≈ market" — into the
--     yard's labour, rounded up to 500. The four flagships: 1,071 t → 749 t; labour carraca 150,000 →
--     168,000, galeón real 187,000 → 205,000, Great Ship 178,500 → 197,000, Baştarda-i Hümayun
--     170,000 → 184,000. The eleven capitals (666-714 t) fit as drafted.
-- (3) THE REQUIREMENTS (§4.4) — 56 hull rows: a capital needs X Heavy Hulls IV, X Capital Hulls I,
--     Command III and the role skill III (11 × 4); a flagship X Capital Hulls V, Fleet Command I and
--     the role skill V (4 × 3).
--
-- ── WHAT IT DELIBERATELY DOES NOT DO ────────────────────────────────────────────────────────────
-- No function body is re-cut: the one rule (public.requirements_unmet, dark since 0135) already
-- refuses a subject WITH requirements while skills_bite is off, so the 15 are closed to everyone
-- today — E_NEEDS_SKILL, every skill named, " — ship skills are not in use yet". No row of the 55
-- hulls already in the world moves (hashed); no item, effect, knob, table, entry point, client write,
-- cron or FK. Merchants: nothing (they sail the live three). Said plainly, the felt change while dark:
-- the Codex and the build yard list 70 hulls, the 15 new ones refused with their needs.
--
-- ── COST (the hot reads must not get slower) ───────────────────────────────────────────────────
-- Nothing on a hot path is re-cut; ship_classes grows 55 → 70, class_slots +75, class_profile /
-- class_cabins / hull_recipes +15. As 0135 does, the self-assert times every merchant hull's speed +
-- hold, ship_stats and ship_view and a grid of quotes BEFORE the rows land and AFTER (after an ANALYZE
-- of the grown tables), faster of two passes, AT PRODUCTION'S PLANNER PAGE COST (random_page_cost
