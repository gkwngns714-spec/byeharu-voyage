-- ── 4. THE PROBE (its own company, rolled back whole) ──────────────────────────────────────────
-- Every new hull at a build yard of its line, its goods ashore and money enough, through the one door:
-- DARK (refused, every one), LIT with no skills (refused, naming every requirement), LIT with the skills
-- (built, paying hull_labour); and a live barca dark at Lisbon (built, 3,000 as before).
create or replace function pg_temp.probe_0138()
returns jsonb
language plpgsql
as $$
declare
  c_uid    constant uuid := '00000000-0138-4000-8000-000000000001';
  v_player uuid;
  v_fleet  uuid;
  v_lis    uuid;
  v_out    jsonb := '{}'::jsonb;
  v_dark   jsonb := '{}'::jsonb;
  v_lit0   jsonb := '{}'::jsonb;
  v_lit    jsonb := '{}'::jsonb;
  v_unmet0 jsonb := '{}'::jsonb;
  h        record;
begin
  begin
    v_player := public.new_house(c_uid, 'Casa da Prova 0138', 'PRT');
    select id, port_id into v_fleet, v_lis from public.fleets where player_id = v_player;
    perform public.credit(v_player, 'PROBE_0138', 100000000);
    create temp table if not exists probe_yards_0138 (class text primary key, yard uuid, ducats bigint) on commit drop;
    delete from probe_yards_0138;
    insert into probe_yards_0138
    select c.code,
           (select b.port_id from public.port_buildings b join public.ports p on p.id = b.port_id
             where b.kind = 'building_yard' and b.tier >= hr.yard_tier
               and public.yard_wrong_country(b.port_id, c.code) is null
             order by b.tier desc, p.code limit 1),
           hr.ducats
      from public.ship_classes c join public.hull_recipes hr on hr.class_code = c.code
     where c.code not in (select code from live_classes_0138);
    -- the goods of every new hull, ashore at its yard (each build is undone, so the most any one wants)
    insert into public.player_storage (player_id, port_id, good_id, qty)
    select v_player, y.yard, hg.good_id, max(hg.qty)
      from probe_yards_0138 y join public.hull_recipe_goods hg on hg.class_code = y.class
     where y.yard is not null
     group by y.yard, hg.good_id
    on conflict (player_id, port_id, good_id) do update set qty = excluded.qty;

    -- DARK
    for h in select * from probe_yards_0138 where yard is not null order by class loop
      v_dark := v_dark || jsonb_build_object(h.class, pg_temp.try_build_0138(v_player, v_fleet, h.class, h.yard));
    end loop;
    -- a live barca at Lisbon, with its goods and fittings to hand, as any company builds it today
    insert into public.player_storage (player_id, port_id, good_id, qty)
    select v_player, v_lis, hg.good_id, hg.qty from public.hull_recipe_goods hg where hg.class_code = 'barca'
    on conflict (player_id, port_id, good_id) do update set qty = greatest(public.player_storage.qty, excluded.qty);
    insert into public.player_items (player_id, port_id, item_code, qty)
    select v_player, v_lis, hi.item_code, hi.qty from public.hull_recipe_items hi where hi.class_code = 'barca'
    on conflict (player_id, port_id, item_code) do update set qty = excluded.qty;
    v_out := v_out || jsonb_build_object('dark_barca', pg_temp.try_build_0138(v_player, v_fleet, 'barca', v_lis));

    -- LIT, no skills
    update public.world_config set value = 'true'::jsonb where key = 'skills_bite';
    for h in select * from probe_yards_0138 where yard is not null order by class loop
      v_lit0 := v_lit0 || jsonb_build_object(h.class, pg_temp.try_build_0138(v_player, v_fleet, h.class, h.yard));
      v_unmet0 := v_unmet0 || jsonb_build_object(h.class, (select count(*) from public.requirements_unmet(v_player, 'hull', h.class)));
    end loop;

    -- LIT, with every hull and role skill, Command and Fleet Command at V
    insert into public.player_skills (player_id, skill_id, level)
    select v_player, sk.id, 5 from public.skills sk join public.skill_profile pr on pr.skill_id = sk.id
     where pr.group_code = 'HULLS'
        or sk.code in ('MERCHANT_SHIPS', 'SHIPS_OF_WAR', 'EXPLORERS', 'ESCORT_SUPPORT', 'COMMAND', 'FLEET_COMMAND')
    on conflict (player_id, skill_id) do update set level = excluded.level;
    for h in select * from probe_yards_0138 where yard is not null order by class loop
      v_lit := v_lit || jsonb_build_object(h.class, pg_temp.try_build_0138(v_player, v_fleet, h.class, h.yard));
    end loop;

    v_out := v_out || jsonb_build_object('dark', v_dark, 'lit0', v_lit0, 'unmet0', v_unmet0, 'lit', v_lit,
                                         'yards', (select jsonb_object_agg(class, yard) from probe_yards_0138));
    raise exception 'PROBE_ROLLBACK_0138';
  exception when others then
    if sqlerrm <> 'PROBE_ROLLBACK_0138' then raise; end if;
  end;
  return v_out;
end $$;

