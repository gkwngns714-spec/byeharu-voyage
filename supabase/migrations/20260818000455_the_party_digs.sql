  execute $f$
create function public.land_progress(p_party uuid, p_at timestamptz)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $body$
-- 0455: THE SUM (docs/design/land-2026-11.md 6.5), cap and all. With e the real seconds since the job's clock began, stopped at the cap:
--   trip = 2 (s + m) + p a;  trips = floor(e / trip) (home);  u = e - trips trip;  in packs = min(p, floor((u - s - m) / a)), never below 0;
--   turns home = trips p.  The cap: e stops at land_away_hours after the last press, or at the end of the first trip if that is later.
-- Called home (terms.home_at): the turns booked, and its packs (terms.carry) once home_at has passed. Where the party is falls out of the
-- same figures: out (passage out), march, digging, back (march home), in (passage home), returning, home. Writes nothing.
declare
  lp      public.land_parties%rowtype;
  t       jsonb;
  v_trip  numeric;
  v_stop  timestamptz;
  v_e     numeric;
  v_trips bigint;
  v_u     numeric;
  v_s     numeric;
  v_m     numeric;
  v_a     numeric;
  v_p     int;
  v_pack  int;
  v_phase text;
begin
  select * into lp from public.land_parties x where x.id = p_party;
  if lp.id is null then
    return null;
  end if;
  if lp.action is null then
    return jsonb_build_object('state', 'home', 'phase', 'home', 'turns', 0, 'new', 0, 'in_packs', 0, 'waiting', lp.waiting);
  end if;
  t := lp.terms;
  v_s := (t ->> 's')::numeric; v_m := (t ->> 'm')::numeric; v_a := (t ->> 'a')::numeric; v_p := (t ->> 'p')::int;
  v_trip := (t ->> 'trip')::numeric;
  if t ? 'home_at' then
    return jsonb_build_object('state', 'returning', 'phase', case when p_at >= (t ->> 'home_at')::timestamptz then 'home' else 'returning' end,
      'turns', lp.booked + case when p_at >= (t ->> 'home_at')::timestamptz then (t ->> 'carry')::int else 0 end,
      'new', case when p_at >= (t ->> 'home_at')::timestamptz then (t ->> 'carry')::int else 0 end,
      'in_packs', (t ->> 'carry')::int, 'home_at', t ->> 'home_at', 'trip', v_trip, 'stopped', false, 'waiting', lp.waiting);
  end if;
  v_stop := greatest(lp.touched_at + make_interval(secs => public.wc_num('land_away_hours') * 3600),
                     lp.started_at + make_interval(secs => v_trip));
  v_e := greatest(0, extract(epoch from least(p_at, v_stop) - lp.started_at));
  v_trips := floor(v_e / v_trip);
  v_u := v_e - v_trips * v_trip;
  v_pack := greatest(0, least(v_p, floor((v_u - v_s - v_m) / v_a)))::int;
  v_phase := case when v_u < v_s then 'out' when v_u < v_s + v_m then 'march' when v_u < v_s + v_m + v_p * v_a then 'digging'
                  when v_u < v_s + 2 * v_m + v_p * v_a then 'back' else 'in' end;
  return jsonb_build_object('state', 'out', 'phase', v_phase,
    'turns', v_trips * v_p, 'new', greatest(0, v_trips * v_p - lp.booked), 'trips', v_trips, 'in_packs', v_pack, 'u', v_u, 'trip', v_trip,
    'next_home_at', case when p_at < v_stop then lp.started_at + make_interval(secs => (v_trips + 1) * v_trip) end,
    'stopped', p_at >= v_stop, 'stop_at', v_stop, 'waiting', lp.waiting);
end
$body$
  $f$;

  -- ── 6. THE ONE WRITER ──
  execute $f$
create function public.land_settle(p_party uuid, p_at timestamptz)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $body$
-- 0455: THE ONE WRITER of everything a land job earns. Books the turns that have come home and are not booked (public.land_progress):
-- goods through public.storage_put at a cost of 0 into the Storage of the party's own harbour (what does not fit waits with the party,
-- and the job ends there: a party with a haul waiting is not sent again); a chance of a second unit a turn while company was there at
-- Send (voyage.rng by party, turn and Send: the same instant gives the same goods); experience into xp_due, booked through
-- public.level_grant at most once in land_book_minutes (key land:<party>:<instant>, so a booking pays once). A party past its cap
-- waits where it stopped: its clock is moved on by the wait, so it goes on from there. A party called home is home at terms.home_at.
-- Every land door calls this first. A merchant has no party.
declare
  lp      public.land_parties%rowtype;
  g       public.goods%rowtype;
  v_pr    jsonb;
  v_new   int := 0;
  v_units int := 0;
  v_put   int := 0;
  v_fit   numeric;
  v_xp    int := 0;
  v_book  int := 0;
  v_crowd numeric;
  v_end   boolean := false;
begin
  select * into lp from public.land_parties x where x.id = p_party for update;
  if lp.id is null then
    return null;
  end if;
  -- what waited for room: as much as fits now
  if lp.waiting > 0 then
    select * into g from public.goods where id = lp.waiting_good;
    v_fit := floor(greatest(public.storage_cap(lp.port_id) - public.storage_used(lp.player_id, lp.port_id), 0) / g.bulk);
    v_put := least(lp.waiting, v_fit)::int;
    if v_put > 0 then
      perform public.storage_put(lp.player_id, lp.port_id, g.id, v_put, 0);
      lp.waiting := lp.waiting - v_put;
      if lp.waiting = 0 then lp.waiting_good := null; end if;
    end if;
  end if;
  if lp.action is not null then
    v_pr := public.land_progress(lp.id, p_at);
    v_new := (v_pr ->> 'new')::int;
    if v_new > 0 then
      select * into g from public.goods where id = (lp.terms ->> 'good')::uuid;
      v_crowd := coalesce((lp.terms ->> 'crowd')::numeric, 0);
      v_units := v_new + case when v_crowd > 0 then
                   (select count(*)::int from generate_series(lp.booked + 1, lp.booked + v_new) n
                     where voyage.rng(lp.id, n, 'land:' || (lp.terms ->> 'sent')) < v_crowd / 100) else 0 end;
      v_fit := floor(greatest(public.storage_cap(lp.port_id) - public.storage_used(lp.player_id, lp.port_id), 0) / g.bulk);
      v_put := least(v_units, greatest(v_fit, 0))::int;
      if v_put > 0 then
        perform public.storage_put(lp.player_id, lp.port_id, g.id, v_put, 0);
      end if;
      if v_units > v_put then
        lp.waiting := lp.waiting + (v_units - v_put);
        lp.waiting_good := g.id;
        v_end := true;
      end if;
      lp.booked := lp.booked + v_new;
      lp.xp_due := lp.xp_due + v_new * (lp.terms ->> 'xp')::int;
    end if;
    if v_pr ->> 'state' = 'returning' and v_pr ->> 'phase' = 'home' then
      v_end := true;
    elsif v_pr ->> 'state' = 'out' and (v_pr ->> 'stopped')::boolean then
      -- it waited where it stopped: its clock moves on by the wait, so it goes on from there after this press
      lp.started_at := lp.started_at + (p_at - (v_pr ->> 'stop_at')::timestamptz);
    end if;
  end if;
  -- the experience: at most once in land_book_minutes
  if lp.xp_due > 0 and (lp.xp_booked_at is null or p_at >= lp.xp_booked_at + make_interval(mins => public.wc_int('land_book_minutes'))) then
    v_book := public.level_grant(lp.player_id, 'dig', lp.xp_due, 'land:' || lp.id || ':' || floor(extract(epoch from p_at) * 1000)::bigint);
    v_xp := lp.xp_due;
    lp.xp_due := 0;
    lp.xp_booked_at := p_at;
  end if;
  update public.land_parties
     set action = case when v_end then null else lp.action end,
         terms = case when v_end then null else lp.terms end,
         region_id = case when v_end then null else lp.region_id end,
         started_at = case when v_end then null else lp.started_at end,
         booked = case when v_end then 0 else lp.booked end,
         touched_at = p_at,
         xp_due = lp.xp_due, xp_booked_at = lp.xp_booked_at, waiting = lp.waiting, waiting_good = lp.waiting_good
   where id = lp.id;
  return jsonb_build_object('turns', v_new, 'units', v_put, 'waiting', lp.waiting, 'xp', v_xp, 'xp_booked', v_book,
                            'good', (select gg.code from public.goods gg where gg.id = g.id), 'ended', v_end);
end
$body$
  $f$;

  execute $f$
