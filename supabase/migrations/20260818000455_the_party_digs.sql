set search_path = public, pg_temp
as $body$
  -- 0455: THE ONE READING of "how far is that land". If the region of p_port is one the good comes from (public.goods.origin_regions):
  -- that region, no passage. Else the nearest harbour of a region that is, by the sailed miles the quay quotes (voyage.reach_from over
  -- public.sea_reaches), and its seconds at land_passage_seconds_per_nm. Null: no such land can be reached from p_port.
