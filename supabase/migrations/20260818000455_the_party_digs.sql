create function public.land_home_for(p_player uuid, p_at timestamptz)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $body$
-- 0455: CALL HOME. Settles, then ends the job: the party turns back where it is with what is in its packs. On its way out it walks back
-- what it has walked (and sails back what it has sailed); digging, it walks the march and sails the passage; already on its way home, it
-- finishes that way. It is home at terms.home_at and its packs are booked at the first press after. Home already: nothing to do.
declare
  v_party uuid;
  lp      public.land_parties%rowtype;
  v_pr    jsonb;
  v_u     numeric;
  v_s     numeric;
  v_m     numeric;
  v_a     numeric;
  v_p     int;
  v_back  numeric;
  v_carry int;
begin
  if not public.land_on() then
    perform cmd.refuse('E_NOT_IN_USE', 'the land is not open yet');
  end if;
  v_party := public.land_party(p_player);
  perform public.land_settle(v_party, p_at);
  select * into lp from public.land_parties x where x.id = v_party;
  if lp.action is null or lp.terms ? 'home_at' then
    return jsonb_build_object('ok', true, 'home_at', coalesce(lp.terms ->> 'home_at', p_at::text));
  end if;
  v_pr := public.land_progress(v_party, p_at);
  v_u := (v_pr ->> 'u')::numeric;
  v_s := (lp.terms ->> 's')::numeric; v_m := (lp.terms ->> 'm')::numeric; v_a := (lp.terms ->> 'a')::numeric; v_p := (lp.terms ->> 'p')::int;
  if v_u < v_s + v_m then
    v_back := v_u; v_carry := 0;
  elsif v_u < v_s + v_m + v_p * v_a then
    v_back := v_s + v_m; v_carry := (v_pr ->> 'in_packs')::int;
  else
    v_back := (v_pr ->> 'trip')::numeric - v_u; v_carry := v_p;
  end if;
  update public.land_parties
     set terms = terms || jsonb_build_object('home_at', p_at + make_interval(secs => v_back), 'carry', v_carry)
   where id = v_party;
  return jsonb_build_object('ok', true, 'home_at', p_at + make_interval(secs => v_back), 'carry', v_carry);
end
