      raise exception '0455 self-assert FAIL: a merchant was not refused (%)', v_note;
    end if;
    v_note := format('the Land read in %s ms; a coal trip by Plymouth of 2,170 s called home with its six; an iron trip of 300 s and 864 iron in 13 hours away (Mining %s); dark every door refused',
                     v_ms, public.level_of('mining', (select x.xp from public.level_xp x where x.player_id = v_pl and x.skill = 'mining')));
    raise exception using errcode = 'ZX455', message = 'PROBE_ROLLBACK_0455';
  exception when sqlstate 'ZX455' then
    v_lived := true;
  end;
  if not v_lived or v_note not like 'the Land read%' then
    raise exception '0455 self-assert FAIL: the probe did not run to its end';
  end if;
  if exists (select 1 from public.players p where p.auth_uid in (c_uid, c_uid2) or p.company_name like 'Casa % 0455')
     or exists (select 1 from public.land_parties) or public.land_on() or public.current_player_id() is not null then
    raise exception '0455 self-assert FAIL: the probe left something behind';
  end if;
