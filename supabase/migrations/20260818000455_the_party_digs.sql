create function public.level_of(p_skill text, p_xp numeric)
returns integer
language sql
stable
security definer
set search_path = public, pg_temp
as $body$
  -- 0455: THE ONE READING of a skill's level from its experience. A short skill: public.level_from_points (to 20, untouched). A long
  -- skill: the highest level of its curve (public.level_curves) whose start is at or below the experience. An unknown skill: null.
  select case when s.curve = 'short' then public.level_from_points(p_xp)
              else coalesce((select max(c.level) from public.level_curves c where c.curve = s.curve and c.xp <= greatest(coalesce(p_xp, 0), 0)), 1) end
    from public.level_skills s where s.code = p_skill
$body$
  $f$;
  execute $f$
create function public.level_begins(p_skill text, p_level integer)
