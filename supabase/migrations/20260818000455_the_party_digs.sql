    perform public.land_collect_for(v_pl, now() + interval '2 hours');
    v_r := v_r || jsonb_build_array(cmd.land_send('platinum') ->> 'error_code');
    v_r := v_r || jsonb_build_array(cmd.land_send('no-such') ->> 'error_code');
