  -- the one cut of the sea, unchanged; a long skill's is cut by public.level_of and public.level_begins.
  select case when s.curve = 'short' then public.level_line(p_points)
              else (select jsonb_build_object('points', floor(greatest(coalesce(p_points, 0), 0)), 'level', l.lvl,
                                              'from', public.level_begins(p_skill, l.lvl), 'next_at', public.level_begins(p_skill, l.lvl + 1))
                      from (select public.level_of(p_skill, p_points) as lvl) l) end
    from public.level_skills s where s.code = p_skill
