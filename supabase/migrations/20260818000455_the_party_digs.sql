    select p.id into v_ply from public.ports p where p.code = 'PLY' and p.kind = 'HARBOUR';
    select g.id into v_iron from public.goods g where g.code = 'iron';
    select g.id into v_coal from public.goods g where g.code = 'coal';
    insert into public.players (auth_uid, company_name, nation_id, ducats, is_npc)
    values (c_uid, 'Casa Mineira 0455', (select n.id from public.nations n where n.code = 'PRT'), 2000, false) returning id into v_pl;
    insert into public.events (player_id, kind, payload) values (v_pl, 'FOUNDED', jsonb_build_object('port', 'LIS'));
    insert into public.players (auth_uid, company_name, nation_id, ducats, is_npc)
    values (null, 'Casa Mercante 0455', (select n.id from public.nations n where n.code = 'PRT'), 5000, true) returning id into v_npc;
    perform cmd.assume_identity(c_uid);

    -- (a) DARK: every door refuses, the read says enabled false and nothing else, the card serves no land skill, the snapshot says false
    v_r := jsonb_build_array(cmd.land_send('iron') ->> 'error_code', cmd.land_collect() ->> 'error_code', cmd.land_home() ->> 'error_code',
                             cmd.land_tool('plain-pick') ->> 'error_code');
    if v_r <> '["E_NOT_IN_USE", "E_NOT_IN_USE", "E_NOT_IN_USE", "E_NOT_IN_USE"]'::jsonb or world.land('mining') <> '{"enabled": false}'::jsonb
       or exists (select 1 from public.land_parties lp where lp.player_id = v_pl)
       or exists (select 1 from jsonb_array_elements(public.level_skills_card(v_pl, '{}'::jsonb) -> 'skills') s where s ->> 'code' = 'mining')
       or (world.snapshot() -> 'config' ->> 'land_enabled')::boolean is distinct from false then
      raise exception '0455 self-assert FAIL: dark, a door opened or the land was served: %', v_r;
    end if;

    -- lit, inside the probe only
    update public.world_config set value = 'true'::jsonb where key = 'land_enabled';
    if not exists (select 1 from jsonb_array_elements(public.level_skills_card(v_pl, '{}'::jsonb) -> 'skills') s
                    where s ->> 'code' = 'mining' and (s ->> 'top')::int = 100 and jsonb_array_length(s -> 'curve') = 100 and (s ->> 'level')::int = 1) then
      raise exception '0455 self-assert FAIL: lit, the card does not serve Mining on its long curve';
    end if;

    -- (b) THE FAR SITE first, at Mining 1: Sea Coal from Lisbon is by Plymouth, the British Isles, 760.2 miles, 950 s;
    --     a trip of 6 is 2 x (950 + 15) + 6 x 40 = 2,170 s
    v_r := public.land_passage(v_lis, v_coal);
    if v_r ->> 'via' <> 'PLY' or v_r ->> 'region' <> 'BRI' or (v_r ->> 'nm')::numeric <> 760.2 or (v_r ->> 'seconds')::int <> 950 then
      raise exception '0455 self-assert FAIL: the coal passage from Lisbon is not Plymouth, 760.2 miles, 950 s: %', v_r;
    end if;
    v_t := now() - interval '3 days';
    v_r := public.land_send_for(v_pl, 'coal', v_t);
    select lp.id into v_party from public.land_parties lp where lp.player_id = v_pl;
    if (v_r ->> 'ok')::boolean is not true or (select (lp.terms ->> 'trip')::int from public.land_parties lp where lp.id = v_party) <> 2170
       or (select lp.port_id from public.land_parties lp where lp.id = v_party) <> v_lis
       or (public.land_progress(v_party, v_t + interval '949 seconds') ->> 'phase') <> 'out'
       or (public.land_progress(v_party, v_t + interval '966 seconds') ->> 'phase') <> 'digging'
       or (public.land_progress(v_party, v_t + interval '966 seconds') ->> 'in_packs')::int <> 0
       or (public.land_progress(v_party, v_t + interval '1006 seconds') ->> 'in_packs')::int <> 1
       or (public.land_progress(v_party, v_t + interval '2169 seconds') ->> 'turns')::int <> 0
       or (public.land_progress(v_party, v_t + interval '2170 seconds') ->> 'turns')::int <> 6 then
      raise exception '0455 self-assert FAIL: the far trip''s sum is not the design''s at 949, 966, 1006, 2169 and 2170 s: % %', v_r,
        (select lp.terms from public.land_parties lp where lp.id = v_party);
    end if;
    -- the party is on the British Isles' list while it is out, and never on Iberia's
    if (select count(*) from public.land_parties lp where lp.region_id = (select r.id from public.regions r where r.code = 'BRI') and lp.player_id = v_pl) <> 1
       or (select count(*) from public.land_parties lp where lp.region_id = (select r.id from public.regions r where r.code = 'IBE') and lp.player_id = v_pl) <> 0 then
      raise exception '0455 self-assert FAIL: a party on a far trip is not on that land''s list';
    end if;
    -- called home on the way back from its first trip's digging, at 2,000 s: it carries its six and is home 170 s later
    v_r := public.land_home_for(v_pl, v_t + interval '2000 seconds');
    if (v_r ->> 'carry')::int <> 6 or (v_r ->> 'home_at')::timestamptz <> v_t + interval '2170 seconds' then
      raise exception '0455 self-assert FAIL: called home on its way back, the party does not carry its packs home on time: %', v_r;
    end if;
    v_r := public.land_collect_for(v_pl, v_t + interval '2170 seconds');
    if (v_r ->> 'units')::int <> 6
       or (select ps.qty from public.player_storage ps where ps.player_id = v_pl and ps.port_id = v_lis and ps.good_id = v_coal) <> 6
       or exists (select 1 from public.player_storage ps where ps.player_id = v_pl and ps.port_id = v_ply)
       or (select lp.action from public.land_parties lp where lp.id = v_party) is not null then
      raise exception '0455 self-assert FAIL: the far haul did not land in Lisbon''s Storage alone, or the job did not end: %', v_r;
    end if;

    -- (c) THE HOME SITE: Iron from Lisbon has no passage; a trip of 6 is 15 + 6 x 45 + 15 = 300 s (Mining 2: 0.2 % of 45 s rounds away)
    v_t := now() - interval '2 days';
    perform public.land_send_for(v_pl, 'iron', v_t);
    v_s := (select lp.terms from public.land_parties lp where lp.id = v_party);
    if (v_s ->> 's')::int <> 0 or (v_s ->> 'm')::int <> 15 or (v_s ->> 'a')::int <> 45 or (v_s ->> 'trip')::int <> 300 or (v_s ->> 'p')::int <> 6
       or (select r.code from public.land_parties lp join public.regions r on r.id = lp.region_id where lp.id = v_party) <> 'IBE' then
      raise exception '0455 self-assert FAIL: an iron Send from Lisbon is not a 300-s trip on Iberia''s land: %', v_s;
    end if;
    if (public.land_progress(v_party, v_t) ->> 'phase') <> 'march'
       or (public.land_progress(v_party, v_t + interval '14 seconds') ->> 'phase') <> 'march'
       or (public.land_progress(v_party, v_t + interval '16 seconds') ->> 'phase') <> 'digging'
       or (public.land_progress(v_party, v_t + interval '16 seconds') ->> 'in_packs')::int <> 0
       or (public.land_progress(v_party, v_t + interval '61 seconds') ->> 'in_packs')::int <> 1
       or (public.land_progress(v_party, v_t + interval '299 seconds') ->> 'turns')::int <> 0
       or (public.land_progress(v_party, v_t + interval '300 seconds') ->> 'turns')::int <> 6
       or (public.land_progress(v_party, v_t + interval '12 hours') ->> 'turns')::int <> 144 * 6
       or (public.land_progress(v_party, v_t + interval '13 hours') ->> 'turns')::int <> 144 * 6 then
      raise exception '0455 self-assert FAIL: the home site''s sum is not the design''s at 0, 14, 16, 61, 299, 300 s, 12 h and 13 h';
    end if;
    -- a Collect at 13 h books what 12 h gives, 864 iron, into Lisbon's Storage at a cost of 0, and the experience; a second at the same
    -- instant books nothing
    v_x := (select x.xp from public.level_xp x where x.player_id = v_pl and x.skill = 'mining');
    v_r := public.land_collect_for(v_pl, v_t + interval '13 hours');
    v_s := public.land_collect_for(v_pl, v_t + interval '13 hours');
    if (v_r ->> 'units')::int <> 864 or (v_r ->> 'xp')::int <> 864 * 4 or (v_s ->> 'units')::int <> 0 or (v_s ->> 'xp')::int <> 0
       or (select ps.qty from public.player_storage ps where ps.player_id = v_pl and ps.port_id = v_lis and ps.good_id = v_iron) <> 864
       or (select ps.basis from public.player_storage ps where ps.player_id = v_pl and ps.port_id = v_lis and ps.good_id = v_iron) <> 0
       or (select x.xp from public.level_xp x where x.player_id = v_pl and x.skill = 'mining') <> v_x + 3456 then
      raise exception '0455 self-assert FAIL: a Collect did not book 12 hours of iron and its experience once: % then %', v_r, v_s;
    end if;
    perform public.land_home_for(v_pl, v_t + interval '13 hours');
    perform public.land_collect_for(v_pl, v_t + interval '14 hours');

    -- (d) THE READ, lit: the jobs, the far good's land; measured
    v_t := clock_timestamp();
    v_r := world.land('mining');
    v_ms := round(extract(epoch from clock_timestamp() - v_t) * 1000, 1);
    if jsonb_array_length(v_r -> 'jobs') <> 57 or (v_r ->> 'company')::boolean is not true
       or (select j ->> 'via' from jsonb_array_elements(v_r -> 'jobs') j where j ->> 'code' = 'coal') <> 'PLY'
       or (select (j ->> 'home')::boolean from jsonb_array_elements(v_r -> 'jobs') j where j ->> 'code' = 'iron') is not true
       or (select (j ->> 'open')::boolean from jsonb_array_elements(v_r -> 'jobs') j where j ->> 'code' = 'platinum') is not false then
      raise exception '0455 self-assert FAIL: the Land read is not the jobs as the catalogue and her level say: %', v_r -> 'party';
    end if;

