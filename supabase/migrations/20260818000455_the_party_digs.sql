create function public.land_send_for(p_player uuid, p_action text, p_at timestamptz)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $body$
-- 0455: SEND. Settles, then starts the job with its terms frozen (public.land_terms) and its clock at p_at. Refused: dark
-- (E_NOT_IN_USE), a merchant, no such job (E_NO_SUCH_JOB), the party out (E_LAND_OUT: call it home first), a haul waiting for room
-- (E_SHED_FULL), the level short (E_NEEDS_SKILL, have / need), no land of it within reach (E_OUT_OF_REACH).
declare
  v_party uuid;
  lp      public.land_parties%rowtype;
  t       jsonb;
begin
  if not public.land_on() then
    perform cmd.refuse('E_NOT_IN_USE', 'the land is not open yet');
  end if;
  v_party := public.land_party(p_player);
  perform public.land_settle(v_party, p_at);
  select * into lp from public.land_parties x where x.id = v_party;
  if not exists (select 1 from public.land_actions a where a.code = p_action) then
    perform cmd.refuse('E_NO_SUCH_JOB', format('there is no job called "%s"', coalesce(p_action, '')));
  end if;
  if lp.action is not null then
    perform cmd.refuse('E_LAND_OUT', 'the party is out; call it home first');
  end if;
  if lp.waiting > 0 then
    perform cmd.refuse('E_SHED_FULL', 'a haul waits for room in Storage: sell, ship or use some first');
  end if;
  t := public.land_terms(p_player, p_action);
  if t -> 'short' is not null and jsonb_typeof(t -> 'short') = 'object' then
    perform cmd.refuse(t -> 'short');
  end if;
  update public.land_parties
     set action = p_action, region_id = (t ->> 'region_id')::uuid, started_at = p_at, touched_at = p_at, booked = 0,
         terms = (t - 'short' - 'have' - 'region' - 'over_cap') || jsonb_build_object('sent', floor(extract(epoch from p_at) * 1000)::bigint)
   where id = v_party;
  return jsonb_build_object('ok', true, 'action', p_action, 'trip', t -> 'trip', 'home_at', p_at + make_interval(secs => (t ->> 'trip')::numeric));
end
$body$
