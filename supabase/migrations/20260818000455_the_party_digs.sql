create function public.land_terms(p_player uuid, p_action text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $body$
-- 0455: WHAT A SEND WOULD DO, and whether it may: the terms frozen at Send, and the Send tray's one source. a: seconds a turn (the job's,
-- over land_yield_pct, less land_level_speed_pct a level above 1, less the best owned tool of the job's kind); m: the site's march;
-- s: the passage each way (public.land_passage; 0 at home); p: the packs; xp: experience a turn; crowd: the chance of a second unit a
-- turn, land_crowd_pct for each other company working that land now, to land_crowd_max; trip = 2 (s + m) + p a. `short` is the refusal
-- a Send would meet (E_NEEDS_SKILL, E_OUT_OF_REACH), else null. Null: no such job, or no company.
declare
  j       public.land_actions%rowtype;
  v_party public.land_parties%rowtype;
  v_port  uuid;
  v_xp    int;
  v_lvl   int;
  v_pass  jsonb;
  v_tool  numeric;
  v_a     int;
  v_m     int;
  v_s     int;
  v_p     int;
  v_crowd numeric;
  v_short jsonb;
begin
  select * into j from public.land_actions a where a.code = p_action;
  if j.code is null then
    return null;
  end if;
  select * into v_party from public.land_parties lp where lp.player_id = p_player and lp.ord = 1;
  v_port := coalesce(v_party.port_id, public.home_port_of(p_player));
  if v_port is null then
    return null;
  end if;
  v_xp := coalesce((select x.xp from public.level_xp x where x.player_id = p_player and x.skill = j.skill), 0);
  v_lvl := public.level_of(j.skill, v_xp);
  v_pass := public.land_passage(v_port, j.good_id);
  v_tool := coalesce((select max(t.speed_pct) from public.land_tools t where t.tool = j.tool and t.code = any(coalesce(v_party.tools, '{}'))), 0);
  v_a := greatest(1, round(j.seconds * 100.0 / public.wc_num('land_yield_pct')
                           * (1 - public.wc_num('land_level_speed_pct') / 100 * (v_lvl - 1))
                           * (1 - v_tool / 100)))::int;
  v_m := coalesce((select s.march_seconds from public.land_sites s where s.region_id = (v_pass ->> 'region_id')::uuid and s.ground = j.ground), 0);
  v_s := coalesce((v_pass ->> 'seconds')::int, 0);
  v_p := public.wc_int('land_pack_base');
  v_crowd := least(public.wc_num('land_crowd_max'),
                   public.wc_num('land_crowd_pct') * (select count(*) from public.land_parties o
                                                       where o.region_id = (v_pass ->> 'region_id')::uuid and o.action is not null and o.player_id <> p_player));
  if v_lvl < j.level then
    v_short := cmd.refusal('E_NEEDS_SKILL', format('needs Mining %s', j.level), cmd.figures(v_lvl, j.level, 'level'));
  elsif v_pass is null then
    v_short := cmd.refusal('E_OUT_OF_REACH', 'no harbour of a land that holds it can be reached from home');
  end if;
  return jsonb_build_object(
    'action', j.code, 'skill', j.skill, 'good', j.good_id, 'level', j.level, 'have', v_lvl,
    'a', v_a, 'm', v_m, 's', v_s, 'p', v_p, 'xp', j.xp, 'crowd', v_crowd,
    'trip', 2 * (v_s + v_m) + v_p * v_a,
    'over_cap', 2 * (v_s + v_m) + v_p * v_a > public.wc_num('land_away_hours') * 3600,
    'home', coalesce((v_pass ->> 'home')::boolean, false), 'region_id', v_pass ->> 'region_id', 'region', v_pass ->> 'region',
    'via', v_pass ->> 'via', 'nm', (v_pass ->> 'nm')::numeric, 'tool', v_tool,
    'short', v_short);
end
$body$
