security definer
set search_path = public, pg_temp
as $body$
-- 0458: BUY THE NEXT MULE, paid to the party's home city (public.pay_city, kind LAND: money moved, nothing made). More packs from the next
-- Send. Refused: dark (E_NOT_IN_USE), a merchant, every mule bought (E_TOP_GRADE), a short purse (E_INSUFFICIENT_FUNDS, from public.credit).
declare
  v_party uuid;
  lp      public.land_parties%rowtype;
  k       jsonb;
  v_after bigint;
begin
  if not public.land_on() then
    perform cmd.refuse('E_NOT_IN_USE', 'the land is not open yet');
  end if;
  v_party := public.land_party(p_player);
  perform public.land_settle(v_party, now());
  select * into lp from public.land_parties x where x.id = v_party for update;
  k := public.wc('land_packs') -> lp.mules;
  if k is null then
    perform cmd.refuse('E_TOP_GRADE', 'the party has every mule');
  end if;
  v_after := public.pay_city(p_player, lp.port_id, 'LAND', (k ->> 'price')::bigint);
  update public.land_parties set mules = mules + 1 where id = v_party;
  return jsonb_build_object('ok', true, 'mules', lp.mules + 1, 'packs', public.land_packs_of(lp.mules + 1), 'price', (k ->> 'price')::bigint, 'purse', v_after);
end
