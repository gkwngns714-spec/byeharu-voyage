-- 0458: REPEAT on or off. Settles first. Off: the next Send is one trip; a party out finishes the trip under way and comes home (terms.last).
-- On: a party out goes on again by itself (until the away cap, as before). A party called home stays called home. Refused: dark, a merchant,
-- no answer (E_BAD_ORDER).
declare
  v_party uuid;
  lp      public.land_parties%rowtype;
begin
  if not public.land_on() then
    perform cmd.refuse('E_NOT_IN_USE', 'the land is not open yet');
  end if;
  if p_on is null then
    perform cmd.refuse('E_BAD_ORDER', 'say on or off');
  end if;
  v_party := public.land_party(p_player);
  perform public.land_settle(v_party, p_at);
  select * into lp from public.land_parties x where x.id = v_party for update;
  update public.land_parties set repeat_on = p_on where id = v_party;
  if lp.action is not null and not (lp.terms ? 'home_at') then
    if p_on then
      update public.land_parties set terms = terms - 'last' where id = v_party;
    elsif not (lp.terms ? 'last') then
      update public.land_parties set terms = terms || jsonb_build_object('last', coalesce((public.land_progress(v_party, p_at) ->> 'trips')::int, 0) + 1)
       where id = v_party;
    end if;
  end if;
  return jsonb_build_object('ok', true, 'repeat', p_on);
end
