          <> '["amber", "baltic-amber"]'::jsonb then
      raise exception '0458 self-assert FAIL: the finds are not the land''s: Lisbon % / the Baltic %',
        public.land_terms(v_pl, 'lead') -> 'finds', public.land_terms(v_pl2, 'lead') -> 'finds';
    end if;
    -- the Baltic party digs lead twelve hours, Repeat on, the top mule: the finds are the dice's, booked in two presses as in one
    perform public.land_send_for(v_pl2, 'lead', c_t);
    v_trip := (select (lp.terms ->> 'trip')::numeric from public.land_parties lp where lp.id = c_bp);
    v_turns := (public.land_progress(c_bp, c_t + interval '12 hours') ->> 'turns')::int;
    select count(*) filter (where z.r < 0.01), count(*) filter (where z.r >= 0.01 and z.r < 0.02) into v_amber, v_bamber
      from generate_series(1, v_turns) n
      cross join lateral (select voyage.rng(c_bp, n, 'find:' || (select lp.terms ->> 'sent' from public.land_parties lp where lp.id = c_bp)) as r) z;
    v_r := public.land_collect_for(v_pl2, c_t + interval '5 hours');
    v_s := public.land_collect_for(v_pl2, c_t + interval '12 hours');
    v_x := coalesce((v_r -> 'found' ->> 'amber')::int, 0) + coalesce((v_s -> 'found' ->> 'amber')::int, 0);
    if v_amber + v_bamber = 0 or v_x <> v_amber
       or coalesce((v_r -> 'found' ->> 'baltic-amber')::int, 0) + coalesce((v_s -> 'found' ->> 'baltic-amber')::int, 0) <> v_bamber
       or coalesce((select ps.qty from public.player_storage ps join public.goods g on g.id = ps.good_id where ps.player_id = v_pl2 and ps.port_id = v_bal and g.code = 'amber'), 0) <> v_amber
       or coalesce((select ps.qty from public.player_storage ps join public.goods g on g.id = ps.good_id where ps.player_id = v_pl2 and ps.port_id = v_bal and g.code = 'baltic-amber'), 0) <> v_bamber
       or coalesce((select ps.basis from public.player_storage ps join public.goods g on g.id = ps.good_id where ps.player_id = v_pl2 and ps.port_id = v_bal and g.code = 'amber' and ps.qty > 0), 0) <> 0 then
      raise exception '0458 self-assert FAIL: the finds booked (% then %) are not the dice''s (amber %, baltic amber %, of % turns)', v_r -> 'found', v_s -> 'found', v_amber, v_bamber, v_turns;
    end if;
    v_note := v_note || format('; the Baltic''s lead, 30 packs, %s turns in 12 h: %s amber and %s baltic amber found and booked', v_turns, v_amber, v_bamber);

    -- (f) THE READ serves the mules, Repeat and the finds
    perform cmd.assume_identity(c_uid2);
    v_r := world.land('mining');
    if (v_r -> 'party' ->> 'mules')::int <> 4 or (v_r -> 'party' ->> 'repeat')::boolean is not true or (v_r -> 'packs' ->> 'now')::int <> 30
       or v_r -> 'packs' -> 'next' <> 'null'::jsonb
       or (select jsonb_array_length(j -> 'finds') from jsonb_array_elements(v_r -> 'jobs') j where j ->> 'code' = 'lead') <> 2 then
      raise exception '0458 self-assert FAIL: the Land read does not serve the mules, Repeat or the finds: % %', v_r -> 'party', v_r -> 'packs';
    end if;
    raise exception using errcode = 'ZX458', message = 'PROBE_ROLLBACK_0458';
  exception when sqlstate 'ZX458' then
    v_lived := true;
  end;
  if not v_lived or v_note not like 'guard:%' then
    raise exception '0458 self-assert FAIL: the probe did not run to its end';
  end if;
  if exists (select 1 from public.players p where p.auth_uid in (c_uid, c_uid2) or p.company_name like 'Casa % 0458')
     or exists (select 1 from public.land_parties lp where lp.id = c_bp) or public.land_on() or public.current_player_id() is not null then
    raise exception '0458 self-assert FAIL: the probe left something behind';
  end if;
  if clock_timestamp() - v_t0 > interval '15 seconds' then
    raise exception '0458 self-assert FAIL: the file took % (budget 15 s)', clock_timestamp() - v_t0;
  end if;
  raise notice '0458 self-assert ok: MULES, REPEAT AND RARE FINDS, DARK. % finds over the jobs; five new functions, fifteen hunks over seven bodies, each once and reversing; land_enabled false, land_yield_pct 100. Probe (rolled back): %. In all % ms.',
    (select count(*) from public.land_drops), v_note, round(extract(epoch from clock_timestamp() - v_t0) * 1000);
end
