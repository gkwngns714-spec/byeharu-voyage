// PURE UNIT SPEC — THE LAND'S JOBS ARE THE RULE'S (migration 0455, docs/design/land-2026-11.md 6.3). No browser, no server.
//   * the VALUES block 0455 carries between its marker lines is exactly scripts/build-land-migration.mjs's output: the rows cannot drift
//     from the ladder and the rule by a hand edit;
//   * Mining is all 57 minerals of the catalogue, each once, each a good that comes from somewhere, ordered by the level it asks;
//   * the rule holds where the design worked it by hand: Iron 45 s and 4 experience at level 1, Sea Coal and Clay at the 40-s floor;
//     no job is under 40 s; an hour of a job at its level is worth about 4,800 coin at level 1 and about 15,000 at 100.

import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import path from 'node:path'
import { LADDERS, landRows, valuesBlock, worthAt } from '../scripts/build-land-migration.mjs'

const MIG = readFileSync(path.resolve('supabase', 'migrations', '20260818000455_the_party_digs.sql'), 'utf8').replaceAll('\r', '')
const GOODS = (JSON.parse(readFileSync(path.resolve('data', 'goods.json'), 'utf8')) as { goods: Array<{ id: string; origin: string[]; baseValue: [number, number] }> }).goods

test('0455 carries exactly the generator\'s rows', () => {
  const a = '      -- BEGIN generated by scripts/build-land-migration.mjs (do not edit by hand)\n'
  const b = '\n      -- END generated by scripts/build-land-migration.mjs'
  const i = MIG.indexOf(a)
  const j = MIG.indexOf(b)
  expect(i, 'the BEGIN marker').toBeGreaterThan(0)
  expect(j, 'the END marker').toBeGreaterThan(i)
  expect(MIG.slice(i + a.length, j)).toBe(valuesBlock())
})

test('Mining is the 57 minerals of the catalogue, each once, by level', () => {
  const rows = landRows().filter((r) => r.skill === 'mining')
  expect(rows).toHaveLength(57)
  expect(new Set(rows.map((r) => r.code)).size).toBe(57)
  const byId = new Map(GOODS.map((g) => [g.id, g]))
  for (const r of rows) expect(byId.get(r.code)?.origin.length ?? 0, r.code).toBeGreaterThan(0)
  const levels = LADDERS.mining.goods.map(([l]) => l)
  expect([...levels].sort((x, y) => x - y)).toEqual(levels)
  expect(levels[0]).toBe(1)
  expect(levels[levels.length - 1]).toBeLessThanOrEqual(100)
})

test('the rule: the design\'s hand-worked rows, the floor, the worth of an hour', () => {
  const rows = new Map(landRows().map((r) => [r.code, r]))
  expect(rows.get('iron')).toMatchObject({ level: 1, seconds: 45, xp: 4 })
  expect(rows.get('coal')).toMatchObject({ level: 1, seconds: 40, xp: 3 })
  expect(rows.get('clay')).toMatchObject({ level: 1, seconds: 40, xp: 3 })
  const byId = new Map(GOODS.map((g) => [g.id, g]))
  for (const r of rows.values()) {
    expect(r.seconds, r.code).toBeGreaterThanOrEqual(40)
    const base = (byId.get(r.code)!.baseValue[0] + byId.get(r.code)!.baseValue[1]) / 2
    // an hour of the job is worth the level's worth, within the 5-s rounding, unless the 40-s floor holds it below
    if (r.seconds > 40) expect(Math.abs((3600 / r.seconds) * base - worthAt(r.level)) / worthAt(r.level), r.code).toBeLessThan(0.07)
  }
  expect(worthAt(1)).toBe(4800)
  expect(worthAt(100)).toBe(15000)
})
