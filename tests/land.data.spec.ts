test('Smithing is 21 made goods of the catalogue, by level, each inside THE GUARD at the fastest make pace', () => {
  const byId = new Map(GOODS.map((g) => [g.id, g]))
  const rows = smithRows()
  expect(rows).toHaveLength(21)
  expect(new Set(rows.map((r) => r.code)).size).toBe(21)
  const levels = MAKERS.smithing.goods.map(([l]) => l)
  expect([...levels].sort((x, y) => x - y)).toEqual(levels)
  expect(levels[0]).toBe(1)
  expect(FASTEST_MAKE.toolPct).toBe(0)
  expect(FASTEST_MAKE.crowdMaxPct).toBe(0)
  for (const r of rows) {
    expect(byId.get(r.code), r.code).toBeTruthy()
    expect(r.kind).toBe('make')
    expect(r.seconds, r.code).toBeGreaterThanOrEqual(40)
    expect(fastestHour(r.seconds, FASTEST_MAKE), `${r.code}: the guard`).toBeLessThanOrEqual(GUARD[r.code].target / 100)
    expect(r.xp, r.code).toBe(Math.max(1, Math.round((r.seconds / 60) * payAt(r.level))))
  }
  // the smith's goods are no Mining good: one job a good
  for (const r of rows) expect(LADDERS.mining.goods.some(([, c]) => c === r.code), r.code).toBe(false)
})

test('0461 makes no tool: the plain pick stays the fastest, so the Mining guard pace is unmoved', () => {
  expect(FASTEST.toolPct).toBe(3)
  expect(/insert into public\.land_tools/i.test(MIG61)).toBe(false)
})

test('0531 carries exactly the generator\'s wood: raw goods that come from somewhere, by level, inside the market guard', () => {
  const mig = readFileSync(path.resolve('supabase', 'migrations', '20260818000531_woodcutting.sql'), 'utf8').replaceAll('\r', '')
  const a = '      -- BEGIN wood generated by scripts/build-land-migration.mjs --wood (do not edit by hand)\n'
  const i = mig.indexOf(a)
  const j = mig.indexOf('\n      -- END wood generated by')
  expect(i, 'the BEGIN marker').toBeGreaterThan(0)
  expect(mig.slice(i + a.length, j)).toBe(woodBlock())
  const rows = woodRows()
  expect(rows).toHaveLength(31)
  expect(new Set(rows.map((r) => r.code)).size).toBe(31)
  const mined = new Set(landRows().map((r) => r.code))
  let last = 0
  for (const r of rows) {
    expect(mined.has(r.code), `${r.code} is mined too`).toBe(false)
    expect(GOODS.find((g) => g.id === r.code)?.origin.length ?? 0, r.code).toBeGreaterThan(0)
    expect(r.level).toBeGreaterThanOrEqual(last)
    last = r.level
    expect(r.seconds).toBeGreaterThanOrEqual(40)
    expect(fastestHour(r.seconds, FASTEST_WOOD), r.code).toBeLessThanOrEqual(GUARD[r.code].target / 100)
  }
})
