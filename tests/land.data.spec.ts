// PURE UNIT SPEC — THE LAND'S JOBS ARE THE RULE'S (migrations 0455 and 0457, docs/design/land-2026-11.md 5.8, 6.3). No browser, no server.
//   * the VALUES block 0457 (the newest land rows) carries between its marker lines is exactly scripts/build-land-migration.mjs's
//     output: the rows cannot drift from the ladder and the rule by a hand edit;
//   * Mining is all 57 minerals of the catalogue, each once, each a good that comes from somewhere, ordered by the level it asks;
//   * the rule: no job under 40 s; a job neither the floor nor the guard holds back is worth about 4,800 coin an hour at level 1 to
//     15,000 at 100; THE MARKET GUARD (5.8 rule 2): at the fastest pace, a party-hour is at most a hundredth of the least middling
//     harbour target of the regions the good comes from (data/land-guard.generated.json).
//   * 0458 (L1c): the finds block 0458 carries is exactly the generator's (--drops); a find is a gem of the ladder on one of the job's
//     lands, never the job's own good; THE GUARD holds with every mule (the top one, at the least march) and for every find against
//     its own good's target; 0458's land_packs knob is the generator's MULES.

import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import path from 'node:path'
import {
  FIND_ONE_IN,
  LADDERS,
  MULES,
  dropRows,
  dropsBlock,
  fastestFindsHour,
  fastestHour,
  fastestHourPacked,
  landRows,
  valuesBlock,
  worthAt,
} from '../scripts/build-land-migration.mjs'

const MIG = readFileSync(path.resolve('supabase', 'migrations', '20260818000457_the_land_keeps_the_market_guard.sql'), 'utf8').replaceAll('\r', '')
const GUARD = (JSON.parse(readFileSync(path.resolve('data', 'land-guard.generated.json'), 'utf8')) as { goods: Record<string, { target: number }> }).goods
const GOODS = (JSON.parse(readFileSync(path.resolve('data', 'goods.json'), 'utf8')) as { goods: Array<{ id: string; origin: string[]; baseValue: [number, number]; category: string }> }).goods
const MIG58 = readFileSync(path.resolve('supabase', 'migrations', '20260818000458_mules_repeat_and_rare_finds.sql'), 'utf8').replaceAll('\r', '')

test('0457 carries exactly the generator\'s rows', () => {
  const a = '      -- BEGIN generated by scripts/build-land-migration.mjs (do not edit by hand)\n'
  const b = '\n      -- END generated by scripts/build-land-migration.mjs'
  const i = MIG.indexOf(a)
  const j = MIG.indexOf(b)
  expect(i, 'the BEGIN marker').toBeGreaterThan(0)
  expect(j, 'the END marker').toBeGreaterThan(i)
  expect(MIG.slice(i + a.length, j)).toBe(valuesBlock())
})

test('Mining is the 57 minerals of the catalogue, each once, by level', () => {
  const rows = landRows().filter((r) => r.skill === 'mining')
  expect(rows).toHaveLength(57)
  expect(new Set(rows.map((r) => r.code)).size).toBe(57)
  const byId = new Map(GOODS.map((g) => [g.id, g]))
  for (const r of rows) expect(byId.get(r.code)?.origin.length ?? 0, r.code).toBeGreaterThan(0)
  const levels = LADDERS.mining.goods.map(([l]) => l)
  expect([...levels].sort((x, y) => x - y)).toEqual(levels)
  expect(levels[0]).toBe(1)
  expect(levels[levels.length - 1]).toBeLessThanOrEqual(100)
})

test('the rule: the floor, the worth of an hour, and the market guard', () => {
  const rows = landRows()
  const byId = new Map(GOODS.map((g) => [g.id, g]))
  for (const r of rows) {
    expect(r.seconds, r.code).toBeGreaterThanOrEqual(40)
    const base = (byId.get(r.code)!.baseValue[0] + byId.get(r.code)!.baseValue[1]) / 2
    const target = GUARD[r.code].target
    // the guard: at the fastest pace, a party-hour is at most a hundredth of the target
    expect(fastestHour(r.seconds), `${r.code}: the guard`).toBeLessThanOrEqual(target / 100)
    const guarded = fastestHour(r.seconds - 5) > target / 100
    // a job the guard did not slow, above the floor: an hour is the level's worth, within the 5-s rounding
    if (!guarded && r.seconds > 40) expect(Math.abs((3600 / r.seconds) * base - worthAt(r.level)) / worthAt(r.level), r.code).toBeLessThan(0.07)
  }
  // the guard bites where L1 measured it: the cheap goods every region has are slow; iron and coal are not at their old 45 s and 40 s
  const by = new Map(rows.map((r) => [r.code, r]))
  for (const c of ['sand', 'clay', 'stone', 'lime']) expect(by.get(c)!.seconds, c).toBeGreaterThan(3600)
  expect(by.get('iron')!.seconds).toBeGreaterThan(45)
  expect(worthAt(1)).toBe(4800)
  expect(worthAt(100)).toBe(15000)
})

test('0458 carries exactly the generator finds, and its mules are the generator MULES', () => {
  const a = '      -- BEGIN drops generated by scripts/build-land-migration.mjs --drops (do not edit by hand)\n'
  const b = '\n      -- END drops generated by scripts/build-land-migration.mjs --drops'
  const i = MIG58.indexOf(a)
  const j = MIG58.indexOf(b)
  expect(i, 'the BEGIN marker').toBeGreaterThan(0)
  expect(j, 'the END marker').toBeGreaterThan(i)
  expect(MIG58.slice(i + a.length, j)).toBe(dropsBlock())
  const knob = /\('land_packs', '([^']+)'::jsonb/.exec(MIG58)
  expect(JSON.parse(knob![1])).toEqual(MULES)
  expect(MULES.map((m) => m.packs)).toEqual([10, 15, 20, 30])
  expect(MULES.map((m) => m.price)).toEqual([3000, 8000, 20000, 50000])
})

test('a find is a gem of the ladder on the land of its job, never its own good', () => {
  const byId = new Map(GOODS.map((g) => [g.id, g]))
  const drops = dropRows()
  expect(drops.length).toBeGreaterThan(0)
  for (const d of drops) {
    expect(byId.get(d.good)?.category, d.good).toBe('gems')
    expect(d.good).not.toBe(d.action)
    expect(LADDERS.mining.goods.some(([, c]) => c === d.good), d.good).toBe(true)
    expect(byId.get(d.good)!.origin.some((r) => byId.get(d.action)!.origin.includes(r)), `${d.action} ${d.good}`).toBe(true)
    expect(d.one_in).toBeGreaterThanOrEqual(FIND_ONE_IN)
  }
})

test('THE GUARD holds with every mule and for every find', () => {
  const rows = landRows()
  const by = new Map(rows.map((r) => [r.code, r]))
  for (const r of rows) {
    const target = GUARD[r.code].target
    for (const m of MULES) {
      // a march only slows a party: with any packs an hour stays under the turn's bound, and so under the hundredth
      expect(fastestHourPacked(r.seconds, m.packs, 15), `${r.code} ${m.packs}`).toBeLessThan(fastestHour(r.seconds))
      expect(fastestHourPacked(r.seconds, m.packs, 15), `${r.code} ${m.packs}`).toBeLessThanOrEqual(target / 100)
    }
  }
  for (const d of dropRows()) {
    expect(fastestFindsHour(by.get(d.action)!.seconds, d.one_in), `${d.action} ${d.good}`).toBeLessThanOrEqual(GUARD[d.good].target / 100)
  }
})
