// PURE UNIT SPEC — THE LAND'S JOBS ARE THE RULE'S (migrations 0455 and 0457, docs/design/land-2026-11.md 5.8, 6.3). No browser, no server.
//   * the VALUES block 0457 (the newest land rows) carries between its marker lines is exactly scripts/build-land-migration.mjs's
//     output: the rows cannot drift from the ladder and the rule by a hand edit;
//   * Mining is all 57 minerals of the catalogue, each once, each a good that comes from somewhere, ordered by the level it asks;
//   * the rule: no job under 40 s; a job neither the floor nor the guard holds back is worth about 4,800 coin an hour at level 1 to
//     15,000 at 100; THE MARKET GUARD (5.8 rule 2): at the fastest pace, a party-hour is at most a hundredth of the least middling
//     harbour target of the regions the good comes from (data/land-guard.generated.json).
//   * 0458 (L1c): the finds block 0458 carries is exactly the generator's (--drops); a find is a gem of the ladder on one of the job's
//     lands, never the job's own good; THE GUARD holds with every mule (the top one, at the least march) and for every find against
//     its own good's target; 0458's land_packs knob is the generator's MULES.
//   * 0461 (L2, the smith): the smith block 0461 carries is exactly the generator's (--smith); 21 make jobs, each a made good of the
//     catalogue, by level; THE GUARD holds at FASTEST_MAKE against the least middling target over every region; 0461 adds no tool, so
//     Mining's guard pace (the plain pick, 3 %) is unmoved.

