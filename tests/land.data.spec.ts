test('a find is a gem of the ladder on the land of its job, never its own good', () => {
  const byId = new Map(GOODS.map((g) => [g.id, g]))
  const drops = dropRows()
  expect(drops.length).toBeGreaterThan(0)
  for (const d of drops) {
    expect(byId.get(d.good)?.category, d.good).toBe('gems')
    expect(d.good).not.toBe(d.action)
    expect(LADDERS.mining.goods.some(([, c]) => c === d.good), d.good).toBe(true)
    expect(byId.get(d.good)!.origin.some((r) => byId.get(d.action)!.origin.includes(r)), `${d.action} ${d.good}`).toBe(true)
    expect(d.one_in).toBeGreaterThanOrEqual(FIND_ONE_IN)
  }
})

test('THE GUARD holds with every mule and for every find', () => {
  const rows = landRows()
  const by = new Map(rows.map((r) => [r.code, r]))
  for (const r of rows) {
    const target = GUARD[r.code].target
    for (const m of MULES) {
      // a march only slows a party: with any packs an hour stays under the turn's bound, and so under the hundredth
      expect(fastestHourPacked(r.seconds, m.packs, 15), `${r.code} ${m.packs}`).toBeLessThan(fastestHour(r.seconds))
      expect(fastestHourPacked(r.seconds, m.packs, 15), `${r.code} ${m.packs}`).toBeLessThanOrEqual(target / 100)
    }
  }
  for (const d of dropRows()) {
    expect(fastestFindsHour(by.get(d.action)!.seconds, d.one_in), `${d.action} ${d.good}`).toBeLessThanOrEqual(GUARD[d.good].target / 100)
  }
})

