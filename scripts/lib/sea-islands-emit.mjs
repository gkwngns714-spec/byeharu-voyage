// THE HARBOURS HAVE THEIR ISLANDS — the SQL scripts/build-sea-migration.mjs emits when ISLANDS_CLOSE_WATER
// is on. It lives apart from the generator's 1,400 lines of whole-table emit because it shares none of them:
// this file moves only what the islands moved, and it mends the courses the world has stored.
//
// A stored course is a list of points somebody baked earlier, so closing water can break it two ways:
//   * the harbour's roadstead moved off its quay by 8 to 29 nm. cmd.do_sail wants a course to end within
//     course_join_nm (15 nm) of the roadstead, so 15 of the 28 would refuse E_OFF_COURSE;
//   * a line that passed through an island's cell. Beyond the 25 nm at each end it refuses E_LAND.
// Prod holds courses no generator can see (every loop a merchant has held, every player's route), so the
// mend is SQL and runs over what the table holds at apply time, not over a list made here.

export function islandsMigrationSql({ SHORT, MIGRATION, b64, moved, patch, stats, nfmt, q, j, opened, closed, newWater, islandCount }) {
  const P = []
  const out = (s = '') => P.push(s)
  const movedRows = moved
    .map(({ p, was, now }) => `    (${q(p.code)}, ${was.rlat}, ${was.rlon}, ${now.lat.toFixed(3)}, ${now.lon.toFixed(3)}, ${now.nm.toFixed(2)})`)
    .join(',\n')
  const line = '-- ' + '═'.repeat(100)
  out(line)
  out(`-- ${SHORT} — THE HARBOURS HAVE THEIR ISLANDS  (owner row 92; row 41, the fleet never touches land)`)
  out(line)
  out(`-- GENERATED by scripts/build-sea-migration.mjs with ISLANDS_CLOSE_WATER. Do not hand-edit: the raster is`)
  out(`-- scripts/sea-grid.mjs over data/world-110m.json, the mend is scripts/lib/sea-islands-emit.mjs.`)
  out(`-- File name: ${MIGRATION}. THE NUMBER IS SET AT DEPLOY (prod head + 1, in order).`)
  out(`--`)
  out(`-- THE OWNER: "some cities are in the ocean, not on land such as istanbul. I want you to fix it." and,`)
  out(`-- 2026-11-05, "some cities are in ocean, they are meant to be like that yes?"`)
  out(`--`)
  out(`-- WHAT MOVES`)
  out(`--   1. public.sea_raster: ${closed} cells closed, ${opened} opened, ${nfmt(newWater)} water cells left. The ${islandCount} islands the 110m sheet`)
  out(`--      lacked are in the land file now, and each closes every cell its drawn ring touches.`)
  out(`--   2. public.sea_reaches: ${moved.length} roadsteads move off their quays (below), and the ${nfmt(stats.changed)} of ${nfmt(stats.pairs)} pairs whose sailed`)
  out(`--      distance the islands actually changed take the new figure. Both sides are measured by TODAY's`)
  out(`--      pathfinder, old water against new, so a pair the islands did not touch keeps its figure to the tenth.`)
  out(`--      Over the changed pairs: mean ${stats.mean} nm, widest +${stats.up} / ${stats.down} nm. 0 pairs unreachable.`)
  out(`--   3. Every stored course that ends at a moved roadstead or crosses a closed cell is MENDED, here, at`)
  out(`--      apply time: public.standing_route_stops, public.npc_courses and any pending SAIL order. Its end goes`)
  out(`--      to the new roadstead and the stretch that crossed the island goes round it, cell by cell, then`)
  out(`--      straightened. The rest of the course is left point for point.`)
  out(`--   4. What is derived from the above: public.sea_leg_asks and port_goods.haul / haul_nm (world.haul_rows,`)
  out(`--      which the world guard holds equal). A longer haul lifts a price a little; a shorter one lowers it.`)
  out(`--   5. public.sea_undo_${SHORT} keeps the pre-image of all of it, for the forward rollback`)
  out(`--      (docs/dev-log/2026-11-05-islands-on-the-chart.md). Server-only.`)
  out(`--`)
  out(`-- WHAT IT DOES NOT TOUCH: public.sea_cells (a closed cell keeps its sea name, like ICE: most of the cell is`)
  out(`-- still water, nobody sails it), public.sea_zone_cells, voyage.channels, any function body, any knob.`)
  out(`-- A voyage already at sea keeps her frozen course and docks on her ETA: she may cross an island once.`)
  out(`--`)
  out(`-- THE ROADSTEADS`)
  for (const { p, was, now } of moved) {
    out(`--   ${p.code} ${p.name.padEnd(24)} (${was.rlat}, ${was.rlon}) ${Number(was.snap_nm).toFixed(2)} nm -> (${now.lat}, ${now.lon}) ${now.nm.toFixed(2)} nm`)
  }
  out(line)
  out()
  out(`-- ── THE PRE-IMAGE ──────────────────────────────────────────────────────────────────────────`)
  out(`create table public.sea_undo_${SHORT} (`)
  out(`  kind text not null check (kind in ('raster', 'reach', 'stop', 'npc_course')),`)
  out(`  ref text not null,`)
  out(`  value jsonb,`)
  out(`  bytes bytea,`)
  out(`  primary key (kind, ref)`)
  out(`);`)
  out(`comment on table public.sea_undo_${SHORT} is`)
  out(`  '${SHORT}: the sea as it stood before the harbours had their islands: the raster, every reach row, and each course this file mended. Read only by the forward rollback; drop it when the after-check has passed.';`)
  out(`alter table public.sea_undo_${SHORT} enable row level security;`)
  out(`revoke all on table public.sea_undo_${SHORT} from public, anon, authenticated;`)
  out()
  out(`insert into public.sea_undo_${SHORT} (kind, ref, bytes) select 'raster', '1', cells from public.sea_raster where id = 1;`)
  out(`insert into public.sea_undo_${SHORT} (kind, ref, value)`)
  out(`select 'reach', code, jsonb_build_object('snap_nm', snap_nm, 'lat', roadstead_lat, 'lon', roadstead_lon, 'reaches', reaches) from public.sea_reaches;`)
  out()
  out(`create temporary table sea_bits_${SHORT} on commit drop as select cells || ''::bytea as old_cells, null::bytea as new_cells from public.sea_raster where id = 1;`)
  out()
  out(`-- ── THE STORED COURSES, READ BEFORE THE WATER MOVES ────────────────────────────────────────`)
  out(`-- was_refused: a course the land guard already refused today is not this file's to answer for.`)
  out(`create temporary table mend_${SHORT} (key text primary key, old_course jsonb not null, was_refused boolean, new_course jsonb, new_nm numeric) on commit drop;`)
  out(`insert into mend_${SHORT} (key, old_course)`)
  out(`select md5(c::text), c from (`)
  out(`  select course as c from public.standing_route_stops where course is not null and jsonb_typeof(course) = 'array' and jsonb_array_length(course) >= 2`)
  out(`  union select course from public.npc_courses`)
  out(`  union select args->'path' from public.orders`)
  out(`   where status = 'pending' and verb = 'SAIL' and jsonb_typeof(args->'path') = 'array' and jsonb_array_length(args->'path') >= 2) s`)
  out(`on conflict do nothing;`)
  out(`update mend_${SHORT} set was_refused = voyage.path_refusal(old_course, (old_course->0->>0)::numeric, (old_course->0->>1)::numeric, (old_course->-1->>0)::numeric, (old_course->-1->>1)::numeric,`)
  out(`                                                  public.wc_num('course_join_nm'), 25, 25) is not null;`)
  out()
  out(`-- ── THE RASTER ─────────────────────────────────────────────────────────────────────────────`)
  out(`update public.sea_raster set cells = decode(${q(b64)}, 'base64') where id = 1;`)
  out(`update sea_bits_${SHORT} set new_cells = (select cells || ''::bytea from public.sea_raster where id = 1);`)
  out()
  out(`-- ── THE ROADSTEADS AND THE DISTANCES ───────────────────────────────────────────────────────`)
  out(`create temporary table moved_${SHORT} (code text primary key, old_lat numeric, old_lon numeric, new_lat numeric, new_lon numeric, snap_nm numeric) on commit drop;`)
  out(`insert into moved_${SHORT} values`)
  out(movedRows + ';')
  out(`update public.sea_reaches sr set roadstead_lat = m.new_lat, roadstead_lon = m.new_lon, snap_nm = m.snap_nm`)
  out(`  from moved_${SHORT} m where sr.code = m.code;`)
  out(`update public.sea_reaches sr set reaches = sr.reaches || v.patch::jsonb from (values`)
  out([...patch.entries()].sort().map(([code, keys]) => `    (${q(code)}, ${j(keys)})`).join(',\n'))
  out(`  ) as v(code, patch) where sr.code = v.code;`)
  out()
  out(`-- ── THE MEND ───────────────────────────────────────────────────────────────────────────────`)
  out(`-- The row and column are path_refusal's own arithmetic, and bit 0 of a cell is its SEA bit.`)
  out(`create function pg_temp.cell_${SHORT}(p_lat float8, p_lon float8) returns int language sql immutable as $$`)
  out(`  select least(719, greatest(0, floor((90 - p_lat) / 0.25)::int)) * 1440 + ((floor((p_lon + 180) / 0.25)::int % 1440) + 1440) % 1440`)
  out(`$$;`)
  out()
  out(`-- Is the straight line between two points water, sampled at a quarter cell? For the mend's own legs.`)
  out(`create function pg_temp.open_${SHORT}(p_cells bytea, a float8[], b float8[]) returns boolean language plpgsql as $$`)
  out(`declare v_n int := greatest(2, ceil(voyage.gc_distance_nm(a[1], a[2], b[1], b[2]) / 3.75)::int); v_s int;`)
  out(`begin`)
  out(`  for v_s in 0 .. v_n loop`)
  out(`    if get_bit(p_cells, pg_temp.cell_${SHORT}(a[1] + (b[1] - a[1]) * v_s / v_n, voyage.lon_lerp(a[2], b[2], v_s::float8 / v_n)) * 2) = 0 then return false; end if;`)
  out(`  end loop;`)
  out(`  return true;`)
  out(`end $$;`)
  out()
  out(`-- The way round: a breadth-first walk over the open cells between two water points, then straightened`)
  out(`-- by line of sight. Returns the points strictly BETWEEN a and b, as a jsonb list; null if no way is found.`)
  out(`create function pg_temp.round_${SHORT}(p_cells bytea, a float8[], b float8[]) returns jsonb language plpgsql as $$`)
  out(`declare`)
  out(`  ca int := pg_temp.cell_${SHORT}(a[1], a[2]); cb int := pg_temp.cell_${SHORT}(b[1], b[2]);`)
  out(`  ra int := ca / 1440; rb int := cb / 1440; xa int := ca % 1440; xb int := cb % 1440;`)
  out(`  v_pad int; rmin int; rmax int; xmin int; xmax int; w int; h int;`)
  out(`  prev int[]; que int[]; v_head int; v_tail int; v_at int; v_r int; v_x int; v_nr int; v_nx int; v_n int; v_goal int; v_start int; d int;`)
  out(`  dr int[] := array[-1, 1, 0, 0, -1, -1, 1, 1]; dx int[] := array[0, 0, -1, 1, -1, 1, -1, 1];`)
  out(`  v_chain float8[] := '{}'; pts float8[][]; v_len int; v_i int; v_k int; v_out jsonb := '[]';`)
  out(`begin`)
  out(`  if xb - xa > 720 then xb := xb - 1440; elsif xa - xb > 720 then xb := xb + 1440; end if;`)
  out(`  foreach v_pad in array array[16, 48, 120] loop`)
  out(`    rmin := greatest(0, least(ra, rb) - v_pad); rmax := least(719, greatest(ra, rb) + v_pad);`)
  out(`    xmin := least(xa, xb) - v_pad; xmax := greatest(xa, xb) + v_pad;`)
  out(`    w := xmax - xmin + 1; h := rmax - rmin + 1;`)
  out(`    prev := array_fill(-1, array[w * h]); que := array_fill(0, array[w * h]);`)
  out(`    v_start := (ra - rmin) * w + (xa - xmin) + 1; v_goal := (rb - rmin) * w + (xb - xmin) + 1;`)
  out(`    prev[v_start] := 0; que[1] := v_start; v_head := 1; v_tail := 1;`)
  out(`    while v_head <= v_tail and prev[v_goal] = -1 loop`)
  out(`      v_at := que[v_head]; v_head := v_head + 1;`)
  out(`      v_r := (v_at - 1) / w + rmin; v_x := (v_at - 1) % w + xmin;`)
  out(`      for d in 1 .. 8 loop`)
  out(`        v_nr := v_r + dr[d]; v_nx := v_x + dx[d];`)
  out(`        continue when v_nr < rmin or v_nr > rmax or v_nx < xmin or v_nx > xmax;`)
  out(`        v_n := (v_nr - rmin) * w + (v_nx - xmin) + 1;`)
  out(`        continue when prev[v_n] <> -1;`)
  out(`        continue when v_n <> v_goal and get_bit(p_cells, (v_nr * 1440 + ((v_nx % 1440) + 1440) % 1440) * 2) = 0;`)
  out(`        prev[v_n] := v_at; v_tail := v_tail + 1; que[v_tail] := v_n;`)
  out(`      end loop;`)
  out(`    end loop;`)
  out(`    exit when prev[v_goal] <> -1;`)
  out(`  end loop;`)
  out(`  if prev[v_goal] = -1 then return null; end if;`)
  out(`  -- the chain, as cell centres, the start and goal cells among them: the line from a sample to the next cell may not cut a corner`)
  out(`  v_at := v_goal;`)
  out(`  v_chain := array[b[1], b[2]];`)
  out(`  while v_at <> 0 loop`)
  out(`    v_r := (v_at - 1) / w + rmin; v_x := (v_at - 1) % w + xmin;`)
  out(`    v_chain := array[90 - (v_r + 0.5) * 0.25, -180 + (((v_x % 1440) + 1440) % 1440 + 0.5) * 0.25] || v_chain;`)
  out(`    v_at := prev[v_at];`)
  out(`  end loop;`)
  out(`  v_chain := array[a[1], a[2]] || v_chain;`)
  out(`  v_len := array_length(v_chain, 1) / 2;`)
  out(`  v_i := 1;`)
  out(`  while v_i < v_len loop`)
  out(`    v_k := v_len;`)
  out(`    while v_k > v_i + 1 and not pg_temp.open_${SHORT}(p_cells, array[v_chain[2 * v_i - 1], v_chain[2 * v_i]], array[v_chain[2 * v_k - 1], v_chain[2 * v_k]]) loop`)
  out(`      v_k := v_k - 1;`)
  out(`    end loop;`)
  out(`    if v_k < v_len then v_out := v_out || jsonb_build_array(jsonb_build_array(round(v_chain[2 * v_k - 1]::numeric, 4), round(v_chain[2 * v_k]::numeric, 4))); end if;`)
  out(`    v_i := v_k;`)
  out(`  end loop;`)
  out(`  return v_out;`)
  out(`end $$;`)
  out()
  out(`-- One course mended. A stretch is SHUT when its cell is closed now and was open before (p_all: every closed`)
  out(`-- cell, at a finer step, for a course a first mend left refused: the server's samples fall where they fall). Returns the course, the same value when nothing was shut,`)
  out(`-- or null when a stretch has no way round or the course begins or ends in shut water.`)
  out(`create function pg_temp.mend_${SHORT}(p_course jsonb, p_new bytea, p_old bytea, p_all boolean) returns jsonb language plpgsql as $$`)
  out(`declare`)
  out(`  v_len int := jsonb_array_length(p_course); v_i int; v_s int; v_st int; v_nm float8;`)
  out(`  lat1 float8; lon1 float8; lat2 float8; lon2 float8; f float8;`)
  out(`  dlat float8[] := '{}'; dlon float8[] := '{}'; isv boolean[] := '{}'; shut boolean[] := '{}';`)
  out(`  v_n int; v_k int; v_e int; v_c int; v_any boolean := false; v_way jsonb; v_out jsonb := '[]';`)
  out(`begin`)
  out(`  for v_i in 0 .. v_len - 2 loop`)
  out(`    lat1 := (p_course->v_i->>0)::float8; lon1 := (p_course->v_i->>1)::float8;`)
  out(`    lat2 := (p_course->(v_i + 1)->>0)::float8; lon2 := (p_course->(v_i + 1)->>1)::float8;`)
  out(`    v_nm := voyage.gc_distance_nm(lat1, lon1, lat2, lon2);`)
  out(`    v_st := greatest(1, ceil(v_nm / case when p_all then 1.25 else 3.75 end)::int);`)
  out(`    for v_s in 0 .. v_st - 1 loop`)
  out(`      f := v_s::float8 / v_st;`)
  out(`      dlat := dlat || (lat1 + (lat2 - lat1) * f); dlon := dlon || voyage.lon_lerp(lon1, lon2, f); isv := isv || (v_s = 0);`)
  out(`    end loop;`)
  out(`  end loop;`)
  out(`  dlat := dlat || lat2; dlon := dlon || lon2; isv := isv || true;`)
  out(`  v_n := array_length(dlat, 1);`)
  out(`  for v_k in 1 .. v_n loop`)
  out(`    v_c := pg_temp.cell_${SHORT}(dlat[v_k], dlon[v_k]);`)
  out(`    shut := shut || (get_bit(p_new, v_c * 2) = 0 and (p_all or get_bit(p_old, v_c * 2) = 1));`)
  out(`    v_any := v_any or shut[v_k];`)
  out(`  end loop;`)
  out(`  if not v_any then return p_course; end if;`)
  out(`  if shut[1] or shut[v_n] then return null; end if;`)
  out(`  v_k := 1;`)
  out(`  while v_k <= v_n loop`)
  out(`    if shut[v_k + 1] is true then`)
  out(`      -- v_k is the last water sample before the stretch, v_e the first after it`)
  out(`      v_e := v_k + 1;`)
  out(`      while shut[v_e] loop v_e := v_e + 1; end loop;`)
  out(`      v_way := pg_temp.round_${SHORT}(p_new, array[dlat[v_k], dlon[v_k]], array[dlat[v_e], dlon[v_e]]);`)
  out(`      if v_way is null then return null; end if;`)
  out(`      v_out := v_out || jsonb_build_array(jsonb_build_array(round(dlat[v_k]::numeric, 4), round(dlon[v_k]::numeric, 4))) || v_way;`)
  out(`      v_k := v_e;`)
  out(`      isv[v_e] := true;`)
  out(`    else`)
  out(`      if isv[v_k] then`)
  out(`        v_out := v_out || jsonb_build_array(jsonb_build_array(round(dlat[v_k]::numeric, 4), round(dlon[v_k]::numeric, 4)));`)
  out(`      end if;`)
  out(`      v_k := v_k + 1;`)
  out(`    end if;`)
  out(`  end loop;`)
  out(`  return v_out;`)
  out(`end $$;`)
  out()
  out(`-- The last step over a mended course: drop every vertex a straight line over open water can skip, looking`)
  out(`-- 12 vertices ahead. A kept leg is not re-judged, so this can shorten a course and never break one.`)
  out(`create function pg_temp.tidy_${SHORT}(p_course jsonb, p_new bytea) returns jsonb language plpgsql as $$`)
  out(`declare v_n int := jsonb_array_length(p_course); v_i int := 0; v_k int; v_out jsonb := jsonb_build_array(p_course->0);`)
  out(`begin`)
  out(`  while v_i < v_n - 1 loop`)
  out(`    v_k := least(v_n - 1, v_i + 12);`)
  out(`    while v_k > v_i + 1 and not pg_temp.open_${SHORT}(p_new, array[(p_course->v_i->>0)::float8, (p_course->v_i->>1)::float8], array[(p_course->v_k->>0)::float8, (p_course->v_k->>1)::float8]) loop`)
  out(`      v_k := v_k - 1;`)
  out(`    end loop;`)
  out(`    v_out := v_out || jsonb_build_array(p_course->v_k);`)
  out(`    v_i := v_k;`)
  out(`  end loop;`)
  out(`  return v_out;`)
  out(`end $$;`)
  out()
  out(`-- A course's end, moved to the new roadstead if it stood at a moved harbour's old one.`)
  out(`create function pg_temp.ends_${SHORT}(p_course jsonb) returns jsonb language plpgsql as $$`)
  out(`declare v_c jsonb := p_course; v_i int; v_at int; m record; v_join float8 := public.wc_num('course_join_nm');`)
  out(`begin`)
  out(`  foreach v_i in array array[0, -1] loop`)
  out(`    select x.new_lat, x.new_lon into m from moved_${SHORT} x`)
  out(`     where voyage.gc_distance_nm((v_c->v_i->>0)::float8, (v_c->v_i->>1)::float8, x.old_lat::float8, x.old_lon::float8) <= v_join`)
  out(`     order by voyage.gc_distance_nm((v_c->v_i->>0)::float8, (v_c->v_i->>1)::float8, x.old_lat::float8, x.old_lon::float8) limit 1;`)
  out(`    if found then`)
  out(`      v_at := case when v_i = 0 then 0 else jsonb_array_length(v_c) - 1 end;`)
  out(`      v_c := jsonb_set(v_c, array[v_at::text], jsonb_build_array(m.new_lat, m.new_lon));`)
  out(`    end if;`)
  out(`  end loop;`)
  out(`  return v_c;`)
  out(`end $$;`)
  out()
  out(`do $mend$`)
  out(`declare`)
  out(`  v_new bytea; v_old bytea; r record; v_c jsonb; v_join numeric := public.wc_num('course_join_nm');`)
  out(`  v_ref text; v_pass int; v_t2 jsonb; v_mended int := 0; v_refused int := 0; v_t timestamptz := clock_timestamp();`)
  out(`begin`)
  out(`  select new_cells, old_cells into v_new, v_old from sea_bits_${SHORT};`)
  out(`  for r in select key, old_course, was_refused from mend_${SHORT} loop`)
  out(`    v_c := pg_temp.mend_${SHORT}(pg_temp.ends_${SHORT}(r.old_course), v_new, v_old, false);`)
  out(`    if v_c is null then raise exception '${SHORT}: a stored course has no way round an island: %', left(r.old_course::text, 300); end if;`)
  out(`    v_ref := voyage.path_refusal(v_c, (v_c->0->>0)::numeric, (v_c->0->>1)::numeric, (v_c->-1->>0)::numeric, (v_c->-1->>1)::numeric, v_join, 25, 25);`)
  out(`    v_pass := 0;`)
  out(`    while v_ref like 'E_LAND%' and v_c is distinct from r.old_course and v_pass < 4 loop`)
  out(`      v_pass := v_pass + 1;`)
  out(`      v_c := coalesce(pg_temp.mend_${SHORT}(v_c, v_new, v_old, true), v_c);`)
  out(`      v_ref := voyage.path_refusal(v_c, (v_c->0->>0)::numeric, (v_c->0->>1)::numeric, (v_c->-1->>0)::numeric, (v_c->-1->>1)::numeric, v_join, 25, 25);`)
  out(`    end loop;`)
  out(`    if v_c is distinct from r.old_course then`)
  out(`      v_t2 := pg_temp.tidy_${SHORT}(v_c, v_new);`)
  out(`      if v_ref is null and voyage.path_refusal(v_t2, (v_t2->0->>0)::numeric, (v_t2->0->>1)::numeric, (v_t2->-1->>0)::numeric, (v_t2->-1->>1)::numeric, v_join, 25, 25) is null then v_c := v_t2; end if;`)
  out(`    end if;`)
  out(`    if v_ref is not null then v_refused := v_refused + 1; raise notice '${SHORT}: still refused after the mend: % %', v_ref, left(r.old_course::text, 120); end if;`)
  out(`    if v_c is distinct from r.old_course then`)
  out(`      v_mended := v_mended + 1;`)
  out(`      update mend_${SHORT} set new_course = v_c,`)
  out(`        new_nm = (select sum((x->>'nm')::numeric) from jsonb_array_elements(voyage.segments_from_course(v_c)) x) where key = r.key;`)
  out(`    end if;`)
  out(`  end loop;`)
  out(`  raise notice '${SHORT}: % stored course(s) read, % mended, % refused for a reason of their own, in %', (select count(*) from mend_${SHORT}), v_mended, v_refused, clock_timestamp() - v_t;`)
  out(`end $mend$;`)
  out()
  out(`insert into public.sea_undo_${SHORT} (kind, ref, value)`)
  out(`select 'stop', s.route_id::text || '|' || s.ord, jsonb_build_object('course', s.course, 'course_nm', s.course_nm)`)
  out(`  from public.standing_route_stops s join mend_${SHORT} m on m.key = md5(s.course::text) where m.new_course is not null;`)
  out(`insert into public.sea_undo_${SHORT} (kind, ref, value)`)
  out(`select 'npc_course', c.from_port::text || '|' || c.to_port::text, jsonb_build_object('course', c.course, 'nm', c.nm)`)
  out(`  from public.npc_courses c join mend_${SHORT} m on m.key = md5(c.course::text) where m.new_course is not null;`)
  out(`update public.standing_route_stops s set course = m.new_course, course_nm = case when s.course_nm is null then null else m.new_nm end`)
  out(`  from mend_${SHORT} m where m.key = md5(s.course::text) and m.new_course is not null;`)
  out(`update public.npc_courses c set course = m.new_course, nm = m.new_nm`)
  out(`  from mend_${SHORT} m where m.key = md5(c.course::text) and m.new_course is not null;`)
  out(`update public.orders o set args = jsonb_set(o.args, '{path}', m.new_course)`)
  out(`  from mend_${SHORT} m where o.status = 'pending' and o.verb = 'SAIL' and jsonb_typeof(o.args->'path') = 'array'`)
  out(`   and m.key = md5((o.args->'path')::text) and m.new_course is not null;`)
  out()
  out(`-- ── WHAT IS DERIVED FROM THE ROADSTEADS AND THE DISTANCES ──────────────────────────────────`)
  out(`update public.sea_leg_asks a set wave_min = d.wave_min, title_min = d.title_min, zones = d.zones`)
  out(`  from public.sea_leg_asks_derive() d`)
  out(` where a.from_port = d.from_port and a.to_port = d.to_port`)
  out(`   and (a.wave_min, a.title_min, a.zones) is distinct from (d.wave_min, d.title_min, d.zones);`)
  out()
  out(`create temporary table haul_moved_${SHORT} on commit drop as`)
  out(`select pg.port_id, pg.good_id, pg.haul_nm as old_nm, pg.haul as old_haul, h.haul_nm as new_nm, h.haul as new_haul`)
  out(`  from public.port_goods pg join world.haul_rows() h on h.port_id = pg.port_id and h.good_id = pg.good_id`)
  out(` where (pg.haul_nm, pg.haul) is distinct from (h.haul_nm, h.haul);`)
  out(`update public.port_goods pg set haul_nm = m.new_nm, haul = m.new_haul`)
  out(`  from haul_moved_${SHORT} m where pg.port_id = m.port_id and pg.good_id = m.good_id;`)
  out()
  out(`-- ── SELF-ASSERT (the rows this file moved) ─────────────────────────────────────────────────`)
  out(`do $$`)
  out(`declare v_bad int; v_n int; v_h int; v_up numeric;`)
  out(`begin`)
  out(`  -- (a) the raster: the row holds this file's bytes, and the old bits are not the new`)
  out(`  if (select md5(cells) from public.sea_raster where id = 1) <> ${q(stats.md5)} then`)
  out(`    raise exception '${SHORT} self-assert FAIL: the raster is not the one this file carries';`)
  out(`  end if;`)
  out(`  -- (b) every moved roadstead is what the ONE SQL rule answers, snap_nm long, and off the land`)
  out(`  select count(*) into v_bad from moved_${SHORT} m join public.sea_reaches sr on sr.code = m.code join public.ports p on p.id = sr.port_id`)
  out(`   cross join lateral voyage.water_roadstead(p.lat, p.lon) w`)
  out(`   where w.lat is distinct from sr.roadstead_lat or w.lon is distinct from sr.roadstead_lon or abs(w.nm - sr.snap_nm) > 0.01 or sr.snap_nm <= 0;`)
  out(`  if v_bad <> 0 then raise exception '${SHORT} self-assert FAIL: % roadstead(s) are not what voyage.water_roadstead answers', v_bad; end if;`)
  out(`  -- (c) a closed island harbour: its own quay no longer stands on sailable water`)
  out(`  select count(*) into v_bad from moved_${SHORT} m where voyage.water_snap_nm(m.old_lat, m.old_lon) = 0;`)
  out(`  if v_bad <> 0 then raise exception '${SHORT} self-assert FAIL: % harbour(s) still stand on sailable water', v_bad; end if;`)
  out(`  -- (d) symmetric, for every pair of a moved harbour, and never under the great circle`)
  out(`  select count(*) into v_bad from public.sea_reaches a join moved_${SHORT} m on m.code = a.code join public.sea_reaches b on b.code <> a.code`)
  out(`   where (a.reaches->>b.code) is distinct from (b.reaches->>a.code) or (a.reaches->>b.code) is null`)
  out(`      or (a.reaches->>b.code)::numeric < voyage.gc_distance_nm(a.roadstead_lat::float8, a.roadstead_lon::float8, b.roadstead_lat::float8, b.roadstead_lon::float8) - 0.2;`)
  out(`  if v_bad <> 0 then raise exception '${SHORT} self-assert FAIL: % reach figure(s) of a moved harbour are one-way, missing or under the great circle', v_bad; end if;`)
  out(`  -- (e) every course this file mended sails, unless the land guard already refused it before this file`)
  out(`  select count(*) into v_bad from mend_${SHORT} m where m.new_course is not null and not m.was_refused`)
  out(`     and voyage.path_refusal(m.new_course, (m.new_course->0->>0)::numeric, (m.new_course->0->>1)::numeric, (m.new_course->-1->>0)::numeric, (m.new_course->-1->>1)::numeric,`)
  out(`                             public.wc_num('course_join_nm'), 25, 25) is not null;`)
  out(`  if v_bad <> 0 then raise exception '${SHORT} self-assert FAIL: % mended course(s) are refused by the land guard', v_bad; end if;`)
  out(`  -- (f) the pre-image holds the rows it promises, the raster among them`)
  out(`  select count(*) into v_n from mend_${SHORT} where new_course is not null;`)
  out(`  if (select count(*) from public.sea_undo_${SHORT} where kind = 'raster') <> 1 then raise exception '${SHORT} self-assert FAIL: the raster has no pre-image'; end if;`)
  out(`  -- (g) the hauls this file moved equal the derivation`)
  out(`  select count(*) into v_h from haul_moved_${SHORT};`)
  out(`  select count(*) into v_bad from haul_moved_${SHORT} m join public.port_goods pg on pg.port_id = m.port_id and pg.good_id = m.good_id`)
  out(`   where (pg.haul_nm, pg.haul) is distinct from (m.new_nm, m.new_haul);`)
  out(`  if v_bad <> 0 then raise exception '${SHORT} self-assert FAIL: % haul row(s) were not moved', v_bad; end if;`)
  out(`  select max(abs(new_nm - old_nm)) into v_up from haul_moved_${SHORT};`)
  out(`  raise notice '${SHORT} self-assert ok: THE HARBOURS HAVE THEIR ISLANDS. ${closed} cells closed, ${moved.length} roadsteads moved, ${stats.changed} pairs re-measured, % stored course(s) mended, % market row(s) took a new haul (widest % nm).', v_n, v_h, coalesce(v_up, 0);`)
  out(`end $$;`)
  out()
  return P.join('\n')
}
