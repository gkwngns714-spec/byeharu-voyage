/** A forward rollback's DO block: every hunk taken back out, once each. */
export function unhunkSql() {
  const one = (h) =>
    `  v_def := replace(pg_get_functiondef('${h.fn}'::regprocedure), E'\\r', '');\n` +
    `  v_n := (length(v_def) - length(replace(v_def, $h$${h.new}$h$, ''))) / length($h$${h.new}$h$);\n` +
    `  if v_n <> 1 then raise exception 'rollback-0441: the 0441 hunk of ${h.fn} occurs % time(s)', v_n; end if;\n` +
    `  execute replace(v_def, $h$${h.new}$h$, $h$${h.old}$h$);`
  return `do $$\ndeclare\n  v_def text;\n  v_n int;\nbegin\n${HUNKS.map(one).join('\n')}\nend\n$$;\n`
}

