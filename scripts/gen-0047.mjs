w(`-- One segment per sub-leg of the polyline, each carrying:`)
w(`--   nm           its own length (the measure's rule, per piece — the stored total is their sum)`)
w(`--   sea_id       voyage.sea_near at the midpoint (0040's sea_at composed with the 8-ring`)
w(`--                approach tolerance), so free water keeps hazard's spatial dimension`)
w(`--   hazard_mult  SHELTER, derived from the raster: land (or ice) within ~2 cells 0.8 — in sight`)
w(`--                of refuge; none within ~7 cells 1.2 — days from shelter; else 1.0. The old`)
w(`--                leg-graph texture keyed on authored endpoints; free segments key on the one`)
w(`--                fact the raster knows. Sea character (piracy, base rate) stays in seas.*.`)
w(`-- Segments over 500 nm are SPLIT into equal parts, so an ocean crossing changes sea and shelter`)
w(`-- as it goes instead of wearing one midpoint's answer for 3,000 nm.`)
w(`declare`)
w(`  r        public.sea_raster%rowtype;`)
w(`  out_segs jsonb := '[]'::jsonb;`)
w(`  i int; k int; n int; pieces int;`)
w(`  lat1 float8; lon1 float8; lat2 float8; lon2 float8;`)
w(`  alat float8; alon float8; blat float8; blon float8;`)
w(`  seg_nm numeric; mlat float8; mlon float8;`)
w(`  v_row int; v_col int; ring int; dr int; dc int; rr int; cc int;`)
w(`  v_land_ring int;`)
w(`begin`)
w(`  select * into r from public.sea_raster where id = 1;`)
w(`  n := coalesce(jsonb_array_length(p_course), 0);`)
w(`  for i in 0 .. n - 2 loop`)
w(`    lat1 := (p_course->i->>0)::float8;     lon1 := (p_course->i->>1)::float8;`)
w(`    lat2 := (p_course->(i+1)->>0)::float8; lon2 := (p_course->(i+1)->>1)::float8;`)
w(`    pieces := greatest(1, ceil(voyage.gc_distance_nm(lat1, lon1, lat2, lon2) / 500)::int);`)
w(`    for k in 0 .. pieces - 1 loop`)
w(`      alat := lat1 + (lat2 - lat1) * k / pieces;       alon := lon1 + (lon2 - lon1) * k / pieces;`)
w(`      blat := lat1 + (lat2 - lat1) * (k + 1) / pieces; blon := lon1 + (lon2 - lon1) * (k + 1) / pieces;`)
w(`      seg_nm := round(voyage.gc_distance_nm(alat, alon, blat, blon)::numeric, 2);`)
w(`      continue when seg_nm <= 0;`)
w(`      mlat := (alat + blat) / 2; mlon := (alon + blon) / 2;`)
w(`      v_row := least(r.rows - 1, greatest(0, floor((90 - mlat) / r.cell_deg)::int));`)
w(`      v_col := ((floor((mlon + 180) / r.cell_deg)::int % r.cols) + r.cols) % r.cols;`)
w(`      v_land_ring := null;`)
w(`      for ring in 1 .. 7 loop`)
w(`        for dr in -ring .. ring loop`)
w(`          rr := v_row + dr;`)
w(`          continue when rr < 0 or rr >= r.rows;`)
w(`          for dc in -ring .. ring loop`)
w(`            continue when greatest(abs(dr), abs(dc)) <> ring;`)
w(`            cc := ((v_col + dc) % r.cols + r.cols) % r.cols;`)
w(`            if get_bit(r.cells, (rr * r.cols + cc) * r.bits_per_cell) = 0 then`)
w(`              v_land_ring := ring;`)
w(`              exit;`)
w(`            end if;`)
w(`          end loop;`)
w(`          exit when v_land_ring is not null;`)
w(`        end loop;`)
w(`        exit when v_land_ring is not null;`)
w(`      end loop;`)
w(`      out_segs := out_segs || jsonb_build_object(`)
w(`        'a', jsonb_build_array(round(alat::numeric, 4), round(alon::numeric, 4)),`)
w(`        'b', jsonb_build_array(round(blat::numeric, 4), round(blon::numeric, 4)),`)
w(`        'nm', seg_nm,`)
w(`        'sea_id', voyage.sea_near(mlat, mlon),`)
w(`        'hazard_mult', case when v_land_ring is not null and v_land_ring <= 2 then 0.8`)
w(`                            when v_land_ring is null then 1.2`)
w(`                            else 1.0 end);`)
w(`    end loop;`)
w(`  end loop;`)
w(`  return out_segs;`)
w(`end $$;`)
