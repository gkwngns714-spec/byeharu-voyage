w(`-- ── 14. THE HELM ORDER AT SEA: she turns where she is ──────────────────────────────────────────`)
w(`create or replace function cmd.divert(p_fleet uuid, p_dest uuid, p_dest_point jsonb, p_path jsonb)`)
w(`returns jsonb`)
w(`language plpgsql`)
w(`security definer`)
w(`set search_path = public, pg_temp`)
w(`as $$`)
w(`-- Supersedes 0037's node-turn body (dropped above). Under the free sea she turns AT HER CLOSED-`)
w(`-- FORM POSITION: the sailing voyage is truncated there and settled through the ONE arrival arm`)
w(`-- (she comes to anchor at the cut point), the queue composed for the old market is cleared`)
w(`-- (0037's rule kept), and the onward passage is a plain SAIL through the ONE parser and the ONE`)
w(`-- mover, from the very point she holds. What has happened stays happened: kept segments are`)
w(`-- byte-identical, settled days keep their PK, and the onward water is a NEW voyage.`)
w(`--`)
w(`-- THE BRIDGE: the client plotted from the position it last READ, and at 1 real minute = 8 sim`)
w(`-- hours she has moved since. Rather than refuse honest staleness — or teleport her onto the`)
w(`-- course — her TRUE position is prepended when the course starts more than course_join_nm away,`)
w(`-- and the bridging water is then verified like all the rest: a cape she rounded between reads`)
w(`-- refuses the divert instead of sailing her back through it.`)
w(`declare`)
w(`  v_player uuid := public.current_player_id();`)
w(`  v_now    timestamptz := now();`)
w(`  f  public.fleets%rowtype;`)
w(`  v  public.voyages%rowtype;`)
w(`  pos record;`)
w(`  v_dest_c text;`)
w(`  v_token  text;`)
w(`  v_keep   jsonb := '[]'::jsonb;`)
w(`  v_prof   jsonb := '[]'::jsonb;`)
w(`  v_acc    numeric := 0;`)
w(`  v_pnm    numeric;`)
w(`  i        int := 0;`)
w(`  e        jsonb;`)
w(`  v_eta    timestamptz;`)
w(`  v_issue  jsonb;`)
w(`  v_course jsonb;`)
w(`begin`)
w(`  select * into f from public.fleets where id = p_fleet;`)
w(`  if f.id is null or v_player is null or f.player_id <> v_player then`)
w(`    return jsonb_build_object('ok', false, 'error_code', 'E_NO_SUCH_FLEET',`)
w(`      'error_message', 'That fleet is not yours.', 'fixes', '[]'::jsonb);`)
w(`  end if;`)
w()
w(`  -- Catch up first: an act must not reason about a stale position (D.2).`)
w(`  perform voyage.settle(p_fleet, v_now);`)
w(`  select * into f from public.fleets where id = p_fleet;`)
w(`  if f.status <> 'SAILING' then`)
w(`    return jsonb_build_object('ok', false, 'error_code', 'E_NOT_SAILING',`)
w(`      'error_message', format('%s is %s, not under way - from a quay, SAIL is the order.', f.name, f.status),`)
w(`      'fixes', jsonb_build_array(format('SAIL %s TO <the new port>', f.name)));`)
w(`  end if;`)
w()
w(`  if p_dest is not null then`)
w(`    select code into v_dest_c from public.ports where id = p_dest;`)
w(`    if v_dest_c is null then`)
w(`      return jsonb_build_object('ok', false, 'error_code', 'E_NO_SUCH_PORT',`)
w(`        'error_message', 'There is no such port to make for.', 'fixes', '[]'::jsonb);`)
w(`    end if;`)
w(`    v_token := v_dest_c;`)
w(`  elsif p_dest_point is not null`)
w(`        and jsonb_typeof(p_dest_point->'lat') = 'number' and jsonb_typeof(p_dest_point->'lon') = 'number' then`)
w(`    v_token := format('%s,%s', round((p_dest_point->>'lat')::numeric, 4), round((p_dest_point->>'lon')::numeric, 4));`)
w(`    v_dest_c := v_token;`)
w(`  else`)
w(`    return jsonb_build_object('ok', false, 'error_code', 'E_NO_SUCH_PORT',`)
w(`      'error_message', 'Name a port, or a point of open sea.', 'fixes', '[]'::jsonb);`)
w(`  end if;`)
w()
w(`  select * into v from public.voyages where fleet_id = p_fleet and status = 'SAILING' for update;`)
w(`  if p_dest is not null and v.dest_port_id = p_dest then`)
w(`    return jsonb_build_object('ok', false, 'error_code', 'E_SAME_DEST',`)
w(`      'error_message', format('%s is already bound for %s.', f.name,`)
w(`        (select name from public.ports where id = p_dest)),`)
w(`      'fixes', '[]'::jsonb);`)
w(`  end if;`)
w()
w(`  select * into pos from voyage.position(v.id, v_now);`)
w()
w(`  -- the queue was composed for another market (0037's rule, kept) - and it is cleared BEFORE`)
w(`  -- she comes to rest, or the arrival arm's own queue-run would depart her on a stale order`)
w(`  -- in the very same act (found by this file's probe: a pending SAIL took her straight back`)
w(`  -- out of the anchor before the onward order could be issued).`)
w(`  perform cmd.clear(p_fleet);`)
w()
w(`  if pos.nm_done < 1 then`)
w(`    -- She has barely left: the voyage is unmade whole rather than truncated to nothing`)
w(`    -- (total_nm must stay > 0). She stands again exactly where she departed.`)
w(`    update public.voyages set status = 'ABORTED' where id = v.id;`)
w(`    if v.origin_port_id is not null then`)
w(`      update public.fleets set status = 'DOCKED', port_id = v.origin_port_id, lat = null, lon = null,`)
w(`             version = version + 1 where id = p_fleet;`)
w(`    else`)
w(`      update public.fleets set status = 'ANCHORED', port_id = null,`)
w(`             lat = (v.path->0->'a'->>0)::numeric, lon = (v.path->0->'a'->>1)::numeric,`)
w(`             version = version + 1 where id = p_fleet;`)
w(`    end if;`)
w(`  else`)
w(`    -- Truncate at her position: kept segments byte-identical, the one under her keel cut AT the`)
w(`    -- point, the unsailed tail gone. total = exactly her progress, so the recomputed ETA is the`)
w(`    -- instant she holds, and the settle below arrives her THROUGH the one arrival arm.`)
w(`    for e in select * from jsonb_array_elements(v.path) loop`)
w(`      exit when i > pos.seg_index;`)
w(`      if i < pos.seg_index then`)
w(`        v_keep := v_keep || e;`)
w(`        v_prof := v_prof || (v.speed_profile->i);`)
w(`        v_acc  := v_acc + (e->>'nm')::numeric;`)
w(`      else`)
w(`        v_pnm := round(pos.nm_done - v_acc, 2);`)
w(`        if v_pnm > 0 then`)
w(`          v_keep := v_keep || (e || jsonb_build_object('b', jsonb_build_array(pos.lat, pos.lon), 'nm', v_pnm));`)
w(`          v_prof := v_prof || (v.speed_profile->i);`)
w(`        end if;`)
w(`      end if;`)
w(`      i := i + 1;`)
w(`    end loop;`)
w(`    update public.voyages`)
w(`       set path = v_keep, speed_profile = v_prof,`)
w(`           total_nm = (select sum((s->>'nm')::numeric) from jsonb_array_elements(v_keep) s),`)
w(`           dest_port_id = null`)
w(`     where id = v.id;`)
w(`    v_eta := voyage.recompute_eta(v.id);`)
w(`    perform voyage.settle(p_fleet, greatest(v_now, v_eta));`)
w(`  end if;`)
w()
w(`  select * into f from public.fleets where id = p_fleet;`)
w(`  if f.status not in ('DOCKED', 'ANCHORED') then`)
w(`    raise exception 'E_DIVERT_FAILED: she did not come to rest at the turn (status %)', f.status using errcode = 'P0001';`)
w(`  end if;`)
w()
w(`  -- the bridge, then the onward passage through the ONE parser and the ONE mover`)
w(`  v_course := p_path;`)
w(`  if v_course is not null and jsonb_typeof(v_course) = 'array' and jsonb_array_length(v_course) >= 1`)
w(`     and f.lat is not null`)
w(`     and voyage.gc_distance_nm(f.lat::float8, f.lon::float8,`)
w(`           (v_course->0->>0)::float8, (v_course->0->>1)::float8) > public.wc_num('course_join_nm') then`)
w(`    v_course := jsonb_build_array(jsonb_build_array(f.lat, f.lon)) || v_course;`)
w(`  end if;`)
