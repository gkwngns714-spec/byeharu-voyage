/** A hunk that must appear exactly once in its pre-image, verified NOW and again at apply. */
function hunk(def, text, label) {
  const n = def.split(text).length - 1
  if (n !== 1) throw new Error(`hunk "${label}" occurs ${n} time(s) in its pre-image, expected 1`)
  return text
}

/** Extract the exact text between two anchors (inclusive start, exclusive end). */
function between(def, startAnchor, endAnchor, label) {
  const i = def.indexOf(startAnchor)
  if (i < 0) throw new Error(`start anchor for "${label}" not found`)
  const j = def.indexOf(endAnchor, i)
  if (j < 0) throw new Error(`end anchor for "${label}" not found`)
  return hunk(def, def.slice(i, j), label)
}

