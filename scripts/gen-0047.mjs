w(`-- ── 10. THE ONE MOVER ──────────────────────────────────────────────────────────────────────────`)
w(`create or replace function cmd.do_sail(p_fleet uuid, p_args jsonb)`)
w(`returns jsonb`)
w(`language plpgsql`)
w(`security definer`)
w(`set search_path = public, pg_temp`)
w(`as $$`)
w(`-- Supersedes 0019's leg-graph body whole. The client PROPOSES a course (args.path, attached by`)
w(`-- cmd.issue's p_path); the server VERIFIES it against its own raster and MEASURES it itself —`)
w(`-- verification is the authoritative act, and no client number is ever believed. With no course`)
w(`-- attached, the straight line is tried — free, and correct exactly when it verifies — otherwise`)
w(`-- the order is refused E_NO_COURSE rather than guessed at.`)
w(`declare`)
w(`  f         public.fleets%rowtype;`)
w(`  v_dest    uuid := nullif(p_args->>'dest', '')::uuid;`)
w(`  v_point   jsonb := p_args->'dest_point';`)
w(`  v_course  jsonb := p_args->'path';`)
w(`  v_plotted boolean := coalesce(jsonb_typeof(p_args->'path') = 'array', false);`)
w(`  v_olat numeric; v_olon numeric; v_head numeric;`)
w(`  v_dlat numeric; v_dlon numeric; v_tail numeric;`)
w(`  v_ref    text;`)
w(`  v_nm     numeric;`)
w(`  v_segs   jsonb;`)
w(`  v_speed  numeric;`)
w(`  v_voyage uuid;`)
w(`begin`)
w(`  select * into f from public.fleets where id = p_fleet;`)
w()
w(`  -- the gates that need no distance, first (status, crew, flagship, and the berth facts)`)
w(`  v_ref := voyage.sail_refusal(p_fleet, v_dest, v_point, 0);`)
w(`  if v_ref is not null then`)
w(`    raise exception '%', v_ref using errcode = 'P0001';`)
w(`  end if;`)
w()
w(`  -- where she lies: a quay, or her own anchor. The approach allowance is the MEASURED snap of`)
w(`  -- the place plus 25 nm slack — the same rule (snap + one cell) the client's straightener`)
w(`  -- applies, held slightly looser here so a course the client passed cannot be refused for its`)
w(`  -- own approach.`)
w(`  if f.port_id is not null then`)
w(`    select p.lat, p.lon into v_olat, v_olon from public.ports p where p.id = f.port_id;`)
w(`    v_head := coalesce((select snap_nm from public.sea_reaches where port_id = f.port_id), 0) + 25;`)
w(`  else`)
w(`    -- her own position: the approach is MEASURED, not guessed — a fleet minutes off a river`)
w(`    -- quay still stands inside that port's approach, where her verified course crosses land`)
w(`    -- cells, and a flat allowance refused her own turn as E_LAND (the acceptance drive).`)
w(`    v_olat := f.lat; v_olon := f.lon;`)
w(`    v_head := voyage.water_snap_nm(v_olat, v_olon) + 25;`)
w(`  end if;`)
w()
w(`  -- where she is bound`)
w(`  if v_dest is not null then`)
w(`    if v_dest = f.port_id then`)
w(`      raise exception 'E_SAME_DEST: % already lies there', f.name using errcode = 'P0001';`)
w(`    end if;`)
w(`    select p.lat, p.lon into v_dlat, v_dlon from public.ports p where p.id = v_dest;`)
w(`    if v_dlat is null then`)
w(`      raise exception 'E_NO_SUCH_PORT: there is no such port' using errcode = 'P0001';`)
w(`    end if;`)
w(`    v_tail := coalesce((select snap_nm from public.sea_reaches where port_id = v_dest), 0) + 25;`)
w(`  elsif v_point is not null then`)
w(`    v_dlat := (v_point->>'lat')::numeric; v_dlon := (v_point->>'lon')::numeric;`)
w(`    if v_dlat is null or v_dlon is null or abs(v_dlat) > 90 or abs(v_dlon) > 180 then`)
w(`      raise exception 'E_BAD_PATH: that is not a point on the sphere' using errcode = 'P0001';`)
w(`    end if;`)
w(`    v_tail := voyage.water_snap_nm(v_dlat, v_dlon) + 25;`)
w(`    if voyage.gc_distance_nm(v_olat::float8, v_olon::float8, v_dlat::float8, v_dlon::float8)`)
w(`         <= public.wc_num('course_join_nm') then`)
w(`      raise exception 'E_SAME_DEST: % already lies there', f.name using errcode = 'P0001';`)
w(`    end if;`)
w(`  else`)
w(`    raise exception 'E_PARSE: SAIL needs a destination - a port, or a lat,lon point of open sea' using errcode = 'P0001';`)
w(`  end if;`)
w()
w(`  -- the course: proposed, or the straight line when none was`)
w(`  if not v_plotted then`)
w(`    v_course := jsonb_build_array(jsonb_build_array(v_olat, v_olon), jsonb_build_array(v_dlat, v_dlon));`)
w(`  end if;`)
w(`  v_ref := voyage.path_refusal(v_course, v_olat, v_olon, v_dlat, v_dlon,`)
w(`                               public.wc_num('course_join_nm'), v_head, v_tail);`)
w(`  if v_ref is not null then`)
w(`    if not v_plotted and v_ref like 'E_LAND:%' then`)
w(`      raise exception 'E_NO_COURSE: the straight way is not open water - the chart plots the course at the moment of ordering' using errcode = 'P0001';`)
w(`    end if;`)
w(`    raise exception '%', v_ref using errcode = 'P0001';`)
w(`  end if;`)
w()
w(`  -- THE MEASURE - the server's own, never the client's`)
w(`  v_segs := voyage.segments_from_course(v_course);`)
w(`  select sum((s->>'nm')::numeric) into v_nm from jsonb_array_elements(v_segs) s;`)
w()
w(`  v_ref := voyage.sail_refusal(p_fleet, v_dest, v_point, v_nm);`)
w(`  if v_ref is not null then`)
w(`    raise exception '%', v_ref using errcode = 'P0001';`)
w(`  end if;`)
w()
w(`  v_speed := voyage.fleet_speed(p_fleet);`)
w(`  v_voyage := voyage.depart(p_fleet, v_segs, f.port_id, v_dest);`)
w(`  perform public.emit_event(f.player_id, 'DEPARTED', jsonb_build_object(`)
w(`    'fleet', f.name, 'voyage_id', v_voyage, 'total_nm', v_nm,`)
w(`    'points', jsonb_array_length(v_course),`)
w(`    'dest', coalesce((select code from public.ports where id = v_dest),`)
w(`                     format('%s,%s', round(v_dlat, 2), round(v_dlon, 2))),`)
w(`    'eta', (select eta from public.voyages where id = v_voyage)));`)
w(`  return jsonb_build_object('voyage_id', v_voyage, 'total_nm', v_nm,`)
w(`                            'voyage_days', round((v_nm / v_speed) / 24, 2));`)
w(`end $$;`)
w()
w(`revoke all on function cmd.do_sail(uuid, jsonb) from public, anon, authenticated;`)
