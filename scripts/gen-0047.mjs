w(`-- ── 9. The closed-form place on the water ──────────────────────────────────────────────────────`)
w(`create or replace function voyage.position(p_voyage uuid, p_at timestamptz default now())`)
w(`returns table (seg_index int, leg_frac numeric, nm_done numeric, total_nm numeric, lat numeric, lon numeric)`)
w(`language plpgsql`)
w(`stable`)
w(`security definer`)
w(`set search_path = public, pg_temp`)
w(`as $$`)
w(`-- Supersedes 0006's port-interpolating body (dropped above). Same rule, new geometry:`)
w(`-- progress_nm is unchanged, and the point is placed LINEARLY along the segment the progress`)
w(`-- falls in — the SAME interpolation voyage.path_refusal samples, so the line judged, the line`)
w(`-- sailed and the point drawn are one line.`)
w(`declare`)
w(`  v       public.voyages%rowtype;`)
w(`  v_done  numeric;`)
w(`  v_acc   numeric := 0;`)
w(`  i       int := 0;`)
w(`  e       jsonb;`)
w(`  v_nm    numeric;`)
w(`begin`)
w(`  select * into v from public.voyages where id = p_voyage;`)
w(`  if v.id is null then`)
w(`    raise exception 'E_NO_SUCH_VOYAGE: %', p_voyage using errcode = 'P0001';`)
w(`  end if;`)
w(`  v_done := voyage.progress_nm(p_voyage, p_at);`)
w(`  for e in select * from jsonb_array_elements(v.path) loop`)
w(`    v_nm := (e->>'nm')::numeric;`)
w(`    if v_done <= v_acc + v_nm or i = jsonb_array_length(v.path) - 1 then`)
w(`      seg_index := i;`)
w(`      leg_frac  := round(least(1, greatest(0, case when v_nm = 0 then 1 else (v_done - v_acc) / v_nm end)), 6);`)
w(`      nm_done   := v_done;`)
w(`      total_nm  := v.total_nm;`)
w(`      lat := round(((e->'a'->>0)::numeric + ((e->'b'->>0)::numeric - (e->'a'->>0)::numeric) * leg_frac), 4);`)
w(`      lon := round(((e->'a'->>1)::numeric + ((e->'b'->>1)::numeric - (e->'a'->>1)::numeric) * leg_frac), 4);`)
w(`      return next;`)
w(`      return;`)
w(`    end if;`)
w(`    v_acc := v_acc + v_nm;`)
w(`    i := i + 1;`)
w(`  end loop;`)
w(`end $$;`)
w()
w(`revoke all on function voyage.position(uuid, timestamptz) from public, anon;`)
w(`grant execute on function voyage.position(uuid, timestamptz) to authenticated;`)

