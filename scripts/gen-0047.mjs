w(`-- ── 17. THE LAND GUARD: every stored course, walked ────────────────────────────────────────────`)
w(`create or replace function voyage.assert_paths_water()`)
w(`returns table (voyages_walked int, legacy_skipped int)`)
w(`language plpgsql`)
w(`stable`)
w(`security definer`)
w(`set search_path = public, pg_temp`)
w(`as $$`)
w(`-- Walks EVERY stored voyage path at sub-cell intervals through THE one sampler`)
w(`-- (voyage.path_refusal) and raises on the first sample that is not open water — the owner's law`)
w(`-- ("i don't want the fleet to ever touch land"), PROVEN rather than intended. Legacy-converted`)
w(`-- paths (straight port-to-port lines, the old model's shape) are counted and skipped, never`)
w(`-- silently. Non-vacuity is the CALLER's duty: 0047's probe and proof 09 assert voyages_walked`)
w(`-- is not zero AND prove the guard bites by feeding it a straight line across Iberia.`)
w(`declare`)
w(`  v public.voyages%rowtype;`)
w(`  v_course jsonb;`)
w(`  v_ref text;`)
w(`  v_head numeric;`)
w(`  v_tail numeric;`)
w(`  n_walked int := 0;`)
w(`  n_legacy int := 0;`)
w(`begin`)
w(`  for v in select * from public.voyages loop`)
w(`    if v.path->0 ? 'legacy' then`)
w(`      n_legacy := n_legacy + 1;`)
w(`      continue;`)
w(`    end if;`)
w(`    v_course := voyage.course_of(v.path);`)
w(`    -- the same allowances the mover granted: a port's measured snap, or — for an open-water`)
w(`    -- end — the point's own measured snap (a divert can lawfully cut a course inside a port's`)
w(`    -- approach, and the guard must judge by the rule the voyage was admitted under).`)
w(`    v_head := coalesce((select sr.snap_nm from public.sea_reaches sr where sr.port_id = v.origin_port_id),`)
w(`                       voyage.water_snap_nm((v_course->0->>0)::numeric, (v_course->0->>1)::numeric)) + 25;`)
w(`    v_tail := coalesce((select sr.snap_nm from public.sea_reaches sr where sr.port_id = v.dest_port_id),`)
w(`                       voyage.water_snap_nm((v_course->(jsonb_array_length(v_course)-1)->>0)::numeric,`)
w(`                                            (v_course->(jsonb_array_length(v_course)-1)->>1)::numeric)) + 25;`)
w(`    v_ref := voyage.path_refusal(v_course,`)
w(`               (v_course->0->>0)::numeric, (v_course->0->>1)::numeric,`)
w(`               (v_course->(jsonb_array_length(v_course)-1)->>0)::numeric,`)
w(`               (v_course->(jsonb_array_length(v_course)-1)->>1)::numeric,`)
w(`               1, v_head, v_tail);`)
w(`    if v_ref is not null then`)
w(`      raise exception 'LAND GUARD: voyage % (% -> %) fails the water law: %',`)
w(`        v.id,`)
w(`        coalesce((select code from public.ports where id = v.origin_port_id), 'open sea'),`)
w(`        coalesce((select code from public.ports where id = v.dest_port_id), 'open sea'),`)
w(`        v_ref;`)
w(`    end if;`)
w(`    n_walked := n_walked + 1;`)
w(`  end loop;`)
w(`  voyages_walked := n_walked;`)
w(`  legacy_skipped := n_legacy;`)
w(`  return next;`)
w(`end $$;`)
w()
w(`revoke all on function voyage.assert_paths_water() from public, anon, authenticated;`)
