// ═══════════════════════════════════════════════════════════════════════════════════════════════
// measure-land-guard.mjs — THE MARKET GUARD'S FIGURE, read from the applied chain's world (docs/design/land-2026-11.md 5.8 rule 2)
// ═══════════════════════════════════════════════════════════════════════════════════════════════
//
// The guard: one party-hour of a land job is no more than one hundredth of that good's target stock at a middling harbour of
// its region, in EVERY region the good comes from. A job has one time wherever it is dug, so the region that binds is the one
// whose middling harbour holds the least.
//
// For each good of scripts/build-land-migration.mjs's ladders, this reads, at every harbour (ports.kind = 'HARBOUR') of every
// region in public.goods.origin_regions, THE LEAST TARGET THE MARKET'S OWN RULE CAN HOLD THAT ROW AT: its base (port_goods.base_target,
// or stock_target where no depth multiple was ever applied) x depth_m0 (0252: a harbour's max-stock multiple runs from depth_m0 0.5
// to depth_m1 1.5 with what is invested; production has it lit, and many harbours sit at 0.5). It takes the middling harbour of each
// region (the lower median, percentile_disc 0.5: a real harbour's figure), and keeps the least of those: { target, region, harbours }.
// So the figure is the same in the chain's world and on production (both hold the same bases), and no day's investment can move a
// harbour under it.
// Every harbour has a market row for every good (254 x 629), and the brakes (the day's cap, the glut) are fractions of that
// row's stock_target, so every harbour of the region counts, whether its roster offers the good or not.
//
// It writes data/land-guard.generated.json, the generator's one input besides data/goods.json. The generator turns it into
// seconds; the migration's self-assert proves the guard again on the live rows at apply (production's targets included).
//
// 0461 (L2, the smith): a MAKE job's good (scripts/build-land-migration.mjs MAKERS) is made at the party's home, and a home can be
// a harbour of any region, so its figure is the least middling target over EVERY region (all 25), not its origin regions.
//
// Usage: node scripts/db/measure-land-guard.mjs          (restores the prefix cache up to 0454; a few seconds)
// ═══════════════════════════════════════════════════════════════════════════════════════════════
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { migrationFiles, MIGRATIONS_DIR, PREFIX_CACHE_DIR, preambleVariant, REPO_ROOT } from './apply-chain.mjs'
import { applyWithPrefixCache } from './prefix-cache.mjs'
import { LADDERS, MAKERS, WOODS } from '../build-land-migration.mjs'

const gather = [...Object.values(LADDERS), ...Object.values(WOODS)].flatMap((l) => l.goods.map(([, c]) => c))
const make = Object.values(MAKERS).flatMap((l) => l.goods.map(([, c]) => c))
const codes = [...gather, ...make]
// The world BEFORE the first migration that carries the generator's rows (0455): the markets are the same (no land file touches
// port_goods), and a land file whose self-assert proves the guard on rows not yet re-emitted cannot stand in the way of re-measuring.
const MARK = '-- BEGIN generated by scripts/build-land-migration.mjs'
const files = []
for (const name of await migrationFiles()) {
  const sql = readFileSync(path.join(MIGRATIONS_DIR, name), 'utf8')
  if (sql.includes(MARK)) break
  files.push({ name, sql })
}
const { db } = await applyWithPrefixCache({ variant: await preambleVariant(), files, cacheDir: PREFIX_CACHE_DIR, log: () => {} })
const rows = (await db.query(`
  with mid as (
    select g.code, rg.code as region, count(*)::int as harbours,
           percentile_disc(0.5) within group (order by coalesce(pg.base_target, pg.stock_target) * least(1, coalesce((select (c.value #>> '{}')::numeric from public.world_config c where c.key = 'depth_m0'), 1))) as target
      from public.goods g
      cross join unnest(case when g.code = any($2::text[]) then (select array_agg(r.code) from public.regions r) else g.origin_regions end) o(rc)
      join public.regions rg on rg.code = o.rc
      join public.ports p on p.region_id = rg.id and p.kind = 'HARBOUR'
      join public.port_goods pg on pg.port_id = p.id and pg.good_id = g.id
     where g.code = any($1::text[])
     group by g.code, rg.code)
  select distinct on (code) code, region, harbours, target::float8 as target,
         (select count(*) from mid m2 where m2.code = mid.code)::int as regions
    from mid order by code, target, region`, [codes, make])).rows
const out = {}
for (const c of codes) {
  const r = rows.find((x) => x.code === c)
  if (!r) throw new Error(`measure-land-guard: "${c}" has no harbour market in any region it comes from`)
  out[c] = { target: r.target, region: r.region, harbours: r.harbours, regions: r.regions }
}
const file = path.join(REPO_ROOT, 'data', 'land-guard.generated.json')
writeFileSync(file, JSON.stringify({
  _what: 'docs/design/land-2026-11.md 5.8 rule 2: for each land good, the least middling-harbour stock_target over the regions it comes from. Written by scripts/db/measure-land-guard.mjs; read by scripts/build-land-migration.mjs.',
  goods: out,
}, null, 2) + '\n')
console.log(`measure-land-guard: ${codes.length} goods -> ${path.relative(REPO_ROOT, file)}`)
for (const c of codes) console.log(`  ${c.padEnd(20)} ${String(out[c].target).padStart(8)} at ${out[c].region} (${out[c].harbours} harbours; ${out[c].regions} regions)`)
process.exit(0)
