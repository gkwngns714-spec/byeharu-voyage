const refusals = []
const courseCache = new Map()
async function leg(a, b) {
  const key = `${a}>${b}`
  if (courseCache.has(key)) return courseCache.get(key)
  const A = ports.get(a)
  const B = ports.get(b)
  const r = findPath(nav, { lat: A.rlat, lon: A.rlon }, { lat: B.rlat, lon: B.rlon })
  let out
  if (!r) out = { err: 'THE pathfinder cannot plot it' }
  else {
    const course = r.path.map(([lat, lon]) => [Number(lat.toFixed(4)), Number(lon.toFixed(4))])
    const chk = await one(
      db0,
      `select voyage.path_refusal($1::jsonb, $2::numeric, $3::numeric, $4::numeric, $5::numeric,
                                  public.wc_num('course_join_nm'), 25, 25) as refusal,
              (select sum((s->>'nm')::numeric) from jsonb_array_elements(voyage.segments_from_course($1::jsonb)) s)::float8 as nm`,
      [JSON.stringify(course), A.rlat, A.rlon, B.rlat, B.rlon],
    )
    out = chk.refusal ? { err: `the server refuses the course: ${chk.refusal}` } : { course, nm: chk.nm }
  }
  courseCache.set(key, out)
  return out
}
async function checkLoop(fl, loopStr) {
  const stops = loopStr.split(/\s+/)
  const c = classes.get(fl.class)
  const crew = fl.hulls * c.crew_required
  const why = []
  if (new Set(stops).size !== stops.length) why.push('a harbour is repeated in the loop')
  for (const s of stops) {
    const p = ports.get(s)
    if (!p) { why.push(`no place ${s}`); continue }
    if (p.kind !== 'HARBOUR') why.push(`${s} is not a HARBOUR`)
    if (c.draft > p.max_draft) why.push(`${s} takes draft ${p.max_draft}, a ${fl.class} draws ${c.draft}`)
    if (p.crew_pool < 0.2 * crew) why.push(`${s}'s quay holds ${p.crew_pool} hands, under 20 % of ${crew}`)
    if (!Number.isFinite(p.rlat)) why.push(`${s} is served no roadstead`)
  }
  const legs = []
  if (!why.length) {
    for (let i = 0; i < stops.length; i++) {
      const a = stops[i], b = stops[(i + 1) % stops.length]
      const L = await leg(a, b)
      if (L.err) why.push(`${a}→${b}: ${L.err}`)
      else legs.push({ from: a, to: b, nm: L.nm, course: L.course })
    }
  }
  return { loop: loopStr, stops, legs, why }
}

