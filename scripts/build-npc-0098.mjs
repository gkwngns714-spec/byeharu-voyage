// ── 3. the measurement: the whole roster, through the one executor ─────────────────────────────
async function measure(label, choice) {
  const t0 = Date.now()
  const db = await freshDb()
  await db.exec(LESSER_SQL)
  await db.exec(`
    update public.world_config set value = to_jsonb(0.0) where key = 'hazard_p_max';
    update public.world_config set value = 'true'::jsonb where key = 'standing_routes_enabled';
    -- pacing is applied to the SIMULATED clock below; the executor runs unpaced
    update public.world_config set value = to_jsonb(0) where key = 'npc_laps_per_game_day';`)
  const byHouse = new Map()
  for (const f of fleets) if (choice.get(f.key)?.hulls > 0) {
    if (!byHouse.has(f.house.company)) byHouse.set(f.house.company, [])
    byHouse.get(f.house.company).push(f)
  }
  const failed = []
  for (const [, hf] of byHouse) {
    const spec = specOf(hf[0].house, hf, choice)
    try {
      await db.query(`select public.npc_found($1::jsonb)`, [JSON.stringify(spec)])
    } catch (e) {
      failed.push(`${spec.company}: ${e.message}`)
    }
  }
  // ONE RANDOM STREAM PER MEASUREMENT: the market's drift (tick_market_drift) draws from random(),
  // and an unseeded stream made two measurements of the same roster disagree by more than a fleet's
  // whole margin (2026-10-08, run 2). Seeded, the same roster on the same chain measures the same.
  await db.query(`select setseed(0.4242)`)
  const sw = await one(db, `select public.npc_traders_switch(true) as j`)
  const keyOfOrd = new Map(fleets.map((f) => [f.ord, f.key]))
  const map = new Map(
    (await rows(db, `select nf.fleet_id, nf.route_id, nf.roster_ord from public.npc_fleets nf`)).map((r) => [
      keyOfOrd.get(r.roster_ord),
      r,
    ]),
  )
  const realStart = Number((await one(db, `select extract(epoch from now())::float8 as t`)).t)
  const st = new Map()
  const fleetState = async (fid) =>
    one(
      db,
      `select f.status, extract(epoch from f.busy_until)::float8 as busy,
              (select extract(epoch from v.eta)::float8 from public.voyages v where v.fleet_id = f.id and v.status = 'SAILING') as eta,
              (select extract(epoch from v.eta - v.departed_at)::float8 from public.voyages v where v.fleet_id = f.id and v.status = 'SAILING') as dur,
              extract(epoch from now())::float8 as now
         from public.fleets f where f.id = $1`,
      [fid],
    )
  const schedule = async (s, S, depart) => {
    const x = await fleetState(s.fleet_id)
    if (x.status === 'SAILING') { s.next = depart + x.dur; s.kind = 'arrive'; s.eta = x.eta }
    else if (x.status === 'REPAIRING' && x.busy) { s.next = depart + Math.max(1, x.busy - x.now); s.kind = 'release'; s.busy = x.busy }
    else { s.next = null; s.kind = 'idle' }
  }
  for (const [key, m] of map) {
    const s = { key, fleet_id: m.fleet_id, route_id: m.route_id, closed: 0, lastStart: 0, lap1: null }
    st.set(key, s)
    await schedule(s, 0, 0)
  }
  const merchantIds = `(select id from public.players where is_npc)`
  let S = 0
  let hour = 0
  let day = Math.floor(realStart / GAME_DAY)
  let slot = Math.floor(realStart / Number(K.drift_slot_seconds))
  let events = 0
  const LIMIT = MAX_SIM_HOURS * 3600
  for (;;) {
    let next = null
    for (const s of st.values()) if (s.next != null && (!next || s.next < next.next)) next = s
    if ([...st.values()].every((s) => s.closed >= LAPS)) break
    const nextHour = (hour + 1) * 3600
    if (!next || next.next > nextHour) {
      if (nextHour > LIMIT) break
      S = nextHour
      hour += 1
      await db.query(`select public.npc_plan(to_timestamp($1)), public.npc_tend(to_timestamp($1))`, [realStart + S])
      for (const s of st.values()) if (s.kind === 'idle') await schedule(s, S, S)
      continue
    }
    S = next.next
    const T = realStart + S
    if (Math.floor(T / GAME_DAY) !== day) {
      day = Math.floor(T / GAME_DAY)
      await db.query(`delete from public.trade_daily where player_id in ${merchantIds}`)
    }
    if (Math.floor(T / Number(K.drift_slot_seconds)) !== slot) {
      slot = Math.floor(T / Number(K.drift_slot_seconds))
      await db.query(`select public.tick_market_drift(to_timestamp($1))`, [T])
    }
    const before = next.closed
    if (next.kind === 'arrive') {
      await db.query(`select voyage.settle($1::uuid, to_timestamp($2))`, [next.fleet_id, next.eta + 0.001])
    } else {
      await db.query(`select cmd.advance($1::uuid, to_timestamp($2))`, [next.fleet_id, next.busy + 0.001])
    }
    events += 1
    next.closed = Number(
      (await one(db, `select count(*)::int as n from public.standing_route_laps where route_id = $1 and closed_at is not null`, [next.route_id])).n,
    )
    let depart = S
    if (next.closed > before) {
      depart = Math.max(S, next.lastStart + GAME_DAY / Math.max(PACE, 1))
      next.lastStart = depart
      if (before === 0) next.lap1 = await lapOne(db, next)
    }
    if (next.closed >= LAPS) {
      // measured: she rests (her voyage, if any, is simply never settled again)
      next.next = null
      next.kind = 'done'
      continue
    }
    await schedule(next, S, depart)
  }
  // results
  const res = new Map()
  for (const [key, s] of st) {
    const laps = await rows(
      db,
      `select lap_no, net::float8 as net, wages::float8 as wages, sold::float8 as sold, bought::float8 as bought,
              supplies::float8 as supplies, repairs::float8 as repairs, jsonb_array_length(skipped) as skipped
         from public.standing_route_laps where route_id = $1 and closed_at is not null order by lap_no`,
      [s.route_id],
    )
    const judged = laps.filter((l) => l.lap_no >= 3 && l.lap_no <= 6)
    const mean = (xs) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : null)
    const route = await one(db, `select paused_reason, (select status from public.fleets where id = $2) as status from public.standing_routes where id = $1`, [s.route_id, s.fleet_id])
    res.set(key, {
      laps: laps.length,
      nets: laps.map((l) => Math.round(l.net)),
      meanNet: mean(judged.map((l) => l.net)),
      meanWages: mean(judged.map((l) => l.wages)),
      firstLap: laps[0] ?? null,
      lap1: s.lap1,
      paused: route?.paused_reason ?? null,
      status: route?.status ?? null,
    })
  }
  const rowsHeld = await one(
    db,
    `select (select count(*) from public.ledger where player_id in ${merchantIds})::int as ledger,
            (select count(*) from public.events where player_id in ${merchantIds})::int as events,
            (select count(*) from public.voyage_events ve join public.voyages v on v.id = ve.voyage_id
              join public.fleets f on f.id = v.fleet_id where f.player_id in ${merchantIds})::int as voyage_events,
            (select count(*) from public.voyages v join public.fleets f on f.id = v.fleet_id where f.player_id in ${merchantIds})::int as voyages`,
  )
  await db.close()
  say(`   ${label}: ${events} arrivals over ${(S / 3600).toFixed(1)} simulated h, ${failed.length} founding failure(s), switch ${JSON.stringify(sw.j.tend?.started)} started — ${((Date.now() - t0) / 1000).toFixed(0)} s`)
  for (const f of failed) say(`      FOUNDING FAILED ${f}`)
  return { res, failed, rowsHeld, simHours: S / 3600, events }
}

/** The first lap's lines, leg by leg, read off the route-born orders before the closer prunes them. */
async function lapOne(db, s) {
  const lap = await one(db, `select id from public.standing_route_laps where route_id = $1 and lap_no = 1`, [s.route_id])
  if (!lap) return null
  const ords = await rows(
    db,
    `select verb, raw_text, result from public.orders where route_lap_id = $1 and status = 'done' order by seq`,
    [lap.id],
  )
  const stop0 = (await one(db, `select p.code from public.standing_route_stops s join public.ports p on p.id = s.port_id where s.route_id = $1 and s.ord = 0`, [s.route_id])).code
  const legs = []
  let at = stop0
  let buys = []
  for (const o of ords) {
    if (o.verb === 'BUY' && o.result?.good) buys.push({ good: o.result.good, qty: Number(o.result.qty), total: Number(o.result.total) })
    if (o.verb === 'SAIL') {
      const to = o.raw_text.trim().split(/\s+/).pop()
      legs.push({ from: at, to, buys })
      buys = []
      at = to
    }
  }
  return legs
}

