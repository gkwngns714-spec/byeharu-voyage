// ── 5. trim, with the chosen loops all running ────────────────────────────────────────────────
const trims = []
let final
const MAX_PASSES = Number(opt('--passes', '8'))
for (let pass = 1; pass <= MAX_PASSES; pass++) {
  final = await measure(`chosen roster, pass ${pass}`, choice)
  let changed = false
  for (const f of fleets) {
    const ch = choice.get(f.key)
    if (!ch || ch.hulls === 0) continue
    const r = final.res.get(f.key)
    const pass_ = r && r.laps >= 3 && r.meanNet != null && r.meanNet >= MIN_NET_TO_WAGES * (r.meanWages ?? 0) && r.meanNet > 0
    // A FLEET THAT HAS PASSED IS KEPT AS IT IS. Trimming another fleet changes the market this one
    // trades in, and re-judging every fleet on every pass ratchets the roster down on noise: run 2
    // of 2026-10-08 dropped 19 of 35 fleets that had each passed at least once. Only the fleets
    // that have never passed are trimmed.
    if (pass_) {
      ch.passed = true
      continue
    }
    if (ch.passed) continue
    if (ch.hulls > 1) {
      trims.push(`${f.key}: ${ch.hulls} → ${ch.hulls - 1} ${f.fl.class} (mean net ${Math.round(r?.meanNet ?? 0)} vs wages ${Math.round(r?.meanWages ?? 0)})`)
      ch.hulls -= 1
    } else if (ch.alt != null) {
      trims.push(`${f.key}: one hull still loses on [${f.cands[ch.idx].loop}]; moved to its alternate [${f.cands[ch.alt].loop}]`)
      ch.idx = ch.alt
      ch.alt = null
      ch.hulls = f.hulls
    } else {
      trims.push(`${f.key}: trimmed to nothing — DROPPED`)
      ch.hulls = 0
    }
    changed = true
  }
  if (!changed) break
  if (pass === MAX_PASSES) {
    // OUT OF PASSES: measure what the last trims left, and a fleet still under the rule is not
    // seeded on hope — it is dropped, loudly.
    final = await measure('chosen roster, after the last trims', choice)
    for (const f of fleets) {
      const ch = choice.get(f.key)
      const r = final.res.get(f.key)
      const ok = r && r.laps >= 3 && r.meanNet != null && r.meanNet > 0 && r.meanNet >= MIN_NET_TO_WAGES * (r.meanWages ?? 0)
      if (ch && ch.hulls > 0 && !ok && !ch.passed) {
        trims.push(`${f.key}: still under the rule after ${MAX_PASSES} passes — DROPPED`)
        ch.hulls = 0
      }
    }
  }
}
