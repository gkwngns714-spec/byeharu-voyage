// ── officers: by home port on the loop, then nation, then bonus (deterministic) ─────────────
function pickOfficers(h, fl, stops, used) {
  const out = []
  for (const spec of fl.officers) {
    const cand = officers
      .filter((o) => o.specialty === spec && !used.has(o.code))
      .sort(
        (a, b) =>
          Number(stops.includes(b.home)) - Number(stops.includes(a.home)) ||
          Number(b.nation === h.nation) - Number(a.nation === h.nation) ||
          b.bonus - a.bonus ||
          a.code.localeCompare(b.code),
      )
    if (cand.length) {
      used.add(cand[0].code)
      out.push(cand[0].code)
    }
  }
  return out
}

function daysFor(f, cand) {
  const c = classes.get(f.fl.class)
  const longest = Math.max(...cand.legs.map((l) => l.nm / (c.kn * 24)))
  return Math.min(999, Math.max(3, Math.ceil(1.5 * longest)))
}
const stopsOf = (cand) => cand.legs.map((l) => ({ port: l.from, course: l.course }))

/** One company's spec, in the shape public.npc_found (0097) reads. */
function specOf(h, houseFleets, choice, extra = {}) {
  const used = new Set()
  const skills = Object.fromEntries(Object.entries(h.skills).filter(([, v]) => v > 0))
  return {
    company: taken.has(h.company) ? h.alt_company : h.company,
    alt_company: h.alt_company,
    nation: h.nation,
    ink: ROSTER.inks[h.nation],
    master: h.master,
    blurb: extra.blurb ?? `${h.company} trades under ${h.master}.`,
    capital: extra.capital ?? MEASURE_CAPITAL,
    patience: h.patience,
    wares: h.wares,
    skills,
    roster_ord: houseFleets[0].houseOrd,
    fleets: houseFleets.map((f) => {
      const ch = choice.get(f.key)
      const cand = f.cands[ch.idx]
      const alt = ch.alt != null ? f.cands[ch.alt] : null
      return {
        name: f.fl.name,
        roster_ord: f.ord,
        days: daysFor(f, cand),
        ships: f.fl.ships.slice(0, ch.hulls).map((n) => ({ class: f.fl.class, name: n })),
        officers: pickOfficers(h, f.fl, cand.stops, used),
        stops: stopsOf(cand),
        ...(alt ? { alt_stops: stopsOf(alt) } : {}),
        ...(extra.fleet?.get(f.key) ?? {}),
      }
    }),
    ...(extra.house ?? {}),
  }
}
