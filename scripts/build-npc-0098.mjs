// build-npc-0098.mjs — the merchant companies are MEASURED, then founded (docs/NPC_TRADERS.md §3.2,
// §11 "0098"). GENERATES supabase/migrations/20260818000098_the_merchant_companies_are_founded.sql
// and data/npc-routes.generated.json from the AUTHORED roster data/npc-houses.json.
// ═══════════════════════════════════════════════════════════════════════════════════════════════
//
// WHAT IT DOES, IN ORDER
//   1. Applies 0001-0097 in PGlite (the chain this migration will be appended to), cached in the OS
//      temp dir by a fingerprint of the preamble and every file it applied.
//   2. VALIDATES every authored candidate loop and REFUSES (prints, never silently drops):
//        a stop that is not a HARBOUR · a harbour repeated in one loop (the 0096 anchor fix is for
//        players; the roster still repeats none) · a hull whose draft a stop cannot take (the
//        voyage.sail_refusal test, 0036:443-447) · a quay whose crew_pool is under 20 % of the
//        fleet's crew (crew_pool never regenerates) · a leg THE pathfinder (src/lib/sea) cannot plot
//        from the served roadsteads · a course the SERVER's voyage.path_refusal refuses as cmd.do_sail
//        would call it · a company name listed in --taken (production's names).
//   3. MEASURES, through the ONE executor: founds the WHOLE roster with npc_found (the 0097 founding)
//      on candidate k for every fleet, flips npc_traders_switch(true), and drives the clock: every
//      arrival is settled by voyage.settle (what tick_arrivals runs for a due fleet), the market is
//      regenerated by tick_market_drift on its own 15-minute slots, the daily cap rolls over at
//      every game-day, and npc_plan + npc_tend run on the hour (what tick_reconcile runs). Merchant
//      pacing (npc_laps_per_game_day, an interval between lap starts) is applied to the simulated
//      clock. Hazards are off (hazard_p_max 0). Each fleet is judged on the MEAN NET of laps 3-6.
//   4. CHOOSES each fleet's loop by that mean net; the runner-up becomes its alternate loop.
//   5. TRIMS: with the chosen loops all running, a fleet whose mean net is under
//      npc_min_net_to_wages × its mean lap wages loses one hull and the whole roster is measured
//      again (largest first is moot: a fleet is one class). A fleet trimmed to nothing is dropped.
//   6. SIZES capital (1.5 × the largest leg outlay of the measured first lap, floor 1.5 × lap wages,
//      summed over the company's fleets), WRITES each blurb from the measured first-lap lines,
//      CHECKS the Lisbon opening frame (every new company is founded at Lisbon, so that frame is
//      where liveliness is judged: ≥ 2 loops must cross it), and EMITS the migration.
//
// WHAT THE MEASUREMENT IS NOT
//   A merchant's departure is stamped with the database's own now() (voyage.depart), so the clock
//   is simulated around it rather than inside it: the harness settles each fleet at its own ETA in
//   arrival order and keeps a simulated clock for pacing, the market's slots and the daily cap.
//   The daily cap's game-day is read from now() by world.daily_cap_remaining, so the harness rolls
//   the cap by deleting merchant trade_daily rows at every simulated game-day boundary. Both are
//   stated in the receipt. The first-lap figures are an upper bound on an untouched market; the
//   steady state (laps 3-6) is what decides.
//
// USAGE
//   node scripts/build-npc-0098.mjs [--taken names.txt] [--laps 6] [--candidates 4] [--no-emit]
//   --taken: one company name per line — production's `select company_name from public.players`.
// ═══════════════════════════════════════════════════════════════════════════════════════════════

