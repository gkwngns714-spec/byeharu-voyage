// THE OPENING FRAME: every company is founded at Lisbon (new_house), and the opening chart is at
// least 12° across (src/chart/chartView.ts). A portrait phone frame on Lisbon is ±6° of longitude
// and ±(6 × 844/390)° of latitude. Count the kept loops whose courses cross it.
const frameOf = (code) => {
  const p = ports.get(code)
  const halfLon = 6
  const halfLat = 6 * (844 / 390)
  return { lat0: p.lat - halfLat, lat1: p.lat + halfLat, lon0: p.lon - halfLon, lon1: p.lon + halfLon }
}
const crossing = (code) => {
  const fr = frameOf(code)
  return kept.filter((f) =>
    f.cands[choice.get(f.key).idx].legs.some((l) =>
      l.course.some(([la, lo]) => la >= fr.lat0 && la <= fr.lat1 && lo >= fr.lon0 && lo <= fr.lon1),
    ),
  ).map((f) => f.fl.name)
}
