// The SQL of migration 0440, as scripts/build-clear-courses.mjs fills it in. A template only: the
// generator owns every number in it.

/** THE OWNER'S OWN EXAMPLE, as a box of solid Socotra (every point in it is drawn land: the
 *  generator checks it on the chart's tiles). The migration's self-assert holds the control course
 *  out of it. */
export const SOCOTRA = { south: 12.45, north: 12.55, west: 53.7, east: 54.2 }

export function migrationSql(x) {
  const S = SOCOTRA
  return `-- ═══════════════════════════════════════════════════════════════════════════════════════════════
-- 0440 — NO COURSE CROSSES THE DRAWN LAND (owner row 352, 2026-11-15)
-- ═══════════════════════════════════════════════════════════════════════════════════════════════
--
-- GENERATED by scripts/build-clear-courses.mjs from a world image of the applied chain (raster
-- ${x.raster}, coast mask public/coast/mask.json). Do not hand-edit: re-run the generator and cut
-- a NEW migration.
--
-- THE OWNER: "some ships go pass through land - such as hadibu. i found one by myself, and i am
-- guessing there are millions like this. fix this properly, and make procedures that this won't
-- happen again".
--
-- ── THE ROOT CAUSE ─────────────────────────────────────────────────────────────────────────────
-- The sea is a 0.25-degree raster (public.sea_raster, 0046), scan-filled from Natural Earth 1:110m.
-- 1:110m has NO Socotra at all (Hadibu's island is open sea to every rule), no Bangka, and coasts
-- straight for 60 nm at a time. The pathfinder (src/lib/sea) searches that raster and STRAIGHTENS
-- the result: two vertices are joined whenever every half-cell sample between them is raster water,
-- and voyage.path_refusal judges the same line the same way. So every course was legal water to the
-- server and was then drawn on the chart's 1:10m coast (public/coast) straight over islands, capes
-- and peninsulas. There is no lane graph and no unchecked straight-line fallback: the one check
-- there is was blind to the land the player sees.
--
-- ── WHAT WAS MEASURED (scripts/db/audit-land-crossings.mjs on the main world, tolerance 2 nm) ──
--   ${x.texts} distinct stored courses (${x.npc} lanes in public.npc_courses: every merchant, cargo,
--   pirate and navy course; ${x.routes} standing route stops). ${x.before} of the distinct courses ran over
--   more than 2 nm of drawn land away from their own harbours.
--
-- ── WHAT THIS FILE DOES ────────────────────────────────────────────────────────────────────────
--   ${x.fixes} courses are re-sailed off the drawn land (src/lib/sea/refine.ts against the coast mask,
--   the same function the browser's course author now runs). Each stays raster water by
--   voyage.path_refusal's own rule (asserted below, every one). On average they are ${x.longer}% longer.
--   ${x.after} distinct courses still cross: the water they need is land to the 0.25-degree raster
--   (a strait or channel it closes), listed in scripts/db/land-crossings.known.json for the raster
--   slice that opens it.
--   Every row that holds a replaced course is rewritten, matched by md5(course::text):
--     public.npc_courses            the lane, and its nm (voyage.segments_from_course's sum)
--     public.standing_route_stops   every route leg on that course, and its course_nm
--     public.cargo_circuit_legs     a cargo circuit's frozen pieces of that course, either way round
--     public.npc_course_zones_memo  the seas of each new course, both ways (0397's memo)
--   In the world it was cut from: ${x.lanes} lanes and ${x.stops} route stops.
--
-- ── VOYAGES ALREADY SAILING ARE LEFT TO FINISH (decided by default) ────────────────────────────
--   A departed voyage is a fixed course: its segments and frozen speeds ARE its schedule (0006,
--   0047); settlement, its ETA and the ship's drawn position all read them. Re-cutting them under a
--   sailing ship would move her and her arrival. A voyage lasts days; her next departure takes the
--   re-sailed lane.
--
-- budget: no table, no cron job, no autovacuum or fillfactor change. One rewrite of existing rows
-- (the lanes, route stops and cargo legs that hold a replaced course) and up to ${2 * x.fixes} memo rows.
-- ═══════════════════════════════════════════════════════════════════════════════════════════════

-- ── 1. THE REPLACED COURSES: the md5 of the old course's text, and the new course ───────────────
create function pg_temp.fix_0440() returns table (old_md5 text, course jsonb) language sql immutable as $fix$
  select v.old_md5, v.course::jsonb from (values
${x.values}
  ) as v(old_md5, course)
$fix$;

-- A course read backwards (a cargo circuit sails a lane the other way round, 0309).
create function pg_temp.rev_0440(p jsonb) returns jsonb language sql immutable as $r$
  select jsonb_agg(t.x order by t.i desc) from jsonb_array_elements(p) with ordinality t(x, i)
$r$;

-- The miles of a course, as cmd.do_sail measures it.
create function pg_temp.nm_0440(p jsonb) returns numeric language sql stable as $n$
  select sum((x ->> 'nm')::numeric) from jsonb_array_elements(voyage.segments_from_course(p)) x
$n$;

-- How many 1-nm samples of a course lie in solid Socotra (a box of it that is drawn land through
-- and through: lat ${S.south} to ${S.north}, lon ${S.west} to ${S.east}).
create function pg_temp.socotra_0440(p jsonb) returns int language plpgsql stable as $s$
declare
  i int; s int; n int; c int := 0; a jsonb; b jsonb; la float8; lo float8;
begin
  for i in 0 .. jsonb_array_length(p) - 2 loop
    a := p -> i;
    b := p -> (i + 1);
    n := greatest(1, ceil(voyage.gc_distance_nm((a ->> 0)::numeric, (a ->> 1)::numeric, (b ->> 0)::numeric, (b ->> 1)::numeric))::int);
    for s in 0 .. n loop
      la := (a ->> 0)::float8 + ((b ->> 0)::float8 - (a ->> 0)::float8) * s / n;
      lo := voyage.lon_lerp((a ->> 1)::float8, (b ->> 1)::float8, s::float8 / n);
      if la between ${S.south} and ${S.north} and lo between ${S.west} and ${S.east} then
        c := c + 1;
      end if;
    end loop;
  end loop;
  return c;
end
$s$;

-- ── 2. THE ONE STEP: every row that holds a replaced course takes the new one ───────────────────
create function pg_temp.clear_0440() returns jsonb language plpgsql as $c$
declare
  v_lanes int;
  v_stops int;
  v_legs  int := 0;
  v_memo  int;
  v_pairs jsonb;
  l       record;
  m       record;
  v_txt   text;
begin
  -- The pieces a cargo circuit froze (voyage.segments_from_course of a chain of lanes, 0309): an
  -- old lane's pieces, either way round, are found by their text and become the new lane's. Read
  -- BEFORE the lanes change, from the old courses themselves.
  select coalesce(jsonb_agg(jsonb_build_array(o.old_inner, o.new_inner)), '[]'::jsonb) into v_pairs
    from (select distinct trim(both '[]' from voyage.segments_from_course(q.c)::text) as old_inner,
                          trim(both '[]' from voyage.segments_from_course(q.n)::text) as new_inner
            from (select c.course as c, f.course as n
                    from public.npc_courses c join pg_temp.fix_0440() f on md5(c.course::text) = f.old_md5
                  union all
                  select pg_temp.rev_0440(c.course), pg_temp.rev_0440(f.course)
                    from public.npc_courses c join pg_temp.fix_0440() f on md5(c.course::text) = f.old_md5) q) o;
  for l in select g.circuit_id, g.ord, g.segments::text as t from public.cargo_circuit_legs g loop
    v_txt := l.t;
    for m in select e ->> 0 as old_inner, e ->> 1 as new_inner from jsonb_array_elements(v_pairs) e loop
      if strpos(v_txt, m.old_inner) > 0 then
        v_txt := replace(v_txt, m.old_inner, m.new_inner);
      end if;
    end loop;
    if v_txt <> l.t then
      update public.cargo_circuit_legs g
         set segments = v_txt::jsonb,
             nm = (select sum((x ->> 'nm')::numeric) from jsonb_array_elements(v_txt::jsonb) x)
       where g.circuit_id = l.circuit_id and g.ord = l.ord;
      v_legs := v_legs + 1;
    end if;
  end loop;

  update public.npc_courses c set course = f.course, nm = pg_temp.nm_0440(f.course)
    from pg_temp.fix_0440() f where md5(c.course::text) = f.old_md5;
  get diagnostics v_lanes = row_count;

  update public.standing_route_stops s set course = f.course, course_nm = pg_temp.nm_0440(f.course)
    from pg_temp.fix_0440() f where md5(s.course::text) = f.old_md5;
  get diagnostics v_stops = row_count;

  -- The seas of every new course, both ways (0397's memo, in 0414's form).
  insert into public.npc_course_zones_memo (course_md5, zones)
  select distinct on (k.h) k.h, k.zones
    from (select md5(f.course::text) as h, public.course_zones(f.course) as zones from pg_temp.fix_0440() f
          union all
          select md5(pg_temp.rev_0440(f.course)::text), public.course_zones(f.course) from pg_temp.fix_0440() f) k
   order by k.h
  on conflict (course_md5) do nothing;
  get diagnostics v_memo = row_count;

  return jsonb_build_object('lanes', v_lanes, 'stops', v_stops, 'cargo_legs', v_legs, 'memo', v_memo);
end
$c$;

-- ── 3. SELF-ASSERT, on a probe that is rolled back ─────────────────────────────────────────────
do $$
declare
  v_join  numeric := public.wc_num('course_join_nm');
  v_old   jsonb;
  v_new   jsonb;
  v_old2  jsonb;
  v_new2  jsonb;
  v_nat   uuid;
  v_circ  bigint;
  v_port  uuid;
  v_got   jsonb;
  v_want  jsonb;
  v_bad   text;
  v_res   jsonb;
begin
  -- (a) THE SERVER'S LAW: every new course is raster water as voyage.path_refusal reads it, with
  --     the figures cmd.do_sail passes for a roads-to-roads course (join = course_join_nm, head and
  --     tail = 0076's flat 25 nm).
  select string_agg(f.old_md5 || ': ' || r.ref, '; ') into v_bad
    from pg_temp.fix_0440() f
   cross join lateral (select voyage.path_refusal(f.course,
                                (f.course -> 0 ->> 0)::numeric, (f.course -> 0 ->> 1)::numeric,
                                (f.course -> -1 ->> 0)::numeric, (f.course -> -1 ->> 1)::numeric, v_join, 25, 25) as ref) r
   where r.ref is not null;
  if v_bad is not null then
    raise exception '0440 self-assert FAIL: a re-sailed course is refused by voyage.path_refusal: %', left(v_bad, 2000);
  end if;

  -- (b) THE OWNER'S EXAMPLE: the control course ran through solid Socotra; the new one does not.
  select f.course into v_new from pg_temp.fix_0440() f where f.old_md5 = '${x.control.old}';
  if v_new is null or pg_temp.socotra_0440(v_new) <> 0 then
    raise exception '0440 self-assert FAIL: the Socotra control is missing or still crosses the island (% samples)', pg_temp.socotra_0440(v_new);
  end if;
  select c.course into v_old from public.npc_courses c where md5(c.course::text) = '${x.control.old}';
  if v_old is not null and pg_temp.socotra_0440(v_old) = 0 then
    raise exception '0440 self-assert FAIL: the Socotra control''s old course does not cross the box, so the box proves nothing';
  end if;

  -- (c) THE PROBE: a cargo circuit of its own whose one leg is two replaced lanes, the second read
  --     backwards. After the step its leg must be exactly the two new lanes' pieces, and no lane or
  --     route stop may still hold a replaced course. Rolled back whole.
  begin
    select c.course, f.course into v_old, v_new
      from public.npc_courses c join pg_temp.fix_0440() f on md5(c.course::text) = f.old_md5 order by f.old_md5 limit 1;
    select c.course, f.course into v_old2, v_new2
      from public.npc_courses c join pg_temp.fix_0440() f on md5(c.course::text) = f.old_md5 order by f.old_md5 desc limit 1;
    if v_old is not null then
      v_nat := (select g.nation_id from public.great_powers g order by g.nation_id limit 1);
      v_port := (select p.id from public.ports p where p.kind = 'HARBOUR' order by p.code limit 1);
      insert into public.cargo_circuits (nation_id, start_port) values (v_nat, v_port) returning id into v_circ;
      insert into public.cargo_circuit_legs (circuit_id, ord, to_port, nm, segments)
      values (v_circ, 1, v_port, 1, voyage.segments_from_course(v_old) || voyage.segments_from_course(pg_temp.rev_0440(v_old2)));
      v_res := pg_temp.clear_0440();
      v_got := (select g.segments from public.cargo_circuit_legs g where g.circuit_id = v_circ and g.ord = 1);
      v_want := voyage.segments_from_course(v_new) || voyage.segments_from_course(pg_temp.rev_0440(v_new2));
      if v_got is distinct from v_want then
        raise exception '0440 self-assert FAIL: the probe cargo leg was not re-cut to the new lanes (% pieces, % wanted)',
          jsonb_array_length(v_got), jsonb_array_length(v_want);
      end if;
      if exists (select 1 from public.npc_courses c join pg_temp.fix_0440() f on md5(c.course::text) = f.old_md5)
         or exists (select 1 from public.standing_route_stops s join pg_temp.fix_0440() f on md5(s.course::text) = f.old_md5) then
        raise exception '0440 self-assert FAIL: a lane or a route stop still holds a replaced course after the step';
      end if;
    end if;
    raise exception using errcode = 'ZX440', message = coalesce(v_res, '{}'::jsonb)::text;
  exception when sqlstate 'ZX440' then
    raise notice '0440 probe (rolled back): %', sqlerrm;
  end;
end
$$;

-- ── 4. THE STEP, for real ────────────────────────────────────────────────────────────────────────
do $$
declare
  v_res jsonb := pg_temp.clear_0440();
begin
  if exists (select 1 from public.npc_courses c join pg_temp.fix_0440() f on md5(c.course::text) = f.old_md5)
     or exists (select 1 from public.standing_route_stops s join pg_temp.fix_0440() f on md5(s.course::text) = f.old_md5) then
    raise exception '0440 FAIL: a lane or a route stop still holds a replaced course';
  end if;
  raise notice '0440 self-assert ok: NO COURSE CROSSES THE DRAWN LAND. ${x.fixes} course(s) re-sailed off the drawn land, every one raster water by voyage.path_refusal; the Hadibu to Kilwa control is off Socotra; the probe cargo leg re-cut and rolled back. Rewritten: %', v_res;
end
$$;
`
}
