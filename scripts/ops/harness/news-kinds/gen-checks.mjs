// gen-checks.mjs: writes 0362's PROD CHECK files (before.sql, after.sql, volatility.sql, volume.sql) and the forward rollback draft (rollback-0362.sql) from the migration's own
// hunks, so the texts checked on prod are the texts the migration cuts; and, with --proof, rewrites the hunk rows proof 64 holds (scripts/db/proofs/64_news_kinds.sql, between its
// two marker lines: the proof puts the old bodies back from them). LOCAL ONLY; not in CI.
//   node scripts/ops/harness/news-kinds/gen-checks.mjs [--proof]
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '../../../..')
const MIG = path.join(ROOT, 'supabase/migrations/20260818000362_the_news_tells_of_trades_prices_pirates_and_gifts.sql')
const PROOF = path.join(ROOT, 'scripts/db/proofs/64_news_kinds.sql')
const sql = readFileSync(MIG, 'utf8').replaceAll('\r', '')
const re = /\('([a-z_.]+\([a-z ,]*\))', (\d+),\n\$o\$([\s\S]*?)\$o\$,\n\$n\$([\s\S]*?)\$n\$\)/g
export const hunks = [...sql.matchAll(re)].map((m) => ({ fn: m[1], n: Number(m[2]), old: m[3], new: m[4] }))
if (hunks.length !== 7) throw new Error(`expected 7 hunks in the migration, found ${hunks.length}`)
for (const h of hunks) if (h.old.includes('$h$') || h.new.includes('$h$')) throw new Error('a hunk holds the quote tag')

export const CUT = [...new Set(hunks.map((h) => h.fn))]
export const NEW_FNS = [
  'public.news_num(numeric)',
  'public.news_good(uuid)',
  'public.news_room(text)',
  'public.news_big_trade(text,uuid,uuid,uuid,numeric,numeric)',
  'public.news_price_spikes(timestamp with time zone,timestamp with time zone)',
  'public.news_pirates(uuid,integer,uuid,text,numeric)',
  'public.news_gift(uuid,uuid,bigint,timestamp with time zone)',
]
const KINDS = ['BIG_SALE', 'BIG_BUY', 'PRICE_SPIKE', 'PIRATES', 'CAPITAL_GIFT']
const KNOBS = ['news_big_trade', 'news_spike_pct', 'news_spike_top', 'news_spike_quiet_hours', 'news_pirate_loss', 'news_merchant_hour']
const arr = (xs) => `array[${xs.map((x) => `'${x}'`).join(', ')}]`
const rows = (indent = '  ') => hunks.map((h) => `${indent}('${h.fn}', ${h.n}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')

if (process.argv.includes('--proof')) {
  const BEGIN = '-- HUNKS BEGIN (written by scripts/ops/harness/news-kinds/gen-checks.mjs --proof from the migration; do not edit by hand)\n'
  const END = '-- HUNKS END\n'
  const proof = readFileSync(PROOF, 'utf8').replaceAll('\r', '')
  const a = proof.indexOf(BEGIN)
  const b = proof.indexOf(END)
  if (a < 0 || b < a) throw new Error('proof 64 has no hunk markers')
  const block = `create temp table hunks_64 (fn text, n int, old text, new text) on commit drop;\ninsert into hunks_64 (fn, n, old, new) values\n${rows()};\n`
  writeFileSync(PROOF, proof.slice(0, a + BEGIN.length) + block + proof.slice(b))
  console.log(`proof 64: ${hunks.length} hunk rows written`)
  process.exit(0)
}

// imported (proof-0362.mjs reads `hunks`): nothing is written
if (path.resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  const cte = `with h(fn, ord, old, new) as (values\n${hunks.map((h) => `  ('${h.fn}'::text, ${h.n}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')}\n), d as (\n  select h.*, replace(pg_get_functiondef(to_regprocedure(h.fn)), chr(13), '') as def from h\n)`
  const run = (f) => `npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/news-kinds/${f}`

  writeFileSync(
    path.join(HERE, 'volatility.sql'),
    `-- 0362 PROD CHECK (first; before and after), read-only, ONE statement: ${run('volatility.sql')}
-- Wanted, before and after alike: 5 rows, every one volatile 'v', definer true, settings {search_path=public, pg_temp}, and no client may execute any (client false).
-- After the deploy the same five rows: a re-cut moves none of them. Only the catalog is read.
begin transaction read only;
select p.oid::regprocedure::text as fn, p.provolatile as volatile, p.prosecdef as definer, p.proconfig as settings,
       has_function_privilege('anon', p.oid, 'execute') or has_function_privilege('authenticated', p.oid, 'execute') as client
  from pg_proc p
 where p.oid = any (array(select to_regprocedure(f) from unnest(${arr(CUT)}) f))
 order by 1;
commit;
`,
  )

  writeFileSync(
    path.join(HERE, 'before.sql'),
    `-- 0362 PROD CHECK (before), read-only, ONE statement: ${run('before.sql')}
-- Wanted: 7 rows; every old_times 1 and new_times 0 (the live bodies are the bodies this file was cut against); made 0 (no leaf, kind or knob of 0362 yet);
-- head 20260818000361 (0362 goes after the open 0355-0361; if one of them is not deployed, its number is simply not there: what matters is old_times 1).
-- Keep \`bodies\` (each cut body's md5 before). Generated by scripts/ops/harness/news-kinds/gen-checks.mjs from the migration's own hunks. The catalog, news_kinds and world_config's keys are read.
begin transaction read only;
${cte}
select fn, ord,
       (length(def) - length(replace(def, old, ''))) / length(old) as old_times,
       (length(def) - length(replace(def, new, ''))) / length(new) as new_times,
       (select count(*) from unnest(${arr(NEW_FNS)}) f where to_regprocedure(f) is not null)
         + (select count(*) from public.news_kinds k where k.kind = any (${arr(KINDS)}))
         + (select count(*) from public.world_config c where c.key like 'news\\_%') as made,
       (select jsonb_object_agg(f, md5(replace(pg_get_functiondef(to_regprocedure(f)), chr(13), ''))) from unnest(${arr(CUT)}) f) as bodies,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from d order by fn, ord;
commit;
`,
  )

  writeFileSync(
    path.join(HERE, 'after.sql'),
    `-- 0362 PROD CHECK (after), read-only, ONE statement: ${run('after.sql')}
-- Wanted: 7 rows; every new_times 1; fns 7 and client_fns 0 (no client may execute a leaf); kinds 5 (all importance 2);
-- knobs {"news_big_trade": 250000, "news_merchant_hour": 2, "news_pirate_loss": 50000, "news_spike_pct": 20, "news_spike_quiet_hours": 6, "news_spike_top": 5};
-- update_row 1 (this file's own "Update" news); head 20260818000362. Keep \`bodies\` (the new md5 of each cut body).
-- Generated by scripts/ops/harness/news-kinds/gen-checks.mjs from the migration's own hunks. The catalog, news_kinds, six knobs and one news row by its key are read.
begin transaction read only;
${cte}
select fn, ord,
       (length(def) - length(replace(def, new, ''))) / length(new) as new_times,
       (select count(*) from unnest(${arr(NEW_FNS)}) f where to_regprocedure(f) is not null) as fns,
       (select count(*) from unnest(${arr(NEW_FNS)}) f where has_function_privilege('authenticated', to_regprocedure(f), 'execute') or has_function_privilege('anon', to_regprocedure(f), 'execute')) as client_fns,
       (select count(*) from public.news_kinds k where k.kind = any (${arr(KINDS)}) and k.importance = 2) as kinds,
       (select jsonb_object_agg(c.key, c.value order by c.key) from public.world_config c where c.key = any (${arr(KNOBS)})) as knobs,
       (select count(*) from public.world_news w where w.key = 'update:0362') as update_row,
       (select jsonb_object_agg(f, md5(replace(pg_get_functiondef(to_regprocedure(f)), chr(13), ''))) from unnest(${arr(CUT)}) f) as bodies,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from d order by fn, ord;
commit;
`,
  )

  writeFileSync(
    path.join(HERE, 'volume.sql'),
    `-- 0362 PROD CHECK (the 30-minute after-check, and again after a day), read-only, ONE statement: ${run('volume.sql')}
-- WHAT THE NEW KINDS TOLD: one row a kind: rows in the last hour and the last 24 hours, how many of them a ship of the world's (npc), and the newest instant.
-- Wanted: for BIG_SALE, BIG_BUY, PIRATES and CAPITAL_GIFT the npc rows of ANY one hour never above news_merchant_hour (2): last_hour_npc at most 2 (3 where two sessions told at the same instant), last_day_npc at most about 48;
-- PRICE_SPIKE last_hour at most news_spike_top (5), last_day at most 120. A kind with no row yet is not listed. One range scan of world_news by its (scope, at) index.
begin transaction read only;
select w.kind,
       count(*) filter (where w.at > now() - interval '1 hour') as last_hour,
       count(*) filter (where w.at > now() - interval '1 hour' and (w.detail->>'npc')::boolean) as last_hour_npc,
       count(*) as last_day,
       count(*) filter (where (w.detail->>'npc')::boolean) as last_day_npc,
       max(w.at) as newest
  from public.world_news w
 where w.scope in ('port', 'company') and w.at > now() - interval '24 hours' and w.kind = any (${arr(KINDS)})
 group by w.kind order by w.kind;
commit;
`,
  )

  writeFileSync(
    path.join(HERE, 'rollback-0362.sql'),
    `-- 0362 FORWARD ROLLBACK, A DRAFT (docs/dev-log/2026-11-13-news-kinds.md). NOT a prod check and NOT a migration yet: to use it, strip the guard line, give it the next number, add its
-- "-- news: none" line and deploy it as any migration (owner only). It swaps 0362's OLD and NEW: each cut body loses exactly what 0362 added (each NEW text once, reversed, judged as a
-- round trip on the live body: no fixed digest, a later file may have re-cut it), then the seven leaves and the six knobs are dropped. A kind that has told nothing is deleted; a kind
-- with rows stays (public.world_news is append-only and its rows name their kind): nothing writes it any more, and its old rows stay readable.
-- THE LIGHTER ROLLBACK: set news_big_trade, news_spike_pct and news_merchant_hour to 0 (trades and spikes stop; the world's ships are not told; a player's raid or gift still is).
-- Tested locally: run.mjs --apply rollback-0362.sql runs to its notice (each body judged as a round trip, and no body left calling a leaf).
-- Generated by scripts/ops/harness/news-kinds/gen-checks.mjs from the migration's own hunks.
-- LOCAL PGlite WORLD ONLY while it carries this line (scripts/ops/harness/README.md): it writes. The first statement refuses a real server (inet_server_addr() is not null there, null on PGlite).
do $$ begin if inet_server_addr() is not null then raise exception 'local PGlite world only: this scene writes'; end if; end $$;
do $r$
declare
  f      record;
  h      record;
  v_live text;
  v_def  text;
  v_back text;
begin
  perform set_config('statement_timeout', '45s', true);
  perform set_config('lock_timeout', '5s', true);
  create temp table hunks_rb_0362 (fn text, n int, old text, new text) on commit drop;
  insert into hunks_rb_0362 (fn, n, old, new) values
${rows()};
  for f in select distinct x.fn from hunks_rb_0362 x order by x.fn loop
    v_live := replace(pg_get_functiondef(f.fn::regprocedure), E'\\r', '');
    v_def := v_live;
    for h in select * from hunks_rb_0362 x where x.fn = f.fn order by x.n desc loop
      if (length(v_def) - length(replace(v_def, h.new, ''))) / length(h.new) <> 1 then
        raise exception 'rollback 0362: hunk % of % is not in the live body exactly once', h.n, f.fn;
      end if;
      v_def := replace(v_def, h.new, h.old);
    end loop;
    v_back := v_def;
    for h in select * from hunks_rb_0362 x where x.fn = f.fn order by x.n loop
      if (length(v_back) - length(replace(v_back, h.old, ''))) / length(h.old) <> 1 then
        raise exception 'rollback 0362: hunk % of %: its OLD text is not in the rebuilt body exactly once', h.n, f.fn;
      end if;
      v_back := replace(v_back, h.old, h.new);
    end loop;
    if v_back is distinct from v_live or v_def = v_live then
      raise exception 'rollback 0362: the rebuilt % does not come back to the live body', f.fn;
    end if;
    execute v_def;
  end loop;
  if exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
              where n.nspname in ('public', 'cmd', 'world', 'voyage')
                and p.prosrc ~ 'news_(big_trade|price_spikes|pirates|gift|room|good|num)\\(' and p.oid <> all (array(select to_regprocedure(x) from unnest(${arr(NEW_FNS)}) x))) then
    raise exception 'rollback 0362: a body still calls a leaf of 0362';
  end if;
  drop function public.news_big_trade(text, uuid, uuid, uuid, numeric, numeric);
  drop function public.news_price_spikes(timestamptz, timestamptz);
  drop function public.news_pirates(uuid, int, uuid, text, numeric);
  drop function public.news_gift(uuid, uuid, bigint, timestamptz);
  drop function public.news_room(text);
  drop function public.news_good(uuid);
  drop function public.news_num(numeric);
  delete from public.world_config c where c.key = any (${arr(KNOBS)});
  delete from public.news_kinds k where k.kind = any (${arr(KINDS)}) and not exists (select 1 from public.world_news w where w.kind = k.kind);
  raise notice 'rollback 0362 ok: % hunks reversed over % bodies; the leaves and the knobs dropped; kinds left (they told something): %',
    (select count(*) from hunks_rb_0362), (select count(distinct x.fn) from hunks_rb_0362 x),
    coalesce((select string_agg(k.kind, ', ' order by k.kind) from public.news_kinds k where k.kind = any (${arr(KINDS)})), 'none');
end
$r$;
`,
  )
  console.log(`wrote volatility.sql, before.sql, after.sql, volume.sql, rollback-0362.sql from ${hunks.length} hunks over ${CUT.length} bodies`)
}
