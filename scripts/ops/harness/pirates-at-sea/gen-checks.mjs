// gen-checks.mjs: writes hunks.sql (a prod check) and rollback-0445.sql (a draft) from the hunks of migration 0445 itself, so they cannot drift from the file.
//   node scripts/ops/harness/pirates-at-sea/gen-checks.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const HERE = path.dirname(fileURLToPath(import.meta.url))
const MIG = path.resolve(HERE, '../../../../supabase/migrations/20260818000445_pirates_cruise_the_sea.sql')
const s = readFileSync(MIG, 'utf8').replaceAll('\r', '')
const re = /\('((?:public|world|voyage|cmd)\.[a-z_]+\([^']*\))', (\d+),\n\$h\$([\s\S]*?)\$h\$,\n\$h\$([\s\S]*?)\$h\$\)/g
const hunks = []
for (let x; (x = re.exec(s)); ) hunks.push({ fn: x[1], ord: Number(x[2]), old: x[3], neu: x[4] })
if (hunks.length !== 10) throw new Error(`hunks ${hunks.length}, 10 expected`)
const fns = [...new Set(hunks.map((h) => h.fn))]
const count = (hay, needle) => hay.split(needle).length - 1
const afterWanted = hunks.map((h) => `${h.fn.replace(/^public\.|\(.*$/g, '')} ${h.ord}: ${count(h.neu, h.old)}`).join(', ')

const check = `-- 0445 PROD CHECK, BEFORE the deploy (and after it): every hunk 0445 cuts occurs EXACTLY ONCE in the live body it cuts, nothing of 0445 is there yet,
-- and the self-assert probe's SELECTION (CLAUDE.md: a migration's selections run read-only on prod first). GENERATED by gen-checks.mjs.
--   npx --yes supabase@2.120.0 db query --linked --output-format json -f scripts/ops/harness/pirates-at-sea/hunks.sql
-- Run scripts/ops/harness/db-health/gate.sql first. ONE statement, read-only: the catalog (pg_get_functiondef of six functions), public.world_config by
-- key, and public.pirate_ships (~121 rows) with each one's fleet and ships by key; stable functions only (public.pirate_ord_wanted, public.pirate_haunt_of).
-- BEFORE, wanted: ok true (every \`n\` 1); applied false; knobs.pirate_strike_tries_per_run 8; probe.fleet not null (a pirate lying free in a harbour,
--   her ord wanted, a haunt in reach of her home: the probe borrows her inside a block it rolls back).
-- AFTER, wanted: applied true; hunks {${afterWanted}} (an old text that stands inside its new text still counts 1).
begin transaction read only;
with h (fn, ord, old) as (values
${hunks.map((h) => `  ('${h.fn}', ${h.ord}, $h$${h.old}$h$)`).join(',\n')}
), body as (
  select f.fn, replace(pg_get_functiondef(f.fn::regprocedure), E'\\r', '') as def
    from (values ${fns.map((f) => `('${f}')`).join(', ')}) f(fn)
), n as (
  select h.fn, h.ord, (length(b.def) - length(replace(b.def, h.old, ''))) / length(h.old) as n from h join body b on b.fn = h.fn
), pr as (
  select x.fleet_id, x.ord, p.code as home, f.status
    from public.pirate_ships x join public.fleets f on f.id = x.fleet_id join public.ports p on p.id = x.home_port
   where x.laid_up_at is null and x.unpaid_since is null and x.wrecked_at is null and f.status = 'DOCKED' and f.busy_until is null
     and public.pirate_ord_wanted(x.ord)
     and exists (select 1 from public.ships s where s.fleet_id = x.fleet_id and s.durability > 0)
     and exists (select 1 from public.pirate_haunt_of(x.home_port, x.ord))
   order by x.ord limit 1
)
select jsonb_build_object(
  'at', now(),
  'head', (select max(m.version) from supabase_migrations.schema_migrations m),
  'ok', (select bool_and(n.n = 1) from n),
  'hunks', (select jsonb_agg(jsonb_build_object('fn', n.fn, 'ord', n.ord, 'n', n.n) order by n.fn, n.ord) from n),
  'bodies', (select jsonb_object_agg(b.fn, md5(b.def)) from body b),
  'applied', to_regprocedure('public.pirate_cruise_plan(uuid,uuid)') is not null,
  'knobs', (select jsonb_object_agg(w.key, w.value) from public.world_config w
             where w.key in ('pirate_cruise_nm', 'pirate_cruise_courses', 'pirate_port_minutes', 'pirate_refit_below', 'pirate_sails_per_run', 'pirate_strike_from_port',
                             'pirate_strike_tries_per_run', 'pirate_haunt_hours', 'pirates_bite', 'pirates_trade', 'attack_enabled', 'city_treasury_enabled')),
  'probe', (select jsonb_build_object('fleet', pr.fleet_id, 'ord', pr.ord, 'home', pr.home, 'status', pr.status) from pr),
  'pirate_ships', (select count(*) from public.pirate_ships)
) as r;
commit;
`
writeFileSync(path.join(HERE, 'hunks.sql'), check)

const back = `-- 0445 FORWARD ROLLBACK, A DRAFT. NOT a prod check and NOT a migration yet: to use it, strip the guard line, give it the next number and deploy it as any
-- migration (owner only). GENERATED by gen-checks.mjs from the file's own hunks.
-- THE FAST LEVERS NEED NO MIGRATION (knob writes, owner only): \`pirate_strike_from_port\` true (a pirate lying in a harbour raids again) and
--   \`pirate_port_minutes\` 720 (the twelve-hour lie: within an hour most pirates lie at a harbour again); \`pirate_cruise_nm\` 0 makes a cruise one lane.
-- THE DRAFT reverses the ten hunks, last first (each hunk's NEW text must occur once in the live body, else it refuses: a later file re-cut the
--   same lines and the draft is stale), then takes out the three functions and the six knobs and puts pirate_strike_tries_per_run back to 8 (only from 16).
--   A pirate under sail on a cruise finishes it (her voyage is a voyage like any other) and is then stepped by 0339's rule: she lies pirate_haunt_hours.
--   Proof 147 must be withdrawn and the one 0445 line taken out of proofs 128, 133, 136 and 137 (and 114's PT_JOB put back) with the same PR.
-- LOCAL PGlite WORLD ONLY while it carries this line (scripts/ops/harness/README.md): it writes. The first statement refuses a real server.
do $$ begin if inet_server_addr() is not null then raise exception 'local PGlite world only: this scene writes'; end if; end $$;
do $r$
declare
  h      record;
  v_def  text;
  v_n    int;
begin
  perform set_config('statement_timeout', '20s', true);
  perform set_config('lock_timeout', '5s', true);
  create temp table back_0445 (fn text, ord int, new text, old text) on commit drop;
  insert into back_0445 values
${hunks.map((h) => `  ('${h.fn}', ${h.ord},\n$h$${h.neu}$h$,\n$h$${h.old}$h$)`).join(',\n')};
  for h in select * from back_0445 order by fn, ord desc loop
    v_def := replace(pg_get_functiondef(h.fn::regprocedure), E'\\r', '');
    v_n := (length(v_def) - length(replace(v_def, h.new, ''))) / length(h.new);
    if v_n <> 1 then
      raise exception 'rollback 0445 refuses: hunk % of % occurs % time(s) in the live body, not once', h.ord, h.fn, v_n;
    end if;
    execute replace(v_def, h.new, h.old);
  end loop;
  if exists (select 1 from back_0445 b where position('0445' in pg_get_functiondef(b.fn::regprocedure)) > 0) then
    raise exception 'rollback 0445 FAIL: something of 0445 is left in the six bodies';
  end if;
  drop function public.pirate_trader_step(uuid, timestamptz, jsonb);
  drop function public.pirate_cruise_plan(uuid, uuid);
  drop function public.pirate_hurt(uuid);
  delete from public.world_config where key in ('pirate_cruise_nm', 'pirate_cruise_courses', 'pirate_port_minutes', 'pirate_refit_below', 'pirate_sails_per_run', 'pirate_strike_from_port');
  update public.world_config set value = to_jsonb(8) where key = 'pirate_strike_tries_per_run' and value = to_jsonb(16);
  raise notice 'rollback 0445 ok: the ten hunks reversed, three functions and six knobs gone; md5 %', (select jsonb_object_agg(b.fn, md5(replace(pg_get_functiondef(b.fn::regprocedure), E'\\r', ''))) from (select distinct fn from back_0445) b);
end $r$;
`
writeFileSync(path.join(HERE, 'rollback-0445.sql'), back)
console.log('written: hunks.sql, rollback-0445.sql;', hunks.length, 'hunks; after wants', afterWanted)
