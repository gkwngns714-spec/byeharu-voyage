// gen-checks.mjs — writes before.sql, after.sql and volatility.sql (the PROD CHECKS of 0343) from the migration's own hunks, so the texts they test are the very texts the file applies.
//   node scripts/ops/harness/city-reserve/gen-checks.mjs
// Each output is ONE read-only statement inside begin transaction read only ... commit (docs/OPS_HEALTH.md; CLAUDE.md): npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/city-reserve/before.sql
// Every function called is STABLE or IMMUTABLE (pg_get_functiondef, to_regprocedure, replace, md5, treasury_balance, city_capital, city_aid_target, wc_num, the new readers once they exist); volatility.sql prints it first.
// No big table is read: ports (249 rows), port_treasury (249), world_config and the catalog only.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const HERE = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))
const sql = readFileSync(path.join(HERE, '..', '..', '..', '..', 'supabase', 'migrations', '20260818000343_city_reserve.sql'), 'utf8').replaceAll('\r', '')
const start = sql.indexOf('insert into hunks_0343 values')
if (start < 0) throw new Error('no hunks in the migration')
const block = sql.slice(start, sql.indexOf('for v_h in select h.fn from hunks_0343'))
const hunks = [...block.matchAll(/\('([^']+)', (\d+),\n\$h\$([\s\S]*?)\$h\$,\n\$h\$([\s\S]*?)\$h\$\)/g)].map((m) => ({ fn: m[1], ord: Number(m[2]), old: m[3], new: m[4] }))
if (hunks.length !== 5) throw new Error(`${hunks.length} hunks parsed, the migration has 5`)
for (const h of hunks) if (h.old.includes('$h$') || h.new.includes('$h$')) throw new Error('a hunk holds the dollar tag')

const values = hunks.map((h) => `  ('${h.fn}'::text, ${h.ord}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')

const head = (name, what) => `-- 0343 PROD CHECK (${name}), read-only, ONE statement: npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/city-reserve/${name}.sql
-- ${what}
-- Generated by scripts/ops/harness/city-reserve/gen-checks.mjs from the migration's own hunks. Every function called is STABLE or IMMUTABLE (run volatility.sql first; it prints provolatile of each). No big table is read.
begin transaction read only;
with h(fn, ord, old, new) as (values
${values}
), per_hunk as (
  select h.fn, h.ord,
         (length(d.def) - length(replace(d.def, h.old, ''))) / length(h.old) as old_times,
         (length(d.def) - length(replace(d.def, h.new, ''))) / length(h.new) as new_times
    from h
    cross join lateral (select to_regprocedure(h.fn) as oid) o
    cross join lateral (select replace(pg_get_functiondef(o.oid), E'\\r', '') as def) d
), bodies as (
  select f.fn, replace(pg_get_functiondef(to_regprocedure(f.fn)), E'\\r', '') as def
    from (select distinct h.fn from h) f
), applied as (
  -- the hunks of one function applied in ord order to its live body (a recursive walk: no second copy of the apply loop's rule)
  with recursive w(fn, ord, def) as (
    select b.fn, 0, b.def from bodies b
    union all
    select w.fn, h.ord, replace(w.def, h.old, h.new) from w join h on h.fn = w.fn and h.ord = w.ord + 1
  )
  select w.fn, w.def from w where w.ord = (select max(h.ord) from h where h.fn = w.fn)
), removed as (
  with recursive r(fn, ord, def) as (
    select b.fn, (select max(h.ord) from h where h.fn = b.fn) + 1, b.def from bodies b
    union all
    select r.fn, h.ord, replace(r.def, h.new, h.old) from r join h on h.fn = r.fn and h.ord = r.ord - 1
  )
  select r.fn, r.def from r where r.ord = 1
), x as (
  select b.fn,
         md5(b.def) as now_md5,
         md5(a.def) as with_hunks_md5,
         md5(r.def) as without_hunks_md5,
         (select jsonb_agg(jsonb_build_array(ph.ord, ph.old_times, ph.new_times) order by ph.ord) from per_hunk ph where ph.fn = b.fn) as times,
         md5(coalesce(p.proacl::text, '') || p.provolatile::text || p.prosecdef::text || coalesce(p.proconfig::text, '') || p.proparallel::text || p.proowner::text || p.prolang::text) as attr_md5
    from bodies b join applied a on a.fn = b.fn join removed r on r.fn = b.fn
    join pg_proc p on p.oid = to_regprocedure(b.fn)
), k as (
  -- the live world's figures, read, never written: what the switch would do today (the formula inline before the deploy; the reader itself after it)
  select p.id, p.code, p.size_tier, coalesce(t.reserve, 0) as reserve, public.treasury_balance(p.id) as bal, public.city_capital(p.id) as cap,
         case when public.city_capital(p.id) is null then 'no_crown' when public.city_capital(p.id) = p.id then 'capital' else 'city' end as cls,
         p.size_tier * 100000 * case when public.city_capital(p.id) = p.id then 5 else 1 end as size_d
    from public.ports p left join public.port_treasury t on t.port_id = p.id
   where p.kind = 'HARBOUR'
)`

const figures = `  'world', jsonb_build_object(
    'harbours', (select count(*) from k),
    'by_class', (select jsonb_object_agg(r.cls, jsonb_build_object('n', r.n, 'under_50k', r.u50, 'under_size', r.us, 'gap_to_size', r.gap)) from (
       select k.cls, count(*) as n, count(*) filter (where k.bal < 50000) as u50, count(*) filter (where k.bal < greatest(k.reserve, k.size_d)) as us, sum(greatest(0, greatest(k.reserve, k.size_d) - k.bal)) as gap from k group by k.cls) r),
    'floor_knob', (select c.value from public.world_config c where c.key = 'treasury_reserve_floor'),
    'switches', (select jsonb_object_agg(c.key, c.value) from public.world_config c where c.key in ('city_treasury_enabled', 'economy_closed', 'convoys_enabled', 'convoy_rich_enabled', 'contract_wind_ms', 'contract_wind_posts')))`

const before = `${head('before', 'Wanted (head 0342, after the navy slice is deployed): every fns[].times entry [ord, 1, 0] except hunk 2 of tick_contract_wind, whose new text sits inside its old (it prints [2, 1, 1]); absent: all true; dark_parity_rows the count of harbours (every target is 0306\'s formula: it is the formula before the deploy). now_md5 / with_hunks_md5 / attr_md5 are the pre-image: after.sql must print now_md5 = this with_hunks_md5 and without_hunks_md5 = this now_md5. world: the live figures, read for the dev-log.')}
select jsonb_build_object(
  'head', (select max(version) from supabase_migrations.schema_migrations),
  'fns', (select jsonb_agg(jsonb_build_object('fn', x.fn, 'times', x.times, 'now_md5', x.now_md5, 'with_hunks_md5', x.with_hunks_md5, 'attr_md5', x.attr_md5) order by x.fn) from x),
  'absent', jsonb_build_object(
    'city_reserve_on', to_regprocedure('public.city_reserve_on()') is null,
    'city_default_reserve', to_regprocedure('public.city_default_reserve(uuid)') is null,
    'city_floor', to_regprocedure('public.city_floor(uuid)') is null,
    'knobs', not exists (select 1 from public.world_config c where c.key in ('city_reserve_enabled', 'city_reserve_per_tier', 'city_reserve_capital_mult'))),
  'dark_parity_rows', (select count(*) from k where public.city_aid_target(k.id) = greatest(k.reserve, round(public.wc_num('treasury_reserve_floor')))::bigint),
${figures}
) as before;
commit;
`

const after = `${head('after', 'Wanted (head 0343): every fns[].times entry [ord, 0, 1] except hunk 2 of tick_contract_wind ([2, 0, 1] as well: its old text is gone); now_md5 = before\'s with_hunks_md5 and without_hunks_md5 = before\'s now_md5; attr_md5 equal to before\'s; present all true; switch false; city_reserve_on false; knobs 100000 and 5; dark_parity_rows = harbours (the floor is the knob and the target is 0306\'s formula at every harbour); wind_reads_floor true; readers_server_only true; sizes: the formula at a tier-2 city, a tier-5 capital and the pirates\' capital (read, not written).')}
select jsonb_build_object(
  'head', (select max(version) from supabase_migrations.schema_migrations),
  'fns', (select jsonb_agg(jsonb_build_object('fn', x.fn, 'times', x.times, 'now_md5', x.now_md5, 'without_hunks_md5', x.without_hunks_md5, 'attr_md5', x.attr_md5) order by x.fn) from x),
  'present', jsonb_build_object(
    'city_reserve_on', to_regprocedure('public.city_reserve_on()') is not null,
    'city_default_reserve', to_regprocedure('public.city_default_reserve(uuid)') is not null,
    'city_floor', to_regprocedure('public.city_floor(uuid)') is not null),
  'switch', (select c.value from public.world_config c where c.key = 'city_reserve_enabled'),
  'city_reserve_on', public.city_reserve_on(),
  'knobs', (select jsonb_object_agg(c.key, c.value) from public.world_config c where c.key like 'city_reserve%'),
  'dark_parity_rows', (select count(*) from k where public.city_floor(k.id) = round(public.wc_num('treasury_reserve_floor'))::bigint
                                                and public.city_aid_target(k.id) = greatest(k.reserve, round(public.wc_num('treasury_reserve_floor')))::bigint),
  'wind_reads_floor', (select d like '%>= public.city_floor(p.id)%' and d not like '%v_floor%' from (select pg_get_functiondef('public.tick_contract_wind(boolean,uuid)'::regprocedure) as d) z),
  'readers_server_only', not exists (select 1 from unnest(array['public.city_reserve_on()', 'public.city_default_reserve(uuid)', 'public.city_floor(uuid)']) f
                                        where has_function_privilege('anon', f, 'execute') or has_function_privilege('authenticated', f, 'execute')),
  'sizes', (select jsonb_object_agg(k.code, jsonb_build_array(k.cls, k.size_tier, public.city_default_reserve(k.id), k.size_d)) from k
             where k.id in ((select id from k where cls = 'city' and size_tier = 2 order by code limit 1), (select id from k where cls = 'capital' and size_tier = 5 order by code limit 1), (select id from k where cls = 'no_crown' order by bal desc limit 1))),
${figures}
) as after;
commit;
`

const volatility = `-- 0343 PROD CHECK (volatility), read-only, ONE statement: run it BEFORE before.sql and after.sql. Prints provolatile of every function they call; wanted: all 's' or 'i' (the new readers are null before the deploy, 's' after).
begin transaction read only;
select jsonb_object_agg(f.fn, (select p.provolatile::text from pg_proc p where p.oid = to_regprocedure(f.fn))) as provolatile
  from (values ('pg_get_functiondef(oid)'), ('to_regprocedure(text)'), ('replace(text,text,text)'), ('md5(text)'), ('has_function_privilege(name,text,text)'),
               ('public.treasury_balance(uuid)'), ('public.city_capital(uuid)'), ('public.city_aid_target(uuid)'), ('public.wc_num(text)'),
               ('public.city_reserve_on()'), ('public.city_default_reserve(uuid)'), ('public.city_floor(uuid)')) f(fn);
commit;
`

writeFileSync(path.join(HERE, 'before.sql'), before)
writeFileSync(path.join(HERE, 'after.sql'), after)
writeFileSync(path.join(HERE, 'volatility.sql'), volatility)
console.log(`wrote before.sql, after.sql, volatility.sql from ${hunks.length} hunks over ${new Set(hunks.map((h) => h.fn)).size} functions`)
