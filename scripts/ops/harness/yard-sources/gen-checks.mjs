// Writes before-hunks.sql and after-hunks.sql for 0358 from the migration's OWN hunks, so the checks cannot drift from the file that deploys.
//   node scripts/ops/harness/yard-sources/gen-checks.mjs
// Both outputs are PROD CHECKS: one statement inside `begin transaction read only` … `commit`, reading the catalog only.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..', '..', '..', '..')
const sql = readFileSync(path.join(ROOT, 'supabase', 'migrations', '20260818000358_the_yard_plans_the_build.sql'), 'utf8').replaceAll('\r', '')
const from = sql.indexOf('insert into hunks_0358 values')
const to = sql.indexOf('v_def := v_pre;', from)
if (from < 0 || to < 0) throw new Error('the hunks of 0358 were not found')
const hunks = [...sql.slice(from, to).matchAll(/\((\d+),\n\$h\$([\s\S]*?)\$h\$,\n\$h\$([\s\S]*?)\$h\$\)/g)].map((m) => ({ n: Number(m[1]), old: m[2], new: m[3] }))
if (hunks.length !== 3) throw new Error(`expected 3 hunks, read ${hunks.length}`)

const values = hunks.map((h) => `  (${h.n}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')
const body = (when, wanted) => `-- 0358 PROD CHECK (${when}), read-only, ONE statement: npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/yard-sources/${when}-hunks.sql
-- ${wanted}
-- Generated by scripts/ops/harness/yard-sources/gen-checks.mjs from the migration's own hunks. Only the catalog is read.
begin transaction read only;
with h(ord, old, new) as (values
${values}),
live as (select replace(pg_get_functiondef('world.yard_sources(uuid,text)'::regprocedure), E'\\r', '') as def)
select h.ord,
       (length(live.def) - length(replace(live.def, h.old, ''))) / length(h.old) as old_times,
       (length(live.def) - length(replace(live.def, h.new, ''))) / length(h.new) as new_times,
       (select p.provolatile::text || ':' || p.prosecdef::text || ':' || coalesce(p.proconfig::text, '') || ':' || coalesce(p.proacl::text, '')
          from pg_proc p where p.oid = 'world.yard_sources(uuid,text)'::regprocedure) as volatility_definer_config_acl,
       md5(live.def) as body_md5,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from h cross join live
 order by h.ord;
commit;
`
writeFileSync(
  path.join(HERE, 'before-hunks.sql'),
  body('before', 'Wanted: 3 rows; every old_times 1 and new_times 0; volatility s, definer true, search_path public, pg_temp, ACL postgres and authenticated only; head = the migration before 0358 in the deploy order.'),
)
writeFileSync(
  path.join(HERE, 'after-hunks.sql'),
  body('after', 'Wanted: 3 rows; every new_times 1 and old_times 0; volatility, definer, config and ACL exactly as before-hunks.sql printed them; head 20260818000358.'),
)
console.log('wrote before-hunks.sql and after-hunks.sql (3 hunks)')
