// gen-checks.mjs: writes the PROD CHECK files that carry 0357's hunks (before.sql, after.sql) and the forward rollback draft
// (rollback-0357.sql) from the migration's own text, so the texts checked on prod are the texts the migration cuts; and, with
// --proof, prints the same hunks as the rows proof 60 holds (scripts/db/proofs/60_live_rounds.sql rebuilds the old bodies from
// them). LOCAL ONLY; not in CI.
//   node scripts/ops/harness/live-rounds/gen-checks.mjs [--proof]
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const MIG = path.resolve(HERE, '../../../../supabase/migrations/20260818000357_a_battle_is_fought_round_by_round.sql')
const sql = readFileSync(MIG, 'utf8').replaceAll('\r', '')
const ENG = 'public.fight_sides(uuid,integer,jsonb,jsonb,jsonb)'
const re = /\((c_eng|'[a-z_.]+\([a-z ,]*\)'), (\d+),\n\$o\$([\s\S]*?)\$o\$,\n\$n\$([\s\S]*?)\$n\$\)/g
export const hunks = [...sql.matchAll(re)].map((m) => ({
  fn: m[1] === 'c_eng' ? ENG : m[1].slice(1, -1),
  n: Number(m[2]),
  old: m[3],
  new: m[4],
}))
export const HUNKS = 23
if (hunks.length !== HUNKS) throw new Error(`expected ${HUNKS} hunks in the migration, found ${hunks.length}`)
for (const h of hunks) if (h.old.includes('$h$') || h.new.includes('$h$')) throw new Error('a hunk holds the quote tag')

export const CUT = [...new Set(hunks.map((h) => h.fn))]
export const NEW_FNS = [
  'voyage.hold_free_hours(uuid)',
  'voyage.hold_cut(uuid,timestamp with time zone,timestamp with time zone)',
  'public.battle_opening_stance(uuid)',
  'public.battle_stance_at(uuid,uuid,timestamp with time zone)',
  'public.battle_sheet_freeze(uuid,timestamp with time zone)',
  'public.battle_fight(uuid,integer)',
  'public.battle_advance(uuid,timestamp with time zone)',
  'public.battle_log(jsonb,jsonb,text)',
  'cmd.battle_stance(uuid,text)',
  'world.battle(uuid)',
]

if (process.argv.includes('--proof-write')) {
  // the rows of proof 60, written between its two marker lines
  const PROOF = path.resolve(HERE, '../../../db/proofs/60_live_rounds.sql')
  const text = readFileSync(PROOF, 'utf8').replaceAll('\r', '')
  const rows = hunks.map((h) => `  ('${h.fn}', ${h.n}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')
  const at = text.indexOf('-- hunks:begin\n')
  const to = text.indexOf('-- hunks:end\n')
  if (at < 0 || to < at) throw new Error('proof 60 has no hunk markers')
  writeFileSync(PROOF, text.slice(0, at) + '-- hunks:begin\n' + rows + '\n' + text.slice(to))
  console.log(`wrote ${hunks.length} hunks into proof 60`)
  process.exit(0)
}
if (process.argv.includes('--proof')) {
  console.log(hunks.map((h) => `  ('${h.fn}', ${h.n}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n'))
  process.exit(0)
}

if (path.resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  const values = hunks.map((h) => `  ('${h.fn}'::text, ${h.n}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')
  const cte = `with h(fn, ord, old, new) as (values\n${values}\n), d as (\n  select h.*, replace(pg_get_functiondef(to_regprocedure(h.fn)), chr(13), '') as def from h\n)`
  const run = (f) => `npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/live-rounds/${f}`
  const fnArr = `array[${NEW_FNS.map((f) => `'${f}'`).join(', ')}]`
  const bodies = `array[${CUT.map((f) => `'${f}'`).join(', ')}]`
  const made = `(select count(*) from unnest(${fnArr}) f where to_regprocedure(f) is not null)
         + (case when to_regclass('public.battle_rounds') is null then 0 else 1 end) + (case when to_regclass('public.battle_stances') is null then 0 else 1 end)
         + (select count(*) from pg_attribute a where a.attrelid = 'public.battles'::regclass and a.attname in ('sheet', 'round_seconds', 'rounds_done', 'next_round_at') and not a.attisdropped)
         + (select count(*) from public.world_config c where c.key = 'battle_round_seconds')`

  writeFileSync(
    path.join(HERE, 'before.sql'),
    `-- 0357 PROD CHECK (before), read-only, ONE statement: ${run('before.sql')}
-- Wanted: ${HUNKS} rows; every old_times 1 and new_times 0; made 0 (no table, column, function or knob of 0357 yet); attack false (the file refuses a lit world);
-- battles 0 and holds 0 (no battle was ever opened on prod, and no voyage carries a hold's row: the day count's hunk then moves nothing); head = the migration before this one.
-- Keep \`bodies\` (each cut body's md5): the dev-log holds the local values at head 0353; public.client_rpc_entry_points moves with 0354, 0355 and 0356 and need not match.
-- Generated by scripts/ops/harness/live-rounds/gen-checks.mjs from the migration's own hunks. Only the catalog, one knob and whether a battle or a hold row exists are read.
begin transaction read only;
${cte}
select fn, ord,
       (length(def) - length(replace(def, old, ''))) / length(old) as old_times,
       (length(def) - length(replace(def, new, ''))) / length(new) as new_times,
       ${made} as made,
       public.attack_on() as attack,
       (select count(*) from (select 1 from public.battles limit 5) q) as battles,
       (select count(*) from (select 1 from public.voyage_events ve where ve.kind = 'BATTLE' limit 5) q) as holds,
       (select jsonb_object_agg(f, md5(replace(pg_get_functiondef(to_regprocedure(f)), chr(13), ''))) from unnest(${bodies}) f) as bodies,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from d order by fn, ord;
commit;
`,
  )

  writeFileSync(
    path.join(HERE, 'after.sql'),
    `-- 0357 PROD CHECK (after), read-only, ONE statement: ${run('after.sql')}
-- Wanted: ${HUNKS} rows; every new_times 1; made 17 (10 functions, 2 tables, 4 columns, 1 knob); client_fns 2 (the two doors, authenticated only) and anon_fns 0; doors 2 (each
-- registered once); tables "rls, no client"; attack false; battles 0, rounds 0, stances 0, holds 0; knobs {"battle_round_seconds": 60, "battle_seconds": 600};
-- pvp "both refusals stand"; head 20260818000357. Keep \`bodies\` (the new md5 of each cut body).
-- Generated by scripts/ops/harness/live-rounds/gen-checks.mjs from the migration's own hunks. The catalog, two knobs and whether one row exists in four tables are read.
begin transaction read only;
${cte}
select fn, ord,
       (length(def) - length(replace(def, new, ''))) / length(new) as new_times,
       ${made} as made,
       (select count(*) from unnest(${fnArr}) f where has_function_privilege('authenticated', to_regprocedure(f), 'execute')) as client_fns,
       (select count(*) from unnest(${fnArr}) f where has_function_privilege('anon', to_regprocedure(f), 'execute')) as anon_fns,
       (select count(*) from public.client_rpc_entry_points() e where e.fn in (to_regprocedure('cmd.battle_stance(uuid,text)'), to_regprocedure('world.battle(uuid)'))) as doors,
       (select string_agg(distinct case when c.relrowsecurity and not has_table_privilege('anon', c.oid, 'select,insert,update,delete')
                                             and not has_table_privilege('authenticated', c.oid, 'select,insert,update,delete') then 'rls, no client' else 'OPEN' end, ', ')
          from pg_class c where c.oid in (to_regclass('public.battle_rounds'), to_regclass('public.battle_stances'))) as tables,
       public.attack_on() as attack,
       (select count(*) from (select 1 from public.battles limit 5) q) as battles,
       (select count(*) from (select 1 from public.battle_rounds limit 5) q) as rounds,
       (select count(*) from (select 1 from public.battle_stances limit 5) q) as stances,
       (select count(*) from (select 1 from public.voyage_events ve where ve.kind = 'BATTLE' limit 5) q) as holds,
       (select jsonb_object_agg(c.key, c.value order by c.key) from public.world_config c where c.key in ('battle_round_seconds', 'battle_seconds')) as knobs,
       case when (select p.prosrc from pg_proc p where p.oid = to_regprocedure('public.battle_open(text,uuid,uuid,timestamp with time zone)')) like '%E_HUMAN_TARGET: no player fights another player%'
             and (select p.prosrc from pg_proc p where p.oid = to_regprocedure('public.attack_for(uuid,uuid,uuid,integer,timestamp with time zone)')) like '%E_HUMAN_TARGET%no player attacks another player%'
            then 'both refusals stand' else 'A REFUSAL IS GONE' end as pvp,
       (select jsonb_object_agg(f, md5(replace(pg_get_functiondef(to_regprocedure(f)), chr(13), ''))) from unnest(${bodies}) f) as bodies,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from d order by fn, ord;
commit;
`,
  )

  // THE FORWARD ROLLBACK OF THE WHOLE SLICE, as a draft a new migration is cut from (owner only). It carries the same hunks, reversed.
  writeFileSync(
    path.join(HERE, 'rollback-0357.sql'),
    `-- 0357 FORWARD ROLLBACK, A DRAFT (docs/COMBAT_LOG.md 5.2; docs/dev-log/2026-11-12-live-rounds.md). NOT a prod check and NOT a migration yet: to use it, strip the guard line, give it the next
-- number, and deploy it as any migration (owner only). THE FIRST ROLLBACK IS THE SWITCH: attack_enabled false stops new battles and the stance door; a running battle finishes under its last stance.
-- This draft is the second: it refuses while a battle is FIGHTING, then swaps 0357's OLD and NEW (each NEW text once, reversed; judged as a round trip on the live body, since a later file
-- may have re-cut the same bodies) and drops what 0357 made: the ten functions, the two tables with their rows, the four columns, the index and the knob. Hold rows already written keep
-- \`free\`; with the day count's hunk gone they count as days again, as before 0357.
-- Tested locally: run.mjs --apply rollback-0357.sql before.sql prints every old_times 1, new_times 0, made 0 (dev-log).
-- Generated by scripts/ops/harness/live-rounds/gen-checks.mjs from the migration's own hunks.
-- LOCAL PGlite WORLD ONLY while it carries this line (scripts/ops/harness/README.md): it writes. The first statement refuses a real server (inet_server_addr() is not null there, null on PGlite).
do $$ begin if inet_server_addr() is not null then raise exception 'local PGlite world only: this scene writes'; end if; end $$;
do $r$
declare
  f      record;
  h      record;
  v_live text;
  v_def  text;
  v_back text;
begin
  perform set_config('statement_timeout', '45s', true);
  perform set_config('lock_timeout', '5s', true);
  if to_regprocedure('world.battle(uuid)') is null or to_regclass('public.battle_rounds') is null then
    raise exception '0357 rollback refuses: 0357 is not applied in this world';
  end if;
  if exists (select 1 from public.battles b where b.status = 'FIGHTING') then
    raise exception '0357 rollback refuses: a battle is being fought. Set attack_enabled false, wait for it to close, and deploy this again.';
  end if;
  create temp table hunks_back (fn text, n int, old text, new text) on commit drop;
  insert into hunks_back (fn, n, old, new) values
${hunks.map((h) => `  ('${h.fn}', ${h.n}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')};
  for f in select distinct x.fn from hunks_back x order by x.fn loop
    v_live := replace(pg_get_functiondef(f.fn::regprocedure), chr(13), '');
    v_def := v_live;
    for h in select * from hunks_back x where x.fn = f.fn order by x.n desc loop
      if (length(v_def) - length(replace(v_def, h.new, ''))) / length(h.new) <> 1 then
        raise exception '0357 rollback: hunk % of % is not in the live body exactly once: the deployed body is not the one 0357 left', h.n, f.fn;
      end if;
      v_def := replace(v_def, h.new, h.old);
    end loop;
    v_back := v_def;
    for h in select * from hunks_back x where x.fn = f.fn order by x.n loop
      v_back := replace(v_back, h.old, h.new);
    end loop;
    if v_back is distinct from v_live then
      raise exception '0357 rollback: % does not come back to the live body when the hunks are put back', f.fn;
    end if;
    execute v_def;
  end loop;
  drop function cmd.battle_stance(uuid, text);
  drop function world.battle(uuid);
  drop function public.battle_log(jsonb, jsonb, text);
  drop function public.battle_advance(uuid, timestamp with time zone);
  drop function public.battle_fight(uuid, integer);
  drop function public.battle_sheet_freeze(uuid, timestamp with time zone);
  drop function public.battle_stance_at(uuid, uuid, timestamp with time zone);
  drop function public.battle_opening_stance(uuid);
  drop function voyage.hold_cut(uuid, timestamp with time zone, timestamp with time zone);
  drop function voyage.hold_free_hours(uuid);
  drop table public.battle_rounds;
  drop table public.battle_stances;
  drop index public.battles_round_due;
  alter table public.battles drop column sheet, drop column round_seconds, drop column rounds_done, drop column next_round_at;
  delete from public.world_config c where c.key = 'battle_round_seconds';
  raise notice '0357 rollback ok: ${CUT.length} bodies at their pre-images, 10 functions, 2 tables, 4 columns, the index and the knob gone';
end
$r$;
`,
  )
  console.log(`wrote before.sql, after.sql and rollback-0357.sql (${HUNKS} hunks, ${CUT.length} bodies)`)
}
