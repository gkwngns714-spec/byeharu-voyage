// gen-checks.mjs: writes hunks.sql (a prod check) and rollback-0448.sql (a draft) from the hunks of migration 0448 itself, so they cannot drift
// from the file.
//   node scripts/ops/harness/stats-one/gen-checks.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const HERE = path.dirname(fileURLToPath(import.meta.url))
const MIG = path.resolve(HERE, '../../../../supabase/migrations/20260818000448_the_stats_count_once.sql')
const s = readFileSync(MIG, 'utf8').replaceAll('\r', '')
const re = /\('((?:public|world|voyage|cmd)\.[a-z_]+\([^']*\))', (\d+),\n\$h\$([\s\S]*?)\$h\$,\n\$h\$([\s\S]*?)\$h\$\)/g
const hunks = []
for (let x; (x = re.exec(s)); ) hunks.push({ fn: x[1], ord: Number(x[2]), old: x[3], neu: x[4] })
if (hunks.length !== 14) throw new Error(`hunks ${hunks.length}, 14 expected`)
const fns = [...new Set(hunks.map((h) => h.fn))]
if (fns.length !== 7) throw new Error(`bodies ${fns.length}, 7 expected`)

const check = `-- 0448 PROD CHECK, BEFORE the deploy (and after it): every hunk 0448 cuts occurs EXACTLY ONCE in the live body it cuts, nothing of 0448 is there
-- yet, and the self-assert probe's SELECTION (CLAUDE.md: a migration's selections run read-only on prod first). GENERATED by gen-checks.mjs.
--   npx --yes supabase@2.120.0 db query --linked --output-format json -f scripts/ops/harness/stats-one/hunks.sql
-- Run scripts/ops/harness/db-health/gate.sql first. ONE statement, read-only: the catalog (pg_get_functiondef of seven functions), and the probe's
-- selection: public.npc_fleets (~885 rows) with each one's fleet, route and ships by key, and the battles being fought. No function is called
-- but the catalog's.
-- BEFORE, wanted: ok true (every \`n\` 1); applied false; second_rule 3 (the three Stats bodies that each decide a state); probe.fleets 4 (four merchant fleets at sea or in port, with a route: the probe borrows
--   them inside a block it rolls back); newest_count not null (the row the file re-states once).
-- AFTER, wanted: applied true; every \`n\` 0 (no old text stands inside its new text); second_rule 0.
begin transaction read only;
with h (fn, ord, old) as (values
${hunks.map((h) => `  ('${h.fn}', ${h.ord}, $h$${h.old}$h$)`).join(',\n')}
), body as (
  select f.fn, replace(pg_get_functiondef(f.fn::regprocedure), E'\\r', '') as def
    from (values ${fns.map((f) => `('${f}')`).join(', ')}) f(fn)
), n as (
  select h.fn, h.ord, (length(b.def) - length(replace(b.def, h.old, ''))) / length(h.old) as n from h join body b on b.fn = h.fn
), pick as (
  -- the probe's selection, by the facts the census will read (the census itself is not there before the deploy)
  select nf.fleet_id
    from public.npc_fleets nf join public.fleets f on f.id = nf.fleet_id
   where nf.route_id is not null and f.status in ('SAILING', 'DOCKED', 'ANCHORED', 'REPAIRING')
     and not exists (select 1 from public.standing_routes r where r.id = nf.route_id and r.paused_reason = 'laid_up')
     and exists (select 1 from public.ships s where s.fleet_id = nf.fleet_id and s.durability > 0)
     and nf.fleet_id not in (select bs.fleet_id from public.battles b join public.battle_sides bs on bs.battle_id = b.id where b.status = 'FIGHTING')
   order by nf.fleet_id limit 4
)
select jsonb_build_object(
  'at', now(),
  'head', (select max(m.version) from supabase_migrations.schema_migrations m),
  'ok', (select bool_and(n.n = 1) from n),
  'hunks', (select jsonb_agg(jsonb_build_object('fn', n.fn, 'ord', n.ord, 'n', n.n) order by n.fn, n.ord) from n),
  'bodies', (select jsonb_object_agg(b.fn, md5(b.def)) from body b),
  'applied', to_regprocedure('public.fleet_tally()') is not null,
  'second_rule', (select count(*) from pg_proc p join pg_namespace ns on ns.oid = p.pronamespace
                   where ns.nspname in ('public', 'cmd', 'world', 'voyage') and p.prokind in ('f', 'p') and p.proname <> 'fleet_state_of'
                     and (ns.nspname, p.proname) not in (('public', 'merchant_doing_at'), ('world', 'report'))
                     and p.prosrc ~ $re$then\\s+'(sea|port|battle|laid_up|wrecked)'$re$),
  'probe', (select jsonb_build_object('fleets', count(*)) from pick),
  'newest_count', (select jsonb_build_object('slot', x.slot, 'at', x.at, 'lists', (select jsonb_object_agg(l.kind, l.at) from public.stats_fleet_list l))
                     from public.stats_fleets x order by x.slot desc limit 1)
) as r;
commit;
`
writeFileSync(path.join(HERE, 'hunks.sql'), check)

const back = `-- 0448 FORWARD ROLLBACK, A DRAFT. NOT a prod check and NOT a migration yet: to use it, strip the guard line, give it the next number and deploy it as
-- any migration (owner only). GENERATED by gen-checks.mjs from the file's own hunks.
-- THERE IS NO FAST LEVER: 0448 has no knob. It changes no play, only what the Stats faces read.
-- THE DRAFT reverses the fourteen hunks, last first (each hunk's NEW text must occur once in the live body, else it refuses: a later file re-cut
--   the same lines and the draft is stale), then drops the four functions. The stored rows need nothing: the next Stats count (within 15 minutes)
--   writes the fleets' row and the lists by the old rules again; until then the Merchants face reads no states (the old body reads them live).
--   THE CLIENT MUST GO BACK WITH IT (it reads \`battle\` and the Merchants face's new keys), and proof 150 and tests/stats.oneCount.spec.ts withdrawn.
-- LOCAL PGlite WORLD ONLY while it carries this line (scripts/ops/harness/README.md): it writes. The first statement refuses a real server.
do $$ begin if inet_server_addr() is not null then raise exception 'local PGlite world only: this scene writes'; end if; end $$;
do $r$
declare
  h      record;
  v_def  text;
  v_n    int;
begin
  perform set_config('statement_timeout', '20s', true);
  perform set_config('lock_timeout', '5s', true);
  create temp table back_0448 (fn text, ord int, new text, old text) on commit drop;
  insert into back_0448 values
${hunks.map((h) => `  ('${h.fn}', ${h.ord},\n$h$${h.neu}$h$,\n$h$${h.old}$h$)`).join(',\n')};
  for h in select * from back_0448 order by fn, ord desc loop
    v_def := replace(pg_get_functiondef(h.fn::regprocedure), E'\\r', '');
    v_n := (length(v_def) - length(replace(v_def, h.new, ''))) / length(h.new);
    if v_n <> 1 then
      raise exception 'rollback 0448 refuses: hunk % of % occurs % time(s) in the live body, not once', h.ord, h.fn, v_n;
    end if;
    execute replace(v_def, h.new, h.old);
  end loop;
  if exists (select 1 from back_0448 b where position('0448' in pg_get_functiondef(b.fn::regprocedure)) > 0) then
    raise exception 'rollback 0448 FAIL: something of 0448 is left in the seven bodies';
  end if;
  drop function public.fleet_tally();
  drop function public.fleet_state(uuid);
  drop function public.fleet_census(uuid);
  drop function public.fleet_state_of(boolean, boolean, boolean, boolean);
  raise notice 'rollback 0448 ok: the fourteen hunks reversed, four functions gone; md5 %', (select jsonb_object_agg(b.fn, md5(replace(pg_get_functiondef(b.fn::regprocedure), E'\\r', ''))) from (select distinct fn from back_0448) b);
end $r$;
`
writeFileSync(path.join(HERE, 'rollback-0448.sql'), back)
console.log('written: hunks.sql, rollback-0448.sql;', hunks.length, 'hunks over', fns.length, 'bodies')
