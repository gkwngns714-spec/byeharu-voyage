// gen-checks.mjs: writes before.sql, after.sql (the same read under two names) and rollback-0415.sql from the hunks of migration 0415 itself, so the checks cannot drift from the file.
//   node scripts/ops/harness/pirate-trade/gen-checks.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const HERE = path.dirname(fileURLToPath(import.meta.url))
const MIG = path.resolve(HERE, '../../../../supabase/migrations/20260818000415_a_pirate_ship_trades_and_no_wreck_waits_on_one_empty_purse.sql')
const s = readFileSync(MIG, 'utf8').replaceAll('\r', '')
const fns = ['public.pirate_ship_step(uuid,timestamp with time zone)', 'public.tick_pirates(timestamp with time zone)', 'public.capital_gift_roster(timestamp with time zone,uuid)',
  'public.capital_gift_one(timestamp with time zone,uuid)', 'public.npc_refit_step(uuid,timestamp with time zone)']
const re = /\((\d+), c_cut\[(\d)\],\n\$h\$([\s\S]*?)\$h\$,\n\$h\$([\s\S]*?)\$h\$\)/g
const hunks = []
for (let x; (x = re.exec(s)); ) hunks.push({ ord: Number(x[1]), fn: fns[x[2] - 1], old: x[3], neu: x[4] })
if (hunks.length !== 11) throw new Error(`hunks ${hunks.length}, 11 expected`)
const count = (hay, needle) => hay.split(needle).length - 1
const E = (t) => "E'" + t.replaceAll('\\', '\\\\').replaceAll("'", "''").replaceAll('\n', '\\n') + "'"
const afterWanted = hunks.map((h) => `${h.ord}: ${count(h.neu, h.old)}`).join(', ')

const check = (name) => `-- 0415 PROD CHECK, BEFORE the deploy AND AGAIN AFTER IT (the same read; before.sql and after.sql are one text), read-only, ONE statement. GENERATED by gen-checks.mjs.
--   npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/pirate-trade/${name}.sql
-- One row, one jsonb column \`r\`. It reads the catalog, nine cities' purses, the pirate fleets and their houses (hundreds of rows), the gift book for those houses and the refit waits. No scan of events, ledger or trades.
-- BEFORE, wanted: head 20260818000414; applied false; hunks: every count 1 (each old text once in the live body: prod's bodies are the pre-images, as the pirates' homes (PR #678) and 0410 leave them);
--   every \`volatility\` s or i. Write down ships, houses, cities, waits.
-- AFTER, wanted: head 20260818000415; applied true; hunks {${afterWanted}} (an old text that stands inside its new text still counts 1);
--   knobs.pirates_trade true, knobs.pirate_house_capital_pct 0.5, knobs.pirate_spend_day_pct unchanged.
--   Within the hour: houses.gifts_7d rises (each a house's capital; at most the day's room less the day's pay), houses.under_line falls. Within a cruise (pirate_haunt_hours at the haunt and two passages; the passages follow the served game day): ships.with_cargo above 0,
--   the hubs' purses in \`cities\` above 0. waits.others_over_3h should read {} from the second hourly refit run on (a merchant or navy wreck behind an empty home is paid for by her country).
--   houses.worth_less_gifts (purses plus cargo at cost, less every gift given) is what trading has made less what refits and wrecks have cost: watch it at +24 h and +7 d.
begin transaction read only;
with hk(ord, fn, old) as (values
${hunks.map((h) => `  (${h.ord}, '${h.fn}', ${E(h.old)})`).join(',\n')}
), body as (
  select f.fn, replace(pg_get_functiondef(f.fn::regprocedure), E'\\r', '') as def
    from (values ${fns.map((f) => `('${f}')`).join(', ')}) f(fn)
), fl as (
  select n.fleet_id, n.player_id, n.ord, n.home_port, n.laid_up_at, n.wrecked_at, f.status, public.fleet_stock_at_cost(n.fleet_id) as cargo,
         (select coalesce(sum(c.build_cost), 0) from public.ships s join public.ship_classes c on c.id = s.class_id where s.fleet_id = n.fleet_id) as build
    from public.pirate_ships n join public.fleets f on f.id = n.fleet_id
), ho as (
  select fl.player_id, sum(fl.build) as build, sum(fl.cargo) as cargo, bool_or(fl.laid_up_at is null) as at_work,
         (select pl.ducats from public.players pl where pl.id = fl.player_id) as ducats,
         (select count(*) from public.capital_gifts g where g.player_id = fl.player_id and g.created_at > now() - interval '7 days') as gifts_7d,
         (select coalesce(sum(g.ducats), 0) from public.capital_gifts g where g.player_id = fl.player_id) as gifted
    from fl group by fl.player_id
), k as (
  select coalesce((select (w.value)::text::numeric from public.world_config w where w.key = 'pirate_house_capital_pct'), 0.5) as cap_pct, public.wc_num('merchant_broke_pct') as broke_pct
)
select jsonb_build_object(
  'at', now(),
  'head', (select max(version) from supabase_migrations.schema_migrations),
  'applied', to_regprocedure('public.pirate_gift_pay(uuid,bigint,timestamp with time zone)') is not null,
  'hunks', (select jsonb_object_agg(hk.ord, (length(b.def) - length(replace(b.def, hk.old, ''))) / length(hk.old)) from hk join body b on b.fn = hk.fn),
  'bodies', (select jsonb_object_agg(b.fn, md5(b.def)) from body b),
  'volatility', (select jsonb_object_agg(p.oid::regprocedure::text, p.provolatile)
                   from pg_proc p where p.oid in ('public.fleet_stock_at_cost(uuid)'::regprocedure, 'public.pirate_hoard()'::regprocedure, 'public.pirate_spend_room(timestamp with time zone)'::regprocedure,
                                                  'public.treasury_balance(uuid)'::regprocedure, 'public.city_surplus(uuid)'::regprocedure, 'public.fleet_kind(uuid)'::regprocedure,
                                                  'public.pirate_nation()'::regprocedure, 'public.wc_num(text)'::regprocedure, 'public.economy_closed()'::regprocedure, 'public.pirates_on()'::regprocedure)),
  'knobs', (select jsonb_object_agg(w.key, w.value) from public.world_config w
             where w.key in ('pirates_trade', 'pirate_house_capital_pct', 'pirate_spend_day_pct', 'merchant_broke_pct', 'gift_max_per_week', 'gift_cooldown_hours', 'npc_refit_share',
                             'navy_upkeep_day', 'npc_refits_enabled', 'pirates_bite', 'npc_sell_margin', 'npc_min_return_pct', 'npc_lines_per_stop', 'pirate_haunt_hours')),
  'economy_closed', public.economy_closed(), 'pirates_on', public.pirates_on(),
  'hoard', public.pirate_hoard(), 'room_today', public.pirate_spend_room(now()),
  'spend_today', (select d.spent from public.pirate_spend_day d where d.day = (now() at time zone 'UTC')::date),
  'pay_left_today', (select count(*) filter (where fl.laid_up_at is null) * round(public.wc_num('navy_upkeep_day') / 24)
                            * ceil(extract(epoch from (date_trunc('day', now() at time zone 'UTC') + interval '1 day') - (now() at time zone 'UTC')) / 3600) from fl),
  'ships', (select jsonb_build_object('fleets', count(*), 'at_work', count(*) filter (where fl.laid_up_at is null), 'sailing', count(*) filter (where fl.status = 'SAILING'),
                                      'unable_to_sail', count(*) filter (where fl.status = 'UNABLE_TO_SAIL'), 'with_cargo', count(*) filter (where fl.cargo > 0), 'cargo_at_cost', coalesce(sum(fl.cargo), 0)) from fl),
  'houses', (select jsonb_build_object('n', count(*), 'capitals', coalesce(sum(round(k.cap_pct * ho.build)), 0), 'purses', coalesce(sum(ho.ducats), 0), 'with_a_purse', count(*) filter (where ho.ducats > 0),
                                       'under_line', count(*) filter (where ho.at_work and ho.ducats < k.cap_pct * ho.build * k.broke_pct),
                                       'gifts_7d', coalesce(sum(ho.gifts_7d), 0), 'gifts_7d_max_a_house', max(ho.gifts_7d), 'gifted_ever', coalesce(sum(ho.gifted), 0),
                                       'worth_less_gifts', coalesce(sum(ho.ducats + ho.cargo - ho.gifted), 0)) from ho cross join k),
  'cities', (select jsonb_object_agg(p.code, jsonb_build_object('purse', public.treasury_balance(p.id), 'surplus', public.city_surplus(p.id)))
               from public.port_allegiance a join public.ports p on p.id = a.port_id where a.nation_id = public.pirate_nation()),
  'waits', jsonb_build_object(
     'pirates', (select count(*) from public.npc_refit_waits w join public.pirate_ships n on n.fleet_id = w.fleet_id),
     'others', (select coalesce(jsonb_object_agg(x.kind, x.n), '{}'::jsonb) from (
        select public.fleet_kind(w.fleet_id) as kind, count(*) as n from public.npc_refit_waits w
         where not exists (select 1 from public.pirate_ships n where n.fleet_id = w.fleet_id) group by 1) x),
     'others_over_3h', (select coalesce(jsonb_object_agg(x.kind, x.n), '{}'::jsonb) from (
        select public.fleet_kind(w.fleet_id) as kind, count(*) as n from public.npc_refit_waits w
         where not exists (select 1 from public.pirate_ships n where n.fleet_id = w.fleet_id) and w.told_at < now() - interval '3 hours' group by 1) x))
) as r;
commit;
`
writeFileSync(path.join(HERE, 'before.sql'), check('before'))
writeFileSync(path.join(HERE, 'after.sql'), check('after'))

