// gen-checks.mjs: writes the PROD CHECK files that carry 0353's hunks (before.sql, after.sql) from the migration's own
// text, so the texts checked on prod are the texts the migration cuts; and, with --proof, prints the same hunks as the
// rows proof 56 holds (scripts/db/proofs/56_combat_log.sql puts the old bodies back from them). LOCAL ONLY; not in CI.
//   node scripts/ops/harness/combat-log/gen-checks.mjs [--proof]
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const MIG = path.resolve(HERE, '../../../../supabase/migrations/20260818000353_a_fight_keeps_its_log.sql')
const sql = readFileSync(MIG, 'utf8').replaceAll('\r', '')
const ENG = 'public.fight_sides(uuid,integer,jsonb,jsonb,jsonb)'
const SKIN = 'voyage.fight_resolve(uuid,integer,numeric,numeric,jsonb)'
const REP = 'voyage.raid_report(uuid,integer,numeric,numeric,jsonb,jsonb)'
const re = /\((c_eng|c_rep|'[a-z_.]+\([a-z ,]*\)'), (\d+),\n\$o\$([\s\S]*?)\$o\$,\n\$n\$([\s\S]*?)\$n\$\)/g
export const hunks = [...sql.matchAll(re)].map((m) => ({
  fn: m[1] === 'c_eng' ? ENG : m[1] === 'c_rep' ? REP : m[1].slice(1, -1),
  n: Number(m[2]),
  old: m[3],
  new: m[4],
}))
if (hunks.length !== 20) throw new Error(`expected 20 hunks in the migration, found ${hunks.length}`)
for (const h of hunks) if (h.old.includes('$h$') || h.new.includes('$h$')) throw new Error('a hunk holds the quote tag')

if (process.argv.includes('--proof')) {
  // the rows of proof 56: (the function the NEW text stands in, n, old, new)
  console.log(hunks.map((h) => `  ('${h.fn}', ${h.n}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n'))
  process.exit(0)
}

// imported (proof-0353.mjs reads `hunks`): nothing is written
if (path.resolve(process.argv[1] ?? '') !== fileURLToPath(import.meta.url)) {
  // an import only
} else {
// before the deploy the skin's hunks are read on voyage.fight_resolve (its live text); after it, on voyage.raid_report
const values = (at) =>
  hunks.map((h) => `  ('${h.fn === REP ? at : h.fn}'::text, '${h.fn}'::text, ${h.n}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')
const cte = (at) =>
  `with h(body, fn, ord, old, new) as (values\n${values(at)}\n), d as (\n  select h.*, replace(pg_get_functiondef(to_regprocedure(h.body)), chr(13), '') as def from h\n)`
const run = (f) => `npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/combat-log/${f}`
const NEW_FNS = `array['voyage.raid_report(uuid,integer,numeric,numeric,jsonb,jsonb)', 'voyage.raid_extras(jsonb,jsonb,jsonb,jsonb)', 'voyage.raid_opts(uuid,integer,uuid)', 'voyage.freeze_order(jsonb,uuid)', 'voyage.leg_order(jsonb)', 'public.raid_orders_on()', 'public.raid_payee(uuid)', 'public.raid_price(uuid)', 'public.raid_ransom(uuid,uuid,bigint)', 'public.fight_flee_chance(numeric)', 'cmd.raid_order(uuid,text)', 'world.raid_read(uuid)']`
const KNOBS = `c.key in ('raid_orders_enabled', 'fight_flee_base', 'fight_flee_floor')`
// the pre-images 0353 was cut against, by digest, AT THE DEPLOY (head 0352). A record only: nothing is held to them, a later migration may re-cut any of these bodies
const PRE = {
  'public.client_rpc_entry_points()': '04141692005b6e8a22b36c7483e576f9',
  'voyage.fight(uuid,integer,uuid,numeric)': 'a4694aca0f213537d184a319f7ef75d9',
  'voyage.settle(uuid,timestamp with time zone)': '7e3233a44e9ad1ba9fe17adae2f544ce',
  'public.fight_sides(uuid,integer,jsonb,jsonb,jsonb)': '2fd7ebc8a572ed14a792f72eeda9dd37',
  'voyage.fight_resolve(uuid,integer,numeric,numeric,jsonb)': '97bbb6d8cd557853e1e3246fcfba15fe',
  'voyage.depart(uuid,jsonb,uuid,uuid,timestamp with time zone)': 'd8cb03b14dddffb1adbacf1997a09e73',
  'voyage.fight_round_line(jsonb,integer,text,jsonb,numeric,text)': '3952c3fd7ca19295117a0d5886899a9b',
}
const BODIES =`array['${ENG}', '${SKIN}', 'voyage.fight_round_line(jsonb,integer,text,jsonb,numeric,text)', 'voyage.fight(uuid,integer,uuid,numeric)', 'voyage.depart(uuid,jsonb,uuid,uuid,timestamp with time zone)', 'voyage.settle(uuid,timestamp with time zone)', 'public.client_rpc_entry_points()']`

writeFileSync(
  path.join(HERE, 'before.sql'),
  `-- 0353 PROD CHECK (before), read-only, ONE statement: ${run('before.sql')}
-- Wanted: 20 rows; every old_times 1 and new_times 0 (the 7 rows named voyage.raid_report are read on voyage.fight_resolve's live text, which the skin is cut from);
-- made 0 (no table, function or knob of 0353 yet); head 20260818000352. Keep \`bodies\` (each cut body's md5): the dev-log holds the local values, and they must be the same text.
-- Generated by scripts/ops/harness/combat-log/gen-checks.mjs from the migration's own hunks. Only the catalog and world_config's keys are read.
begin transaction read only;
${cte(SKIN)}
select fn, ord,
       (length(def) - length(replace(def, old, ''))) / length(old) as old_times,
       (length(def) - length(replace(def, new, ''))) / length(new) as new_times,
       (select count(*) from unnest(${NEW_FNS}) f where to_regprocedure(f) is not null)
         + (case when to_regclass('public.fleet_raid_orders') is null then 0 else 1 end)
         + (select count(*) from public.world_config c where ${KNOBS}) as made,
       (select jsonb_object_agg(f, md5(replace(pg_get_functiondef(to_regprocedure(f)), chr(13), ''))) from unnest(${BODIES}) f) as bodies,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from d order by fn, ord;
commit;
`,
)

writeFileSync(
  path.join(HERE, 'after.sql'),
  `-- 0353 PROD CHECK (after), read-only, ONE statement: ${run('after.sql')}
-- Wanted: 20 rows; every new_times 1; fns 12, client_fns 2 (the two doors, authenticated only) and anon_fns 0; doors 2 (each registered once);
-- order_table "rls, no client"; order_rows false (the switch is off and no door has run); switch false; knobs
-- {"fight_flee_base":0.15,"fight_flee_floor":0.05,"raid_orders_enabled":false}; head 20260818000353. Keep \`bodies\` (the new md5 of each cut body).
-- Generated by scripts/ops/harness/combat-log/gen-checks.mjs from the migration's own hunks. The catalog, three knobs and whether one order row exists are read.
begin transaction read only;
${cte(REP)}
select fn, ord,
       (length(def) - length(replace(def, new, ''))) / length(new) as new_times,
       (select count(*) from unnest(${NEW_FNS}) f where to_regprocedure(f) is not null) as fns,
       (select count(*) from unnest(${NEW_FNS}) f where has_function_privilege('authenticated', to_regprocedure(f), 'execute')) as client_fns,
       (select count(*) from unnest(${NEW_FNS}) f where has_function_privilege('anon', to_regprocedure(f), 'execute')) as anon_fns,
       (select count(*) from public.client_rpc_entry_points() e where e.fn in (to_regprocedure('cmd.raid_order(uuid,text)'), to_regprocedure('world.raid_read(uuid)'))) as doors,
       (select case when c.relrowsecurity and not has_table_privilege('anon', c.oid, 'select,insert,update,delete')
                         and not has_table_privilege('authenticated', c.oid, 'select,insert,update,delete') then 'rls, no client' else 'OPEN' end
          from pg_class c where c.oid = to_regclass('public.fleet_raid_orders')) as order_table,
       exists (select 1 from public.fleet_raid_orders) as order_rows,
       public.raid_orders_on() as switch,
       (select jsonb_object_agg(c.key, c.value order by c.key) from public.world_config c where ${KNOBS}) as knobs,
       (select jsonb_object_agg(f, md5(replace(pg_get_functiondef(to_regprocedure(f)), chr(13), ''))) from unnest(${BODIES} || '${REP}'::text) f) as bodies,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from d order by fn, ord;
commit;
`,
)

// THE FORWARD ROLLBACK OF THE WHOLE SLICE, as a draft a new migration is cut from (owner only). It carries the same hunks, reversed.
writeFileSync(
  path.join(HERE, 'rollback-0353.sql'),
  `-- 0353 FORWARD ROLLBACK, A DRAFT (docs/COMBAT_LOG.md 5.1; docs/dev-log/2026-11-11-fight-log.md). NOT a prod check and NOT a migration yet: to use it, strip the guard line, give it the next
-- number, and deploy it as any migration (owner only). It swaps 0353's OLD and NEW: each cut body loses exactly what 0353 added (each NEW text once, reversed, judged as a round trip on the live body: no fixed digest, a later file may have re-cut it),
-- voyage.fight_resolve's body comes back from voyage.raid_report with its hunks reversed, and what 0353 made is dropped (the functions, the table with its order rows, the three knobs).
-- Days and reports already written keep their log: a client that knows the shape still draws them, and nothing on the server reads it.
-- THE LIGHTER ROLLBACK, FOR ORDERS ALONE: a migration that sets raid_orders_enabled false. voyage.leg_order then answers null, every frozen order is ignored at once and the door refuses.
-- Tested locally: run.mjs --apply rollback-0353.sql before.sql prints every old_times 1, new_times 0, made 0; on a chain with 0354 it runs the same.
-- Generated by scripts/ops/harness/combat-log/gen-checks.mjs from the migration's own hunks.
-- LOCAL PGlite WORLD ONLY while it carries this line (scripts/ops/harness/README.md): it writes. The first statement refuses a real server (inet_server_addr() is not null there, null on PGlite).
do $$ begin if inet_server_addr() is not null then raise exception 'local PGlite world only: this scene writes'; end if; end $$;
do $r$
declare
  f     record;
  h     record;
  v_live text;
  v_def  text;
  v_back text;
begin
  perform set_config('statement_timeout', '45s', true);
  perform set_config('lock_timeout', '5s', true);
  if to_regprocedure('${REP}') is null or to_regclass('public.fleet_raid_orders') is null then
    raise exception '0353 rollback refuses: 0353 is not applied in this world';
  end if;
  create temp table hunks_back (fn text, n int, old text, new text) on commit drop;
  insert into hunks_back (fn, n, old, new) values
${hunks.map((h) => `  ('${h.fn}', ${h.n}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')};
  -- every cut body back to its pre-image; voyage.raid_report reversed IS voyage.fight_resolve's old body, and replaces the one-line wrapper
  -- JUDGED BY THE HUNKS, as a round trip on the body as it is now (never by a fixed digest: a later migration may have re-cut any of these bodies, as 0354 did the registry):
  -- each NEW text once in the live body, reversed; each OLD text then once in the result; and putting the NEW texts back gives the live body again.
  for f in select distinct x.fn from hunks_back x order by x.fn loop
    v_live := replace(pg_get_functiondef(f.fn::regprocedure), chr(13), '');
    v_def := v_live;
    for h in select * from hunks_back x where x.fn = f.fn order by x.n desc loop
      if (length(v_def) - length(replace(v_def, h.new, ''))) / length(h.new) <> 1 then
        raise exception '0353 rollback: hunk % of % is not in the live body exactly once: a later migration re-cut the text 0353 added; cut this rollback again from the live body', h.n, f.fn;
      end if;
      v_def := replace(v_def, h.new, h.old);
    end loop;
    v_back := v_def;
    for h in select * from hunks_back x where x.fn = f.fn order by x.n loop
      if (length(v_back) - length(replace(v_back, h.old, ''))) / length(h.old) <> 1 then
        raise exception '0353 rollback: hunk % of %: its OLD text is not in the reversed body exactly once', h.n, f.fn;
      end if;
      v_back := replace(v_back, h.old, h.new);
    end loop;
    if v_back is distinct from v_live then
      raise exception '0353 rollback: % does not come back to the live body when the hunks are put back', f.fn;
    end if;
    execute v_def;
  end loop;
  drop function cmd.raid_order(uuid, text);
  drop function world.raid_read(uuid);
  drop function voyage.raid_opts(uuid, integer, uuid);
  drop function voyage.raid_report(uuid, integer, numeric, numeric, jsonb, jsonb);
  drop function voyage.raid_extras(jsonb, jsonb, jsonb, jsonb);
  drop function voyage.freeze_order(jsonb, uuid);
  drop function voyage.leg_order(jsonb);
  drop function public.raid_ransom(uuid, uuid, bigint);
  drop function public.raid_price(uuid);
  drop function public.raid_payee(uuid);
  drop function public.fight_flee_chance(numeric);
  drop function public.raid_orders_on();
  drop table public.fleet_raid_orders;
  delete from public.world_config c where ${KNOBS};
  raise notice '0353 rollback ok: 7 bodies less 0353''s hunks (a round trip on each), 12 functions, the order table and 3 knobs gone';
end
$r$;
`,
)
console.log('wrote before.sql, after.sql and rollback-0353.sql (20 hunks)')
}
