// gen-checks.mjs — writes before.sql (the PROD CHECK of 0345) from the migration's own hunks, so the texts it tests are the very texts the file applies.
//   node scripts/ops/harness/ship-stores/gen-checks.mjs
// The output is ONE read-only statement inside begin transaction read only ... commit (CLAUDE.md): npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/ship-stores/before.sql
// Every function it calls is STABLE or IMMUTABLE (pg_get_functiondef, to_regprocedure, replace). Only the catalog and world_config are read.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const HERE = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))
const sql = readFileSync(path.join(HERE, '..', '..', '..', '..', 'supabase', 'migrations', '20260818000345_stores_have_their_own_space.sql'), 'utf8').replaceAll('\r', '')
const start = sql.indexOf('insert into hunks_0345 values')
if (start < 0) throw new Error('no hunks in the migration')
const block = sql.slice(start, sql.indexOf('for v_h in select h.fn from hunks_0345'))
const hunks = [...block.matchAll(/\('([^']+)', (\d+),\s*\$h\$([\s\S]*?)\$h\$,\s*\$h\$([\s\S]*?)\$h\$\)/g)].map((m) => ({ fn: m[1], ord: Number(m[2]), old: m[3], new: m[4] }))
if (hunks.length !== 17) throw new Error(`${hunks.length} hunks parsed, the migration has 17`)
const values = hunks.map((h) => `  ('${h.fn}'::text, ${h.ord}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')

writeFileSync(
  path.join(HERE, 'before.sql'),
  `-- 0345 PROD CHECK (before), read-only, ONE statement: npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/ship-stores/before.sql
-- Wanted (head 0344): 17 rows, every row old_times 1, new_times 0, absent true (no knob and no reader of 0345 exists yet), head 20260818000344.
-- Generated by scripts/ops/harness/ship-stores/gen-checks.mjs from the migration's own hunks. Only the catalog and world_config are read.
begin transaction read only;
with h(fn, ord, old, new) as (values
${values}
)
select h.fn, h.ord,
       (length(d.def) - length(replace(d.def, h.old, ''))) / length(h.old) as old_times,
       (length(d.def) - length(replace(d.def, h.new, ''))) / length(h.new) as new_times,
       not exists (select 1 from public.world_config c where c.key in ('ship_stores_separate', 'ship_stores_days'))
         and to_regprocedure('public.ship_stores_separate()') is null and to_regprocedure('public.ship_stores_space(uuid)') is null
         and to_regprocedure('public.ship_stores_room(uuid,numeric)') is null and to_regprocedure('public.stores_in_hold(numeric)') is null
         and to_regprocedure('public.ship_stores_card(uuid)') is null as absent,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from h
  cross join lateral (select replace(pg_get_functiondef(to_regprocedure(h.fn)), E'\\r', '') as def) d
 order by h.fn, h.ord;
commit;
`,
)
console.log('wrote before.sql with', hunks.length, 'hunks')
