// gen.mjs - writes before.sql and rollback-0431.sql from 0431's OWN hunk table (no second hand copy of a hunk). Run after any edit of the migration:
//   node scripts/ops/harness/fleet-tabs/gen.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '../../../..')
const mig = readFileSync(path.join(root, 'supabase/migrations/20260818000431_the_stats_open_every_fleet.sql'), 'utf8')

const cut = [...mig.slice(mig.indexOf('c_cut constant text[] := array['), mig.indexOf('];', mig.indexOf('c_cut constant'))).matchAll(/'([^']+)'/g)].map((m) => m[1])
const table = mig.slice(mig.indexOf('insert into hunk_0431 values'), mig.indexOf('  for h in select * from hunk_0431'))
const hunks = [...table.matchAll(/\((\d+), c_cut\[(\d+)\],\n\$h\$([\s\S]*?)\$h\$,\n\$h\$([\s\S]*?)\$h\$\)/g)].map((m) => ({ ord: Number(m[1]), fn: cut[Number(m[2]) - 1], old: m[3], new: m[4] }))
if (hunks.length !== 11 || cut.length !== 11) throw new Error(`gen: read ${hunks.length} hunks and ${cut.length} bodies, want 11 and 11`)

const before = `-- before.sql: READ ONLY on prod, one statement, BEFORE 0431 is pushed (generated by gen.mjs from the migration's own hunks: do not edit by hand).
-- Each of 0431's eleven hunks occurs exactly once in the live body it cuts (want eleven 1s), nothing of 0431 is there yet, the head is 0430,
-- and the sizes the book will read beside (battles, convoy_cargo) and the Stats count's last runs. Catalog reads, pg_get_functiondef (STABLE),
-- the planner's row estimates and stats_runs (7 days of receipts) only.
begin transaction read only;
select jsonb_build_object(
  'head', (select max(version) from supabase_migrations.schema_migrations),
  'absent', to_regclass('public.fleet_book') is null and to_regclass('public.fleet_lines') is null and to_regclass('public.stats_fleet_list') is null
            and to_regprocedure('world.stats_fleet(uuid)') is null and not exists (select 1 from pg_trigger t where t.tgname = 'fleet_book_battle'),
  'hunks', (select jsonb_agg((length(b.def) - length(replace(b.def, h.old, ''))) / length(h.old) order by h.ord)
              from (values
${hunks.map((h) => `                (${h.ord}, '${h.fn}', $h$${h.old}$h$)`).join(',\n')}) h(ord, fn, old)
              cross join lateral (select replace(pg_get_functiondef(h.fn::regprocedure), E'\\r', '') as def) b),
  'rows_est', (select jsonb_object_agg(c.relname, c.reltuples::bigint) from pg_class c join pg_namespace n on n.oid = c.relnamespace
                where n.nspname = 'public' and c.relname in ('battles', 'battle_sides', 'convoy_cargo', 'navy_ships', 'pirate_ships', 'cargo_ships')),
  'runs', (select jsonb_agg(jsonb_build_object('at', x.at, 'ms', x.ms, 'fleets_ms', x.receipt -> 'phases' -> 'fleets') order by x.at desc)
             from (select r.at, r.ms, r.receipt from public.stats_runs r order by r.at desc limit 4) x)
) as before_0431;
commit;
`
writeFileSync(path.join(here, 'before.sql'), before)

const rollback = `do $$ begin if inet_server_addr() is not null then raise exception 'local PGlite world only: this scene writes'; end if; end $$;
-- rollback-0431.sql: the FORWARD ROLLBACK DRAFT of 0431 (owner only; generated by gen.mjs from the migration's own hunks: do not edit by hand). To
-- deploy it: copy it into supabase/migrations/ under the next number and delete its first line (the guard). It swaps 0431's eleven hunks back (each
-- must occur once, and no body may keep a trace of 0431), takes the two reads out of the registry by that hunk, drops the battle trigger, the reads,
-- the bookers, the writer and the three tables (the book's figures go with them: they are a record, nothing of play reads them). The client's faces
-- Navy, Pirates and Cargo then say their figures did not load until the client is reverted too.
do $r$
declare
  h     record;
  v_def text;
  v_n   int;
begin
  perform set_config('lock_timeout', '5s', true);
  create temp table hunk_r431 (ord int primary key, fn text, new text, old text) on commit drop;
  insert into hunk_r431 values
${hunks.map((h) => `  (${h.ord}, '${h.fn}',\n$h$${h.new}$h$,\n$h$${h.old}$h$)`).join(',\n')};
  for h in select * from hunk_r431 order by ord desc loop
    v_def := replace(pg_get_functiondef(h.fn::regprocedure), E'\\r', '');
    v_n := (length(v_def) - length(replace(v_def, h.new, ''))) / length(h.new);
    if v_n <> 1 then
      raise exception 'rollback-0431: hunk % of % occurs % time(s), not once', h.ord, h.fn, v_n;
    end if;
    execute replace(v_def, h.new, h.old);
  end loop;
  if exists (select 1 from hunk_r431 x where pg_get_functiondef(x.fn::regprocedure) ~ '0431|fleet_book|stats_fleet_list') then
    raise exception 'rollback-0431: a trace of 0431 is left in a body';
  end if;
  drop trigger fleet_book_battle on public.battles;
  drop function world.stats_fleet(uuid);
  drop function world.stats_fleet_list(text);
  drop function public.stats_fleet_list_rows(text, timestamptz);
  drop function public.fleet_book_battle();
  drop function public.fleet_book_take(uuid, text, bigint, uuid, uuid, timestamptz);
  drop function public.fleet_book_refit(uuid, bigint, timestamptz);
  drop function public.fleet_book_stop(uuid, uuid, text, jsonb, bigint, jsonb, timestamptz);
  drop function public.fleet_book_fight(uuid, uuid, text, jsonb, boolean, boolean, timestamptz);
  drop function public.fleet_book_add(uuid, timestamptz, jsonb, text, jsonb);
  drop function public.fleet_figs_add(jsonb, jsonb);
  drop table public.stats_fleet_list;
  drop table public.fleet_lines;
  drop table public.fleet_book;
  raise notice 'rollback-0431 ok: eleven hunks reversed; the battle trigger, two reads, the list, five bookers, the writer and three tables dropped';
end $r$;
`
writeFileSync(path.join(here, 'rollback-0431.sql'), rollback)
console.log(`gen: ${hunks.length} hunks -> before.sql, rollback-0431.sql`)
