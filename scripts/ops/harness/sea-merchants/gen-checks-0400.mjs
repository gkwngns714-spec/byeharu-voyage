// 0400 PROD CHECKS and the rollback draft, generated from the migration's own hunks: node scripts/ops/harness/sea-merchants/gen-checks-0400.mjs
// Writes before-0400.sql (run on prod BEFORE the deploy), after-0400.sql (AFTER it) and rollback-0400.sql (a DRAFT, local only).
// Each prod check is ONE read-only statement over the catalog and world_config: no game function is called.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const here = path.dirname(fileURLToPath(import.meta.url))
const NAME = '20260818000400_a_merchant_keeps_her_home_waters.sql'
const mig = readFileSync(path.join(here, '../../../../supabase/migrations', NAME), 'utf8').replace(/\r/g, '')
const hunks = [...mig.matchAll(/\((\d+), '(public\.[a-z_]+\([a-z,]*\))',\n\$h\$([\s\S]*?)\$h\$,\n\$h\$([\s\S]*?)\$h\$\)/g)].map((m) => ({ n: Number(m[1]), fn: m[2], old: m[3], new: m[4] }))
if (hunks.length !== 3) throw new Error(`expected 3 hunks, found ${hunks.length}`)
const count = (hay, needle) => hay.split(needle).length - 1
for (const h of hunks) h.oldAfter = count(h.new, h.old)
const rows = hunks.map((h) => `  ('${h.fn}'::text, ${h.n}, ${h.oldAfter}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')
const NEW_FNS = ['public.npc_sea_floor(uuid)', 'public.npc_sea_shut(numeric,uuid,jsonb,integer,integer,integer,integer)']
const run = (f) => `npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/sea-merchants/${f}`
const catalog = `with h(fn, ord, old_after_wanted, old, new) as (values
${rows}
), d as (
  select h.*, replace(pg_get_functiondef(to_regprocedure(h.fn)), chr(13), '') as def, (select p.provolatile from pg_proc p where p.oid = to_regprocedure(h.fn)) as volatility from h
)
select fn, ord, volatility,
       (length(def) - length(replace(def, old, ''))) / length(old) as old_times,
       (length(def) - length(replace(def, new, ''))) / length(new) as new_times,
       old_after_wanted,
       (select count(*) from unnest(array[${NEW_FNS.map((f) => `'${f}'`).join(', ')}]) f where to_regprocedure(f) is not null) as new_functions,
       to_regprocedure('public.sea_judge(integer,numeric,text[],integer,integer,integer,integer)') is not null and to_regprocedure('public.sea_floor(uuid,jsonb)') is not null as floors_of_0396_in,
       (select jsonb_object_agg(c.key, c.value) from public.world_config c where c.key in ('sea_conditions_bite', 'sea_conditions_bite_npc')) as switches,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from d order by ord;`
writeFileSync(path.join(here, 'before-0400.sql'), `-- 0400 PROD CHECK, BEFORE the deploy, read-only, ONE statement: ${run('before-0400.sql')}
-- Wanted, three rows (the three hunks): every old_times 1, every new_times 0, new_functions 0, floors_of_0396_in true, every volatility s,
-- switches sea_conditions_bite true and sea_conditions_bite_npc false, HEAD IT MEETS: 20260818000399.
-- Generated by gen-checks-0400.mjs from the migration's own hunks.
begin transaction read only;
${catalog}
commit;
`)
writeFileSync(path.join(here, 'after-0400.sql'), `-- 0400 PROD CHECK, AFTER the deploy, read-only, ONE statement: ${run('after-0400.sql')}
-- Wanted, three rows: every new_times 1, every old_times = old_after_wanted, new_functions 2, every volatility s, the switches as before (this file sets
-- none: sea_conditions_bite_npc still false), head 20260818000400. Then scripts/ops/harness/sea-light/before-npc.sql: merchants_with_no_open_leg 0, ready true.
-- Generated by gen-checks-0400.mjs from the migration's own hunks.
begin transaction read only;
${catalog}
commit;
`)
const back = hunks.map((h) => `  ('${h.fn}', ${h.n}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')
writeFileSync(path.join(here, 'rollback-0400.sql'), `-- 0400 FORWARD ROLLBACK, A DRAFT. NOT a prod check and NOT a migration yet: to use it, strip the guard line, give it the next number, add "-- news: none" and
-- deploy it as any migration (owner only). It puts back 0397's and 0399's texts in the three cut bodies (each NEW text once, judged as a round trip on the
-- live body) and drops the two functions of 0400. Merchants are then judged on the plain rule again: IF sea_conditions_bite_npc IS TRUE, TURN IT OFF FIRST
-- (the merchants with no open leg would be laid up). Generated by gen-checks-0400.mjs from the migration's own hunks.
-- LOCAL PGlite WORLD ONLY while it carries this line (scripts/ops/harness/README.md): it writes. The first statement refuses a real server (inet_server_addr() is not null there, null on PGlite).
do $$ begin if inet_server_addr() is not null then raise exception 'local PGlite world only: this scene writes'; end if; end $$;
do $r$
declare
  h      record;
  v_live text;
  v_def  text;
begin
  perform set_config('statement_timeout', '45s', true);
  perform set_config('lock_timeout', '5s', true);
  if to_regprocedure('public.npc_sea_floor(uuid)') is null then
    raise exception '0400 rollback refuses: 0400 is not applied in this world';
  end if;
  create temp table hunks_back (fn text, n int, old text, new text) on commit drop;
  insert into hunks_back (fn, n, old, new) values
${back};
  for h in select * from hunks_back order by n loop
    v_live := replace(pg_get_functiondef(h.fn::regprocedure), chr(13), '');
    if (length(v_live) - length(replace(v_live, h.new, ''))) / length(h.new) <> 1 then
      raise exception '0400 rollback: hunk % of % is not in the live body exactly once: a later migration re-cut it; cut this rollback again from the live body', h.n, h.fn;
    end if;
    v_def := replace(v_live, h.new, h.old);
    if replace(v_def, h.old, h.new) <> v_live then
      raise exception '0400 rollback: % does not come back to the live body when the hunk is put back', h.fn;
    end if;
    execute v_def;
  end loop;
  drop function public.npc_sea_shut(numeric, uuid, jsonb, integer, integer, integer, integer);
  drop function public.npc_sea_floor(uuid);
  raise notice '0400 rollback ok: 3 bodies less 0400''s 3 hunks (a round trip on each), the 2 new functions gone';
end
$r$;
`)
console.log('wrote before-0400.sql, after-0400.sql, rollback-0400.sql')
