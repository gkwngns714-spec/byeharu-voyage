// gen-checks.mjs — writes before.sql, after.sql and volatility.sql (the PROD CHECKS of 0339) from the migration's own hunks, so the texts they test are the very texts the file applies.
//   node scripts/ops/harness/pirate-ships-sail/gen-checks.mjs
// Each output is ONE read-only statement (docs/OPS_HEALTH.md; CLAUDE.md): npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/pirate-ships-sail/before.sql
// Every function called is STABLE or IMMUTABLE (pg_get_functiondef, to_regprocedure, replace, md5, treasury_balance, realm_purse, pirate_power, the new readers once they exist); volatility.sql prints it first.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const HERE = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))
const sql = readFileSync(path.join(HERE, '..', '..', '..', '..', 'supabase', 'migrations', '20260818000339_pirate_ships_sail.sql'), 'utf8').replaceAll('\r', '')
const start = sql.indexOf('insert into hunks_0339 values')
if (start < 0) throw new Error('no hunks in the migration')
const block = sql.slice(start, sql.indexOf('for v_h in select h.fn from hunks_0339'))
const hunks = [...block.matchAll(/\('([^']+)', (\d+),\n\$h\$([\s\S]*?)\$h\$,\n\$h\$([\s\S]*?)\$h\$\)/g)].map((m) => ({ fn: m[1], ord: Number(m[2]), old: m[3], new: m[4] }))
if (hunks.length !== 21) throw new Error(`${hunks.length} hunks parsed, the migration has 21`)
for (const h of hunks) if (h.old.includes('$h$') || h.new.includes('$h$')) throw new Error('a hunk holds the dollar tag')

// one row a FUNCTION: its hunks applied in order (old -> new) give the wanted body; taken out in reverse give the pre-image back
const fns = [...new Set(hunks.map((h) => h.fn))].sort()
const values = hunks.map((h) => `  ('${h.fn}'::text, ${h.ord}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')

