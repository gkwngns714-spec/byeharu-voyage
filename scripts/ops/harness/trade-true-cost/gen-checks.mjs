// 0361 PROD CHECKS and the rollback draft, generated from the migration's own hunks: node scripts/ops/harness/trade-true-cost/gen-checks.mjs
// Writes before.sql (run on prod BEFORE the deploy, AFTER 0360 is in), after.sql (AFTER it), volatility.sql (either side) and rollback-0361.sql (a DRAFT, local only).
// Every prod check is ONE read-only statement: the catalog and plain SELECTs of world_config only. No game function is called.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const here = path.dirname(fileURLToPath(import.meta.url))
const NAME = '20260818000361_trade_says_what_a_trip_really_costs.sql'
const mig = readFileSync(path.join(here, '../../../../supabase/migrations', NAME), 'utf8').replace(/\r/g, '')
const hunks = [...mig.matchAll(/\('((?:world|public)\.[a-z_]+\([a-z,]+\))', (\d),\n\$h\$([\s\S]*?)\$h\$,\n\$h\$([\s\S]*?)\$h\$\)/g)].map((m) => ({ fn: m[1], n: Number(m[2]), old: m[3], new: m[4] }))
if (hunks.length !== 22) throw new Error(`expected 22 hunks, found ${hunks.length}`)
const count = (hay, needle) => hay.split(needle).length - 1
// after the deploy an OLD text is still found wherever a NEW text of the same body carries it (a NEW that begins with its OLD line, a line kept inside it)
for (const h of hunks) h.oldAfter = hunks.filter((x) => x.fn === h.fn).reduce((n, x) => n + count(x.new, h.old), 0)
const rows = hunks.map((h) => `  ('${h.fn}'::text, ${h.n}, ${h.oldAfter}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')
const run = (f) => `npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/trade-true-cost/${f}`
const HELPERS = ['world.trip_stop_seconds()', 'world.trip_hulls(uuid)', 'world.trip_leg(jsonb,numeric,numeric,boolean,numeric)']
const catalog = `with h(fn, ord, old_after_wanted, old, new) as (values
${rows}
), d as (
  select h.*, replace(pg_get_functiondef(to_regprocedure(h.fn)), chr(13), '') as def from h
)
select fn, ord,
       (length(def) - length(replace(def, old, ''))) / length(old) as old_times,
       (length(def) - length(replace(def, new, ''))) / length(new) as new_times,
       old_after_wanted,
       (select count(*) from unnest(array[${HELPERS.map((f) => `'${f}'`).join(', ')}]) f where to_regprocedure(f) is not null) as helpers,
       (select count(*) from public.world_news n where n.key = 'update:0361') as news_row,
       (select jsonb_object_agg(c.key, c.value) from public.world_config c
         where c.key in ('economy_closed', 'city_treasury_enabled', 'port_prep_seconds', 'port_fee_base', 'port_fee_pct', 'time_compression',
                         'good_board_quoted', 'good_board_quoted_near')) as knobs,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from d order by fn, ord;`
writeFileSync(path.join(here, 'before.sql'), `-- 0361 PROD CHECK (before), read-only, ONE statement: ${run('before.sql')}
-- RUN IT AFTER 0360 IS DEPLOYED (0361 re-cuts 0360's world.trip_cost; before 0360 its three rows read null).
-- Wanted: 22 rows (3 of world.trip_cost, 3 of world.board_legs, 9 of world.board_sell, 7 of world.good_board); every old_times 1; every new_times 0; helpers 0;
-- news_row 0; head 20260818000360. \`knobs\` says what a trip reads on prod today: whether the economy is closed and the city purses lit (then dock fees and
-- port time are in force and Trade's profit will fall by them), the port time, the dock fee's base and share, the clock's compression, how many rows a board prices.
-- Generated by scripts/ops/harness/trade-true-cost/gen-checks.mjs from the migration's own hunks. Only the catalog and world_config are read.
begin transaction read only;
${catalog}
commit;
`)
writeFileSync(path.join(here, 'after.sql'), `-- 0361 PROD CHECK (after), read-only, ONE statement: ${run('after.sql')}
-- Wanted: 22 rows; every new_times 1; every old_times = its old_after_wanted (an OLD line that a NEW text keeps is still found: the column says how often);
-- helpers 3; news_row 1; head 20260818000361; knobs as before (this file sets none).
-- Generated by scripts/ops/harness/trade-true-cost/gen-checks.mjs from the migration's own hunks. Only the catalog and world_config are read.
begin transaction read only;
${catalog}
commit;
`)
writeFileSync(path.join(here, 'volatility.sql'), `-- 0361 PROD CHECK (either side), read-only, ONE statement: ${run('volatility.sql')}
-- The four re-cut bodies, the read that leans on them, the three helpers (after the deploy) and every authority they compose: volatility (wanted: s or i on
-- every row), definer, settings and who may run it. Wanted: world.good_board, world.best_sales and world.trip_cost s, open to authenticated and not to anon;
-- world.board_legs, world.board_sell and (after) world.trip_leg, world.trip_hulls, world.trip_stop_seconds s and server only; the same rows before and after
-- but for the three helpers.
begin transaction read only;
select p.oid::regprocedure::text as fn, p.provolatile as volatile, p.prosecdef as definer, coalesce(p.proconfig::text, '') as settings,
       has_function_privilege('authenticated', p.oid, 'execute') as authenticated_may, has_function_privilege('anon', p.oid, 'execute') as anon_may
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
 where (n.nspname, p.proname) in (('world', 'good_board'), ('world', 'best_sales'), ('world', 'trip_cost'), ('world', 'board_legs'), ('world', 'board_sell'), ('world', 'board_origin'),
                                  ('world', 'trip_leg'), ('world', 'trip_hulls'), ('world', 'trip_stop_seconds'), ('public', 'stores_topup'), ('public', 'stores_cost'),
                                  ('public', 'npc_leg_days'), ('public', 'port_fee'), ('public', 'fleet_stock_at_cost'), ('public', 'fleet_wage'), ('public', 'economy_closed'),
                                  ('public', 'supply_needs'), ('voyage', 'total_days'), ('public', 'wc_num'))
 order by 1;
commit;
`)
const back = hunks.map((h) => `  ('${h.fn}', ${h.n}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')
writeFileSync(path.join(here, 'rollback-0361.sql'), `-- 0361 FORWARD ROLLBACK, A DRAFT. NOT a prod check and NOT a migration yet: to use it, strip the guard line, give it the next number, add its news line
-- ("-- news: none" or a public.news_update row) and deploy it as any migration (owner only). It swaps 0361's OLD and NEW: each of the four re-cut bodies loses
-- exactly what 0361 added (each NEW text once, reversed, judged as a round trip on the live body: no fixed digest, a later file may have re-cut it), and the
-- three helpers are dropped. Trade's board then reads as before 0361 (wages by the fraction, the longest leg's supplies, no dock fee in the profit, the sailing
-- alone); the client reads the new keys as optional and falls back. world.trip_cost answers what it answers now (0361 did not change its answer).
-- Tested locally: measure.mjs --apply=${NAME} rollback-0361.sql before.sql prints every old_times 1, new_times 0, helpers 0.
-- Generated by scripts/ops/harness/trade-true-cost/gen-checks.mjs from the migration's own hunks.
-- LOCAL PGlite WORLD ONLY while it carries this line (scripts/ops/harness/README.md): it writes. The first statement refuses a real server (inet_server_addr() is not null there, null on PGlite).
do $$ begin if inet_server_addr() is not null then raise exception 'local PGlite world only: this scene writes'; end if; end $$;
do $r$
declare
  f      record;
  h      record;
  v_live text;
  v_def  text;
  v_back text;
begin
  perform set_config('statement_timeout', '45s', true);
  perform set_config('lock_timeout', '5s', true);
  if to_regprocedure('world.trip_leg(jsonb,numeric,numeric,boolean,numeric)') is null then
    raise exception '0361 rollback refuses: 0361 is not applied in this world';
  end if;
  create temp table hunks_back (fn text, n int, old text, new text) on commit drop;
  insert into hunks_back (fn, n, old, new) values
${back};
  for f in select distinct x.fn from hunks_back x order by 1 loop
    v_live := replace(pg_get_functiondef(f.fn::regprocedure), chr(13), '');
    v_def := v_live;
    -- the NEW texts out, last first (the order 0361's own self-assert reverses them in)
    for h in select * from hunks_back x where x.fn = f.fn order by n desc loop
      if (length(v_def) - length(replace(v_def, h.new, ''))) / length(h.new) <> 1 then
        raise exception '0361 rollback: hunk % of % is not in the live body exactly once: a later migration re-cut the text 0361 added; cut this rollback again from the live body', h.n, f.fn;
      end if;
      v_def := replace(v_def, h.new, h.old);
    end loop;
    -- a round trip: the hunks put back give the live body again
    v_back := v_def;
    for h in select * from hunks_back x where x.fn = f.fn order by n loop
      if (length(v_back) - length(replace(v_back, h.old, ''))) / length(h.old) <> 1 then
        raise exception '0361 rollback: hunk % of %: its OLD text is not in the reversed body exactly once', h.n, f.fn;
      end if;
      v_back := replace(v_back, h.old, h.new);
    end loop;
    if v_back <> v_live then
      raise exception '0361 rollback: % does not come back to the live body when the hunks are put back', f.fn;
    end if;
    execute v_def;
  end loop;
  drop function world.trip_leg(jsonb, numeric, numeric, boolean, numeric);
  drop function world.trip_hulls(uuid);
  drop function world.trip_stop_seconds();
  raise notice '0361 rollback ok: 4 bodies less 0361''s 22 hunks (a round trip on each), the 3 helpers gone';
end
$r$;
`)
