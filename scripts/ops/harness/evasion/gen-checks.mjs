// gen-checks.mjs: writes check.sql (the PROD CHECK of 0453, the same read before and after the deploy) and rollback-0453.sql (a draft) from the
// hunks of migration 0453 itself, so the checks cannot drift from the file.   node scripts/ops/harness/evasion/gen-checks.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const HERE = path.dirname(fileURLToPath(import.meta.url))
const MIG = path.resolve(HERE, '../../../../supabase/migrations/20260818000453_a_run_is_a_chase.sql')
const s = readFileSync(MIG, 'utf8').replaceAll('\r', '')
const re = /\('([a-z_.]+\([a-z ,]*\))', (\d+),\n\$h\$([\s\S]*?)\$h\$,\n\$h\$([\s\S]*?)\$h\$\)/g
const hunks = []
for (let x; (x = re.exec(s)); ) hunks.push({ fn: x[1], ord: Number(x[2]), old: x[3], neu: x[4] })
if (hunks.length !== 7) throw new Error(`hunks ${hunks.length}, 7 expected`)
const fns = [...new Set(hunks.map((h) => h.fn))]
const count = (hay, needle) => hay.split(needle).length - 1
const E = (t) => "E'" + t.replaceAll('\\', '\\\\').replaceAll("'", "''").replaceAll('\n', '\\n') + "'"
const key = (h) => `${h.fn.replace(/\(.*/, '').replace(/^.*\./, '')}.${h.ord}`
const afterOld = hunks.map((h) => `${key(h)}: ${count(h.neu, h.old)}`).join(', ')

const check = `-- 0453 PROD CHECK, BEFORE the deploy AND AGAIN AFTER IT (the same read), read-only, ONE statement. GENERATED by gen-checks.mjs from the migration's own hunks.
--   npx --yes supabase@2.120.0 db query --linked --output-format json -f scripts/ops/harness/evasion/check.sql
-- Run scripts/ops/harness/db-health/gate.sql first (gate_ok true). One row, one jsonb column \`r\`. It reads the catalog (four function bodies), the knobs, the level
-- tables' Evasion rows, public.battles of the last hour (RAID rows are kept 48 h; ~50 an hour) and the beat's ring. No big table is scanned; no game function is called.
-- BEFORE, wanted: head 20260818000452 (#752 deploys first; 20260818000451 if it has not); applied false; old: every count 1; new: every count 0; level_skills
--   max_ord 10, evasion false, perk_run 0, activities 0, chase {} (no chase_* knob), fns {level_perk_at: false, evasion_of: false}; levels_bite, level_skills_on,
--   level_perks_on, npc_ship_level_enabled true; hull_speed_floor 0.6, crew_short_speed_mult 0.7, flee_per_try 0.05, tick_abilities RN {cd 20, for 20}.
--   Write down raids_1h (all, flee, fled), rolls_pct (min / median / max) and the beat.
-- AFTER (30 minutes), wanted: head 20260818000453; applied true; new: every count 1; old {${afterOld}} (an old text that stands inside its new text still counts 1);
--   level_skills max_ord 11, evasion true, perk_run 19, activities 2; chase {chase_enabled true, chase_base 0.15, chase_power 2, chase_floor 0.01, chase_cap 0.5,
--   chase_per_handling 0.5}; cards_ev_1h = every tick battle opened since the deploy (no_ev_newest before the deploy); rolls_pct within 1..50, median about 7
--   where it was 3; raids_1h.flee: of the runners about 1 in 10 got away by running (the replay of prod's 100 sheets: docs/dev-log/2026-11-16-evasion.md);
--   stuck 0; span_s max <= 75 as before; beat no worse than BEFORE; evasion_xp only companies that were raided and ran.
-- FAIL (each a rollback by the knob chase_enabled false, the owner's): the beat over 2,000 ms; a raid stuck FIGHTING; a roll outside 1..50; of 30 or more
--   runners none away, or more than 3 in 10.
-- ROLLBACK: scripts/ops/harness/evasion/rollback-0453.sql (a draft; the quick one is the switch).
begin transaction read only;
with hk(k, fn, old, neu) as (values
${hunks.map((h) => `  ('${key(h)}', '${h.fn}', ${E(h.old)}, ${E(h.neu)})`).join(',\n')}
), body as (
  select f.fn, replace(pg_get_functiondef(f.fn::regprocedure), E'\\r', '') as def
    from (values ${fns.map((f) => `('${f}')`).join(', ')}) f(fn)
), b as (
  select x.id, x.kind, x.status, x.started_at, x.resolves_at, x.result, x.sheet, x.ticks
    from public.battles x where x.started_at > now() - interval '1 hour' and x.ticks is not null and x.ticks <> 'null'::jsonb
)
select jsonb_build_object(
  'at', now(),
  'head', (select max(m.version) from supabase_migrations.schema_migrations m),
  'applied', to_regprocedure('public.evasion_of(uuid)') is not null,
  'old', (select jsonb_object_agg(hk.k, (length(body.def) - length(replace(body.def, hk.old, ''))) / length(hk.old)) from hk join body on body.fn = hk.fn),
  'new', (select jsonb_object_agg(hk.k, (length(body.def) - length(replace(body.def, hk.neu, ''))) / length(hk.neu)) from hk join body on body.fn = hk.fn),
  'bodies', (select jsonb_object_agg(body.fn, md5(body.def)) from body),
  'fns', jsonb_build_object('level_perk_at', to_regprocedure('public.level_perk_at(text,integer)') is not null, 'evasion_of', to_regprocedure('public.evasion_of(uuid)') is not null),
  'level_skills', jsonb_build_object(
    'max_ord', (select max(k.ord) from public.level_skills k),
    'evasion', exists (select 1 from public.level_skills k where k.code = 'evasion'),
    'perk_run', (select count(*) from public.level_perks k where k.perk = 'run'),
    'activities', (select count(*) from public.level_activities a where a.code in ('run_away', 'run_try'))),
  'chase', (select coalesce(jsonb_object_agg(k.key, k.value), '{}'::jsonb) from public.world_config k where k.key like 'chase\\_%'),
  'knobs', (select jsonb_object_agg(k.key, k.value) from public.world_config k
             where k.key ~ '^(raid_flee|flee_|fight_flee|fight_evade)' or k.key in ('levels_bite', 'level_skills_on', 'level_perks_on', 'npc_ship_level', 'npc_ship_level_enabled',
                                                                                  'hull_speed_floor', 'crew_short_speed_mult', 'tick_fight_kinds', 'raid_orders_enabled')),
  'tick_rn', (select k.value -> 'RN' from public.world_config k where k.key = 'tick_abilities'),
  'tick_1h', (select count(*) from b),
  'cards_full_1h', (select count(*) from b where not exists (select 1 from jsonb_array_elements(coalesce(b.sheet -> 'a', '[]'::jsonb) || coalesce(b.sheet -> 'b', '[]'::jsonb)) h
                                                              where not (h ?& array['speed', 'handling', 'lv', 'crew_need']))),
  'cards_ev_1h', (select count(*) from b where not exists (select 1 from jsonb_array_elements(coalesce(b.sheet -> 'a', '[]'::jsonb) || coalesce(b.sheet -> 'b', '[]'::jsonb)) h
                                                            where not (h ?& array['ev', 'run']))),
  'no_ev_newest', (select max(b.started_at) from b where exists (select 1 from jsonb_array_elements(coalesce(b.sheet -> 'a', '[]'::jsonb) || coalesce(b.sheet -> 'b', '[]'::jsonb)) h
                                                                  where not (h ?& array['ev', 'run']))),
  'sheet_kb', (select round(avg(length(b.sheet::text)) / 1024.0, 2) from b),
  'raids_1h', (select jsonb_build_object(
                 'all', (select coalesce(jsonb_object_agg(z.o, z.n), '{}'::jsonb) from (select coalesce(b.ticks ->> 'out', '-') as o, count(*) as n from b where b.kind = 'RAID' group by 1) z),
                 'flee', (select coalesce(jsonb_object_agg(z.o, z.n), '{}'::jsonb) from (select coalesce(b.ticks ->> 'out', '-') as o, count(*) as n from b where b.kind = 'RAID' and b.ticks #>> '{ai,a}' = 'FLEE' group by 1) z),
                 'ran', (select count(*) from b where b.kind = 'RAID' and exists (select 1 from jsonb_array_elements(b.ticks -> 'e') e where e ->> 2 = 'X' and e ->> 1 = '0')),
                 'fled', (select count(*) from b where b.kind = 'RAID' and coalesce((b.ticks #>> '{r,fled}')::boolean, false)))),
  'rolls_pct', (select jsonb_build_object('n', count(*), 'min', min((e ->> 3)::numeric), 'median', percentile_cont(0.5) within group (order by (e ->> 3)::numeric),
                                          'max', max((e ->> 3)::numeric), 'away', count(*) filter (where e ->> 4 = '1'))
                  from b cross join lateral jsonb_array_elements(b.ticks -> 'e') e where b.kind = 'RAID' and e ->> 2 = 'X' and e ->> 1 = '0'),
  'open_pct', (select jsonb_build_object('n', count(*), 'min', min((b.ticks #>> '{rc,a,0,1}')::numeric), 'median', percentile_cont(0.5) within group (order by (b.ticks #>> '{rc,a,0,1}')::numeric),
                                         'max', max((b.ticks #>> '{rc,a,0,1}')::numeric))
                 from b where b.kind = 'RAID' and b.ticks #>> '{ai,a}' = 'FLEE'),
  'span_s', (select jsonb_build_object('mean', round(avg(extract(epoch from b.resolves_at - b.started_at))), 'max', round(max(extract(epoch from b.resolves_at - b.started_at)))) from b),
  'stuck', (select count(*) from b where b.status = 'FIGHTING' and b.resolves_at < now() - interval '2 minutes'),
  'evasion_xp', (select jsonb_build_object('companies', count(*), 'xp', coalesce(sum(x.xp), 0)) from public.level_xp x where x.skill = 'evasion'),
  'beat', (select jsonb_build_object('mean_ms', round(avg(a.ms)), 'n', count(*)) from public.arrivals_beats a where a.at > now() - interval '5 minutes')
) as r;
commit;
`

const rollback = `-- 0453 ROLLBACK DRAFT (forward, owner only; NOT a migration until the owner asks for one; then it takes prod head + 1). GENERATED by gen-checks.mjs.
-- QUICK, THE SWITCH ALONE (no code moves; 0453's self-assert and proofs 152 / 155 EV_OFF prove this is 0450's chance to the digit, for every NEW roll and
--   every re-run); the level, its experience and its tile stay, and what was earned is kept:
--   update public.world_config set value = 'false'::jsonb where key = 'chase_enabled';
-- SOFTER OR HARDER, NOT OFF (docs/dev-log/2026-11-16-evasion.md, the replay of prod's sheets): chase_base 0.20 (softer) or 0.10 (harder); chase_power 1
--   (a flatter ratio); the steps of perk run in public.level_perks (what a level is worth).
-- The cards' \`ev\` and \`run\` on a sheet are a read: they need no rollback (an old client ignores them).
-- WHOLE: the seven hunks of 0453 reversed (each NEW text back to its OLD, once each, as its self-assert proves they reverse), in this order, then
--   drop function public.evasion_of(uuid);          -- after public.battle_hull_card no longer calls it
--   drop function public.level_perk_at(text, int);  -- after public.level_perk and public.evasion_of no longer call it
--   delete from public.world_config where key in ('chase_enabled', 'chase_base', 'chase_power', 'chase_floor', 'chase_cap', 'chase_per_handling');
--   delete from public.level_perks where perk = 'run';
--   The level's row (public.level_skills 'evasion') and its two activities stay if any company holds experience in it: public.level_book is append-only
--   (0411's rollback draft leaves what was earned in place the same way). With no experience anywhere they go too:
--   delete from public.level_activities where skill = 'evasion'; delete from public.level_skills where code = 'evasion';
${hunks.map((h) => `--   ${key(h)}  (${h.fn})`).join('\n')}
-- THIS FILE IS NOTES, every line a comment: nothing in it runs. It carries the harness guard (the next line) so the tree's reader knows it for a
-- local draft and not a prod check, and so that a statement uncommented here later still refuses to run on production.
do $$ begin if inet_server_addr() is not null then raise exception 'local PGlite world only: this scene writes'; end if; end $$;
`

const files = { 'check.sql': check, 'rollback-0453.sql': rollback }
if (process.argv.includes('--check')) {
  for (const [f, text] of Object.entries(files)) if (readFileSync(path.join(HERE, f), 'utf8').replaceAll('\r', '') !== text) throw new Error(`${f} is not what gen-checks.mjs writes: run it`)
  console.log('evasion checks: held to the migration')
} else {
  for (const [f, text] of Object.entries(files)) writeFileSync(path.join(HERE, f), text)
  console.log(`wrote ${Object.keys(files).join(', ')} (${hunks.length} hunks, ${fns.length} functions)`)
}
