// gen-checks.mjs: writes check.sql (the PROD CHECK of 0450, the same read before and after the deploy) and rollback-0450.sql (a draft) from the
// hunks of migration 0450 itself, so the checks cannot drift from the file.   node scripts/ops/harness/battle-stats/gen-checks.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const HERE = path.dirname(fileURLToPath(import.meta.url))
const MIG = path.resolve(HERE, '../../../../supabase/migrations/20260818000450_a_fight_shows_its_ships_and_escaping_is_hard.sql')
const s = readFileSync(MIG, 'utf8').replaceAll('\r', '')
const re = /\('([a-z_.]+\([a-z ,]*\))', (\d+),\n\$h\$([\s\S]*?)\$h\$,\n\$h\$([\s\S]*?)\$h\$\)/g
const hunks = []
for (let x; (x = re.exec(s)); ) hunks.push({ fn: x[1], ord: Number(x[2]), old: x[3], neu: x[4] })
if (hunks.length !== 9) throw new Error(`hunks ${hunks.length}, 9 expected`)
const fns = [...new Set(hunks.map((h) => h.fn))]
const count = (hay, needle) => hay.split(needle).length - 1
const E = (t) => "E'" + t.replaceAll('\\', '\\\\').replaceAll("'", "''").replaceAll('\n', '\\n') + "'"
const key = (h) => `${h.fn.replace(/\(.*/, '').replace(/^.*\./, '')}.${h.ord}`
const afterOld = hunks.map((h) => `${key(h)}: ${count(h.neu, h.old)}`).join(', ')

const check = `-- 0450 PROD CHECK, BEFORE the deploy AND AGAIN AFTER IT (the same read), read-only, ONE statement. GENERATED by gen-checks.mjs from the migration's own hunks.
--   npx --yes supabase@2.120.0 db query --linked --output-format json -f scripts/ops/harness/battle-stats/check.sql
-- Run scripts/ops/harness/db-health/gate.sql first (gate_ok true). One row, one jsonb column \`r\`. It reads the catalog (four function bodies), a dozen knobs,
-- public.battles of the last hour (RAID rows are kept 48 h; ~100 an hour) and the beat's ring. No big table is scanned; stable functions only.
-- BEFORE, wanted: head 20260818000449 (the migration before it); applied false; old: every count 1 (each old text once in the live body); new: every count 0;
--   knobs raid_flee_floor 0.1, raid_flee_max 0.8 and no flee_* / raid_flee_base; cards_1h 0. Write down raids_1h (outcomes, and of those that opened FLEE).
-- AFTER (30 minutes), wanted: head 20260818000450; applied true; new: every count 1; old {${afterOld}} (an old text that stands inside its new text still counts 1);
--   knobs raid_flee_floor 0.03, raid_flee_max 0.45, raid_flee_base 0.1, flee_per_level 0.03, flee_level_max 0.15, flee_hurt_under 0.5, flee_hurt_max 0.2, flee_per_try 0.05;
--   cards_1h = every tick battle opened since the deploy (no_card only battles opened before it); sheet_kb mean about +1 to +2 over BEFORE, ticks_kb about +0.3;
--   raids_1h.flee: fewer EVADED, more PLUNDERED than BEFORE (the replay of 100 sheets: got away by running 15 of 39 before, 4 of 39 after; all raids EVADED 47 -> 36,
--   PLUNDERED 22 -> 32); rolls_pct: every roll within 3..45; stuck 0; span_s as before (max <= 75); beat < 1,000 ms and no worse than BEFORE.
-- ROLLBACK (the owner's knobs, the old chance to the digit): scripts/ops/harness/battle-stats/rollback-0450.sql.
begin transaction read only;
with hk(k, fn, old, neu) as (values
${hunks.map((h) => `  ('${key(h)}', '${h.fn}', ${E(h.old)}, ${E(h.neu)})`).join(',\n')}
), body as (
  select f.fn, replace(pg_get_functiondef(f.fn::regprocedure), E'\\r', '') as def
    from (values ${fns.map((f) => `('${f}')`).join(', ')}) f(fn)
), b as (
  select x.id, x.kind, x.status, x.started_at, x.resolves_at, x.result, x.sheet, x.ticks
    from public.battles x where x.started_at > now() - interval '1 hour' and x.ticks is not null and x.ticks <> 'null'::jsonb
)
select jsonb_build_object(
  'at', now(),
  'head', (select max(m.version) from supabase_migrations.schema_migrations m),
  'applied', to_regprocedure('public.battle_hull_card(uuid)') is not null,
  'old', (select jsonb_object_agg(hk.k, (length(body.def) - length(replace(body.def, hk.old, ''))) / length(hk.old)) from hk join body on body.fn = hk.fn),
  'new', (select jsonb_object_agg(hk.k, (length(body.def) - length(replace(body.def, hk.neu, ''))) / length(hk.neu)) from hk join body on body.fn = hk.fn),
  'bodies', (select jsonb_object_agg(body.fn, md5(body.def)) from body),
  'volatility', (select jsonb_object_agg(p.oid::regprocedure::text, p.provolatile) from pg_proc p
                  where p.oid in ('public.fleet_kind(uuid)'::regprocedure, 'public.level_in_force(numeric)'::regprocedure, 'world.ship_stats(uuid)'::regprocedure,
                                  'public.ship_base(uuid)'::regprocedure, 'public.captain_level(uuid,text)'::regprocedure)),
  'knobs', (select jsonb_object_agg(k.key, k.value) from public.world_config k
             where k.key ~ '^(raid_flee|flee_)' or k.key in ('fight_flee_base', 'fight_flee_floor', 'fight_evade_max', 'fight_evade_per_sighting', 'levels_bite',
                                                                             'npc_ship_level', 'tick_fight_kinds', 'ship_level_accuracy_per_level', 'ship_level_sighting_per_level')),
  'tick_1h', (select count(*) from b),
  'cards_1h', (select count(*) from b where not exists (select 1 from jsonb_array_elements(coalesce(b.sheet -> 'a', '[]'::jsonb) || coalesce(b.sheet -> 'b', '[]'::jsonb)) h where not (h ? 'lv'))),
  'no_card_newest', (select max(b.started_at) from b where exists (select 1 from jsonb_array_elements(coalesce(b.sheet -> 'a', '[]'::jsonb) || coalesce(b.sheet -> 'b', '[]'::jsonb)) h where not (h ? 'lv'))),
  'sheet_kb', (select round(avg(length(b.sheet::text)) / 1024.0, 2) from b),
  'ticks_kb', (select round(avg(length(b.ticks::text)) / 1024.0, 2) from b),
  'raids_1h', (select jsonb_build_object(
                 'all', (select coalesce(jsonb_object_agg(z.o, z.n), '{}'::jsonb) from (select coalesce(b.ticks ->> 'out', '-') as o, count(*) as n from b where b.kind = 'RAID' group by 1) z),
                 'flee', (select coalesce(jsonb_object_agg(z.o, z.n), '{}'::jsonb) from (select coalesce(b.ticks ->> 'out', '-') as o, count(*) as n from b where b.kind = 'RAID' and b.ticks #>> '{ai,a}' = 'FLEE' group by 1) z),
                 'fled', (select count(*) from b where b.kind = 'RAID' and coalesce((b.ticks #>> '{r,fled}')::boolean, false)))),
  'rolls_pct', (select jsonb_build_object('n', count(*), 'min', min((e ->> 3)::numeric), 'max', max((e ->> 3)::numeric), 'away', count(*) filter (where e ->> 4 = '1'))
                  from b cross join lateral jsonb_array_elements(b.ticks -> 'e') e where b.kind = 'RAID' and e ->> 2 = 'X' and e ->> 1 = '0'),
  'span_s', (select jsonb_build_object('mean', round(avg(extract(epoch from b.resolves_at - b.started_at))), 'max', round(max(extract(epoch from b.resolves_at - b.started_at)))) from b),
  'stuck', (select count(*) from b where b.status = 'FIGHTING' and b.resolves_at < now() - interval '2 minutes'),
  'beat', (select jsonb_build_object('mean_ms', round(avg(a.ms)), 'n', count(*)) from public.arrivals_beats a where a.at > now() - interval '5 minutes')
) as r;
commit;
`

const rollback = `-- 0450 ROLLBACK DRAFT (forward, owner only; NOT a migration until the owner asks for one; then it takes prod head + 1). GENERATED by gen-checks.mjs.
-- QUICK, THE KNOBS ALONE (no code moves; 0450's self-assert and proof 152 BS_OLD prove this is the old chance to the digit, for every NEW roll and every re-run):
--   update public.world_config set value = to_jsonb(0.10) where key = 'raid_flee_floor';
--   update public.world_config set value = to_jsonb(0.80) where key = 'raid_flee_max';
--   update public.world_config set value = to_jsonb(0.15) where key = 'raid_flee_base';
--   update public.world_config set value = to_jsonb(0) where key in ('flee_per_level', 'flee_hurt_max', 'flee_per_try');
-- SOFTER, NOT OFF (the replay of 100 prod sheets, docs/dev-log/2026-11-16-battle-stats.md): raid_flee_floor 0.05, raid_flee_base 0.15, flee_per_level 0.02,
--   flee_per_try 0.03 (got away by running 9 of 39 instead of 4; the old rule 15).
-- The cards on the sheet and the screen's \`ships\` are a read: they need no rollback (an old client ignores \`ships\`, \`rc\`, \`lv\`).
-- WHOLE: the nine hunks of 0450 reversed (each NEW text back to its OLD, once each, as its self-assert proves they reverse), in this order, then
--   drop function public.battle_hull_card(uuid); drop function public.ship_level(uuid);   -- after public.fight_card and public.tick_battle_run no longer call them
--   delete from public.world_config where key in ('raid_flee_base', 'flee_per_level', 'flee_level_max', 'flee_hurt_under', 'flee_hurt_max', 'flee_per_try');
--   and raid_flee_floor 0.10, raid_flee_max 0.80 as above. Hulls already carded on a sheet keep their card (read by nothing then).
${hunks.map((h) => `--   ${key(h)}  (${h.fn})`).join('\n')}
-- THIS FILE IS NOTES, every line a comment: nothing in it runs. It carries the harness guard (the next line) so the tree's reader knows it for a
-- local draft and not a prod check, and so that a statement uncommented here later still refuses to run on production.
do $$ begin if inet_server_addr() is not null then raise exception 'local PGlite world only: this scene writes'; end if; end $$;
`

const files = { 'check.sql': check, 'rollback-0450.sql': rollback }
if (process.argv.includes('--check')) {
  for (const [f, text] of Object.entries(files)) if (readFileSync(path.join(HERE, f), 'utf8').replaceAll('\r', '') !== text) throw new Error(`${f} is not what gen-checks.mjs writes: run it`)
  console.log('battle-stats checks: held to the migration')
} else {
  for (const [f, text] of Object.entries(files)) writeFileSync(path.join(HERE, f), text)
  console.log(`wrote ${Object.keys(files).join(', ')} (${hunks.length} hunks, ${fns.length} functions)`)
}
