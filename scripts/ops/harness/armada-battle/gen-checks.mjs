// gen-checks.mjs: writes the PROD CHECK files that carry 0379's hunks (before.sql, after.sql) and the forward rollback draft
// (rollback-0379.sql) from the migration's own text, so the texts checked on prod are the texts the migration cuts; and, with
// --proof-write, writes the same hunks into proof 69 (scripts/db/proofs/69_armada_battle.sql rebuilds the old bodies from them).
// LOCAL ONLY; not in CI.
//   node scripts/ops/harness/armada-battle/gen-checks.mjs [--proof-write]
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const MIG = path.resolve(HERE, '../../../../supabase/migrations/20260818000379_an_armada_fights_as_one.sql')
const sql = readFileSync(MIG, 'utf8').replaceAll('\r', '')
const re = /\(('[a-z_.]+\([a-z ,]*\)'), (\d+),\n\$o\$([\s\S]*?)\$o\$,\n\$n\$([\s\S]*?)\$n\$\)/g
export const hunks = [...sql.matchAll(re)].map((m) => ({ fn: m[1].slice(1, -1), n: Number(m[2]), old: m[3], new: m[4] }))
export const HUNKS = 13
if (hunks.length !== HUNKS) throw new Error(`expected ${HUNKS} hunks in the migration, found ${hunks.length}`)
for (const h of hunks) if (h.old.includes('$h$') || h.new.includes('$h$')) throw new Error('a hunk holds the quote tag')

export const CUT = [...new Set(hunks.map((h) => h.fn))]
export const NEW_FNS = [
  'public.battle_armada(uuid,timestamp with time zone)',
  'public.attack_armada_gates(uuid,uuid,timestamp with time zone)',
  'public.battle_armada_join(uuid,text,uuid,timestamp with time zone)',
  'public.battle_armada_sheet(uuid)',
  'public.battle_armada_note(uuid)',
  'public.attack_armada_close(uuid,jsonb,bigint,bigint)',
  'public.battle_armada_view(uuid,uuid)',
]
const rowsOf = (cast) => hunks.map((h) => `  ('${h.fn}'${cast}, ${h.n}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')

if (process.argv.includes('--proof-write')) {
  // the rows of proof 69, written between its two marker lines
  const PROOF = path.resolve(HERE, '../../../db/proofs/69_armada_battle.sql')
  const text = readFileSync(PROOF, 'utf8').replaceAll('\r', '')
  const at = text.indexOf('-- hunks:begin\n')
  const to = text.indexOf('-- hunks:end\n')
  if (at < 0 || to < at) throw new Error('proof 69 has no hunk markers')
  writeFileSync(PROOF, text.slice(0, at) + '-- hunks:begin\n' + rowsOf('') + '\n' + text.slice(to))
  console.log(`wrote ${hunks.length} hunks into proof 69`)
  process.exit(0)
}

if (path.resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  const cte = `with h(fn, ord, old, new) as (values\n${rowsOf('::text')}\n), d as (\n  select h.*, replace(pg_get_functiondef(to_regprocedure(h.fn)), chr(13), '') as def from h\n)`
  const run = (f) => `npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/armada-battle/${f}`
  const fnArr = `array[${NEW_FNS.map((f) => `'${f}'`).join(', ')}]`
  const bodies = `array[${CUT.map((f) => `'${f}'`).join(', ')}]`
  const made = `(select count(*) from unnest(${fnArr}) f where to_regprocedure(f) is not null)`
  const how = `(select pg_get_constraintdef(c.oid) from pg_constraint c where c.conrelid = to_regclass('public.battle_sides') and c.conname = 'battle_sides_how_check')`
  const pvp = `case when (select p.prosrc from pg_proc p where p.oid = to_regprocedure('public.battle_open(text,uuid,uuid,timestamp with time zone)')) like '%E_HUMAN_TARGET: no player fights another player%'
             and (select p.prosrc from pg_proc p where p.oid = to_regprocedure('public.attack_for(uuid,uuid,uuid,integer,timestamp with time zone)')) like '%E_HUMAN_TARGET%no player attacks another player%'
            then 'both refusals stand' else 'A REFUSAL IS GONE' end`

  writeFileSync(
    path.join(HERE, 'before.sql'),
    `-- 0379 PROD CHECK (before), read-only, ONE statement: ${run('before.sql')}
-- IT DEPLOYS AFTER 0375 (the attacks work) AND 0378: head 20260818000378. Attacks may be LIT by then, and the file takes the switch as it finds it.
-- Wanted: ${HUNKS} rows; EVERY old_times 1 and new_times 0 (a 0 in old_times means a file deployed since batch 6 re-cut a line 0379 anchors on: do not deploy, re-cut the hunk);
-- made 0 (none of 0379's seven functions yet); how_check lists OPENED, ESCORT, CALLED and not ARMADA; armada_sides 0;
-- attack is printed (true or false: both are fine); fighting is printed (battles being fought now, at most 5 counted: the deploy holds public.battle_sides for about a
-- second, so a quiet moment is kinder, and a lone fleet's battle goes on as it was); armadas and armada_fleets are printed (how many armadas stand);
-- pvp "both refusals stand".
-- Keep \`bodies\` (each cut body's md5): the dev-log holds the local values on batch 6.
-- Generated by scripts/ops/harness/armada-battle/gen-checks.mjs from the migration's own hunks. Only the catalog, one knob and whether a row exists in four tables are read.
begin transaction read only;
${cte}
select fn, ord,
       (length(def) - length(replace(def, old, ''))) / length(old) as old_times,
       (length(def) - length(replace(def, new, ''))) / length(new) as new_times,
       ${made} as made,
       ${how} as how_check,
       public.attack_on() as attack,
       (select count(*) from (select 1 from public.battles b where b.status = 'FIGHTING' limit 5) q) as fighting,
       (select count(*) from (select 1 from public.battle_sides bs where bs.how not in ('OPENED', 'ESCORT', 'CALLED') limit 5) q) as armada_sides,
       (select count(*) from (select 1 from public.armadas limit 50) q) as armadas,
       (select count(*) from (select 1 from public.armada_fleets limit 300) q) as armada_fleets,
       ${pvp} as pvp,
       (select jsonb_object_agg(f, md5(replace(pg_get_functiondef(to_regprocedure(f)), chr(13), ''))) from unnest(${bodies}) f) as bodies,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from d order by fn, ord;
commit;
`,
  )

  writeFileSync(
    path.join(HERE, 'after.sql'),
    `-- 0379 PROD CHECK (after), read-only, ONE statement: ${run('after.sql')}
-- Wanted: ${HUNKS} rows; every new_times 1; made 7; client_fns 0 and anon_fns 0 (no client reaches a new function); how_check lists OPENED, ESCORT, CALLED, ARMADA;
-- attack as it was before the deploy (the file does not write it); armada_sides is printed (0 right after a dark deploy; lit, an armada may have attacked already);
-- pvp "both refusals stand"; switch_first "yes" (in both doors the switch is read before the first line of 0379); if attack is true the News face has one new row,
-- "Armada battles"; head 20260818000379. Keep \`bodies\` (the new md5 of each cut body).
-- Generated by scripts/ops/harness/armada-battle/gen-checks.mjs from the migration's own hunks. The catalog, one knob and whether one row exists in two tables are read.
begin transaction read only;
${cte}
select fn, ord,
       (length(def) - length(replace(def, new, ''))) / length(new) as new_times,
       ${made} as made,
       (select count(*) from unnest(${fnArr}) f where has_function_privilege('authenticated', to_regprocedure(f), 'execute')) as client_fns,
       (select count(*) from unnest(${fnArr}) f where has_function_privilege('anon', to_regprocedure(f), 'execute')) as anon_fns,
       ${how} as how_check,
       public.attack_on() as attack,
       (select count(*) from (select 1 from public.battle_sides bs where bs.how = 'ARMADA' limit 5) q) as armada_sides,
       ${pvp} as pvp,
       case when (select p.prosrc from pg_proc p where p.oid = to_regprocedure('public.battle_open(text,uuid,uuid,timestamp with time zone)')) like '%if not public.attack_on() then%public.battle_armada_join(%'
             and (select p.prosrc from pg_proc p where p.oid = to_regprocedure('public.attack_for(uuid,uuid,uuid,integer,timestamp with time zone)')) like '%if not public.attack_on() then%public.attack_armada_gates(%'
            then 'yes' else 'NO' end as switch_first,
       (select jsonb_object_agg(f, md5(replace(pg_get_functiondef(to_regprocedure(f)), chr(13), ''))) from unnest(${bodies}) f) as bodies,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from d order by fn, ord;
commit;
`,
  )

  writeFileSync(
    path.join(HERE, 'volatility.sql'),
    `-- 0379 PROD CHECK (volatility), read-only, ONE statement: ${run('volatility.sql')}
-- Run it BEFORE before.sql and after.sql. Prints provolatile of every function they call; wanted: all 's' or 'i'.
begin transaction read only;
select jsonb_object_agg(f.fn, (select p.provolatile::text from pg_proc p where p.oid = to_regprocedure(f.fn))) as provolatile
  from (values ('pg_get_functiondef(oid)'), ('pg_get_constraintdef(oid)'), ('to_regprocedure(text)'), ('to_regclass(text)'), ('replace(text,text,text)'), ('md5(text)'),
               ('has_function_privilege(name,oid,text)'), ('public.attack_on()')) f(fn);
commit;
`,
  )

  // THE FORWARD ROLLBACK OF THE WHOLE SLICE, as a draft a new migration is cut from (owner only). It carries the same hunks, reversed.
  writeFileSync(
    path.join(HERE, 'rollback-0379.sql'),
    `-- 0379 FORWARD ROLLBACK, A DRAFT (docs/ARMADA.md section 7; docs/dev-log/2026-11-13-armada-battle.md). NOT a prod check and NOT a migration yet: to use it, strip the guard line, give it
-- the next number, and deploy it as any migration (owner only). THE FIRST ROLLBACK IS THE SWITCH: attack_enabled false stops new battles; a running battle finishes with the sides it has.
-- This draft is the second: it refuses while a battle is FIGHTING or a side row says ARMADA (the constraint could not go back over such a row: those rows are the record of battles
-- fought as an armada, and whoever uses this decides what becomes of them first), then swaps 0379's OLD and NEW (each NEW text once, reversed; judged as a round trip on the live
-- body, since a later file may have re-cut the same bodies), drops the seven functions and puts the constraint back to its three words.
-- Tested locally: run.mjs --apply on ONE scene file holding this draft and then before.sql's statement (a scene is rolled back at its end, so the two must share one file):
-- ${HUNKS} rows, every old_times 1, new_times 0, made 0, how_check without ARMADA.
-- Generated by scripts/ops/harness/armada-battle/gen-checks.mjs from the migration's own hunks.
-- LOCAL PGlite WORLD ONLY while it carries this line (scripts/ops/harness/README.md): it writes. The first statement refuses a real server (inet_server_addr() is not null there, null on PGlite).
do $$ begin if inet_server_addr() is not null then raise exception 'local PGlite world only: this scene writes'; end if; end $$;
do $r$
declare
  f      record;
  h      record;
  v_live text;
  v_def  text;
  v_back text;
begin
  perform set_config('statement_timeout', '45s', true);
  perform set_config('lock_timeout', '5s', true);
  if to_regprocedure('public.battle_armada_join(uuid,text,uuid,timestamp with time zone)') is null then
    raise exception '0379 rollback refuses: 0379 is not applied in this world';
  end if;
  if exists (select 1 from public.battles b where b.status = 'FIGHTING') then
    raise exception '0379 rollback refuses: a battle is being fought. Set attack_enabled false, wait for it to close, and deploy this again.';
  end if;
  if exists (select 1 from public.battle_sides bs where bs.how = 'ARMADA') then
    raise exception '0379 rollback refuses: a side row says ARMADA (a battle was fought as an armada). Decide what becomes of those rows first.';
  end if;
  create temp table hunks_back (fn text, n int, old text, new text) on commit drop;
  insert into hunks_back (fn, n, old, new) values
${rowsOf('')};
  for f in select distinct x.fn from hunks_back x order by x.fn loop
    v_live := replace(pg_get_functiondef(f.fn::regprocedure), chr(13), '');
    v_def := v_live;
    for h in select * from hunks_back x where x.fn = f.fn order by x.n desc loop
      if (length(v_def) - length(replace(v_def, h.new, ''))) / length(h.new) <> 1 then
        raise exception '0379 rollback: hunk % of % is not in the live body exactly once: the deployed body is not the one 0379 left', h.n, f.fn;
      end if;
      v_def := replace(v_def, h.new, h.old);
    end loop;
    v_back := v_def;
    for h in select * from hunks_back x where x.fn = f.fn order by x.n loop
      v_back := replace(v_back, h.old, h.new);
    end loop;
    if v_back is distinct from v_live then
      raise exception '0379 rollback: % does not come back to the live body when the hunks are put back', f.fn;
    end if;
    execute v_def;
  end loop;
  drop function public.battle_armada_view(uuid, uuid);
  drop function public.attack_armada_close(uuid, jsonb, bigint, bigint);
  drop function public.battle_armada_note(uuid);
  drop function public.battle_armada_sheet(uuid);
  drop function public.battle_armada_join(uuid, text, uuid, timestamp with time zone);
  drop function public.attack_armada_gates(uuid, uuid, timestamp with time zone);
  drop function public.battle_armada(uuid, timestamp with time zone);
  alter table public.battle_sides drop constraint battle_sides_how_check;
  alter table public.battle_sides add constraint battle_sides_how_check check (how = any (array['OPENED'::text, 'ESCORT'::text, 'CALLED'::text]));
  raise notice '0379 rollback ok: ${CUT.length} bodies at their pre-images, 7 functions gone, the constraint at its three words';
end
$r$;
`,
  )
  console.log(`wrote before.sql, after.sql, volatility.sql and rollback-0379.sql (${HUNKS} hunks, ${CUT.length} bodies)`)
}
