// Writes before.sql (run on prod BEFORE the deploy), after.sql (AFTER it), volatility.sql (either side) and rollback-0391.sql (a DRAFT, local only).
// Every prod check is ONE read-only statement: the catalog and plain SELECTs of world_config and the sea tables. No game function is called.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const here = path.dirname(fileURLToPath(import.meta.url))
const NAME = '20260818000391_a_wall_says_what_is_short.sql'
const mig = readFileSync(path.join(here, '../../../../supabase/migrations', NAME), 'utf8').replace(/\r/g, '')
const hunks = [...mig.matchAll(/\((\d+), '((?:world|public|cmd|voyage)\.[a-z_]+\([a-z,[\]]*\))',\n\$h\$([\s\S]*?)\$h\$,\n\$h\$([\s\S]*?)\$h\$\)/g)].map((m) => ({ n: Number(m[1]), fn: m[2], old: m[3], new: m[4] }))
if (hunks.length !== 10) throw new Error(`expected 10 hunks, found ${hunks.length}`)
const count = (hay, needle) => hay.split(needle).length - 1
// after the deploy an OLD text is still found wherever a NEW text of the same body carries it (a NEW that keeps its OLD line)
for (const h of hunks) h.oldAfter = hunks.filter((x) => x.fn === h.fn).reduce((n, x) => n + count(x.new, h.old), 0)
const rows = hunks.map((h) => `  ('${h.fn}'::text, ${h.n}, ${h.oldAfter}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')
const run = (f) => `npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/sea-wall/${f}`
const NEW_FNS = ['public.far_powers()', 'world.sea_zone_map()', 'public.sea_floor(uuid,jsonb)']
const catalog = `with h(fn, ord, old_after_wanted, old, new) as (values
${rows}
), d as (
  select h.*, replace(pg_get_functiondef(to_regprocedure(h.fn)), chr(13), '') as def from h
)
select fn, ord,
       (length(def) - length(replace(def, old, ''))) / length(old) as old_times,
       (length(def) - length(replace(def, new, ''))) / length(new) as new_times,
       old_after_wanted,
       (select count(*) from unnest(array[${NEW_FNS.map((f) => `'${f}'`).join(', ')}]) f where to_regprocedure(f) is not null) as new_functions,
       (select jsonb_object_agg(c.key, c.value) from public.world_config c where c.key in ('sea_conditions_bite', 'sea_conditions_bite_npc', 'pirates_joinable')) as switches,
       (select count(*) from public.sea_zones) as seas,
       (select count(*) from public.sea_zone_cells) as map_rows,
       (select count(*) from public.ports p join public.sea_leg_asks a on a.from_port = p.id and a.to_port = p.id where p.kind = 'HARBOUR') as harbours_with_a_sea,
       (select count(*) from public.ports p where p.kind = 'HARBOUR') as harbours,
       -- the countries whose capital's sea asks a title, said from the tables (what public.far_powers answers), and how many human companies sail for one
       (select string_agg(n.code, ' ' order by n.code)
          from public.nations n join public.ports p on p.code = n.capital_port_code
          join public.sea_leg_asks a on a.from_port = p.id and a.to_port = p.id join public.sea_zones z on z.code = a.zones[1]
         where z.title_min > 1) as far_powers,
       (select count(*) from public.players pl join public.nations n on n.id = pl.nation_id join public.ports p on p.code = n.capital_port_code
          join public.sea_leg_asks a on a.from_port = p.id and a.to_port = p.id join public.sea_zones z on z.code = a.zones[1]
         where not pl.is_npc and z.title_min > 1) as human_companies_of_a_far_power,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from d order by ord;`
writeFileSync(path.join(here, 'before.sql'), `-- 0391 PROD CHECK (before), read-only, ONE statement: ${run('before.sql')}
-- Wanted: 8 rows (1 of public.sea_refusal, 1 of cmd.found_house, 3 of world.sea_conditions, 1 of public.client_rpc_entry_points, 1 of world.route_legs,
-- 1 of cmd.refusal_caught); every
-- old_times 1; every new_times 0; new_functions 0; sea_conditions_bite false; seas 64; map_rows 720; harbours_with_a_sea = harbours; head = 20260818000390 (0391 meets
-- 0390, gear wear: the armada's battle 0379, the pirate company 0380 and 0381 and gear wear 0390 deploy before it). far_powers is what the new function will answer (local: AYU BAN GUJ JOS JPN MLB MNG MUG PER PIR RUS); human_companies_of_a_far_power says how
-- many companies already sail for one (they are not touched by this file; the lighting file judges them).
-- Generated by scripts/ops/harness/sea-wall/gen-checks.mjs from the migration's own hunks. Only the catalog, world_config and the sea tables are read.
begin transaction read only;
${catalog}
commit;
`)
writeFileSync(path.join(here, 'after.sql'), `-- 0391 PROD CHECK (after), read-only, ONE statement: ${run('after.sql')}
-- Wanted: 8 rows; every new_times 1; every old_times = its old_after_wanted (an OLD line that a NEW text keeps is still found: the column says how often);
-- new_functions 3; the switches as before (this file sets none: sea_conditions_bite still false); head 20260818000391.
-- Generated by scripts/ops/harness/sea-wall/gen-checks.mjs from the migration's own hunks. Only the catalog, world_config and the sea tables are read.
begin transaction read only;
${catalog}
commit;
`)
writeFileSync(path.join(here, 'volatility.sql'), `-- 0391 PROD CHECK (either side), read-only, ONE statement: ${run('volatility.sql')}
-- The cut bodies, the two new functions (after the deploy) and what they compose: volatility, definer, settings and who may run it. Wanted: every row s or
-- i (cmd.refusal_caught i) except cmd.found_house (v, a command); world.sea_conditions, world.route_legs, world.sea_zone_map (after) and cmd.found_house open to authenticated and
-- not to anon; public.sea_refusal, public.sea_gate, public.far_powers (after), public.fleet_wave, public.title_level server only. The same rows before and
-- after but for the two new functions.
begin transaction read only;
select p.oid::regprocedure::text as fn, p.provolatile as volatile, p.prosecdef as definer, coalesce(p.proconfig::text, '') as settings,
       has_function_privilege('authenticated', p.oid, 'execute') as authenticated_may, has_function_privilege('anon', p.oid, 'execute') as anon_may
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
 where (n.nspname, p.proname) in (('public', 'sea_refusal'), ('cmd', 'found_house'), ('world', 'sea_conditions'), ('world', 'route_legs'), ('world', 'sea_zone_map'),
                                  ('public', 'far_powers'), ('public', 'sea_gate'), ('public', 'sea_conditions_on'), ('public', 'fleet_wave'), ('public', 'title_level'),
                                  ('public', 'nation_joinable'), ('public', 'client_rpc_entry_points'), ('cmd', 'refusal_caught'), ('cmd', 'refusal'))
 order by 1;
commit;
`)
const back = hunks.map((h) => `  ('${h.fn}', ${h.n}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')
writeFileSync(path.join(here, 'rollback-0391.sql'), `-- 0391 FORWARD ROLLBACK, A DRAFT. NOT a prod check and NOT a migration yet: to use it, strip the guard line, give it the next number, add its news line
-- ("-- news: none") and deploy it as any migration (owner only). It swaps 0391's OLD and NEW: each of the eight cut bodies loses exactly what 0391 added (each
-- NEW text once, reversed, judged as a round trip on the live body: no fixed digest, a later file may have re-cut it), and the three new functions are dropped.
-- The rule's figures lose short_title / short_wave, the conditions read loses harbours / port / seas / far_powers, a leg loses \`sea\`, a refused order loses the sea's figures, the way home (public.sea_floor) is gone from the gate, the pathfinder and the read, and founding under a far
-- power is no longer refused when the conditions bite: SO IF sea_conditions_bite IS TRUE, TURN IT OFF FIRST (or accept companies born behind a wall).
-- The client reads every one of those keys as optional and falls back (no shading, no "which is short").
-- Tested locally (run.mjs --apply=0391 on this file followed by before.sql in one scene): every old_times 1, new_times 0, new_functions 0.
-- Generated by scripts/ops/harness/sea-wall/gen-checks.mjs from the migration's own hunks.
-- LOCAL PGlite WORLD ONLY while it carries this line (scripts/ops/harness/README.md): it writes. The first statement refuses a real server (inet_server_addr() is not null there, null on PGlite).
do $$ begin if inet_server_addr() is not null then raise exception 'local PGlite world only: this scene writes'; end if; end $$;
do $r$
declare
  f      record;
  h      record;
  v_live text;
  v_def  text;
  v_back text;
begin
  perform set_config('statement_timeout', '45s', true);
  perform set_config('lock_timeout', '5s', true);
  if to_regprocedure('world.sea_zone_map()') is null or to_regprocedure('public.far_powers()') is null then
    raise exception '0391 rollback refuses: 0391 is not applied in this world';
  end if;
  create temp table hunks_back (fn text, n int, old text, new text) on commit drop;
  insert into hunks_back (fn, n, old, new) values
${back};
  for f in select distinct x.fn from hunks_back x order by 1 loop
    v_live := replace(pg_get_functiondef(f.fn::regprocedure), chr(13), '');
    v_def := v_live;
    -- the NEW texts out, last first
    for h in select * from hunks_back x where x.fn = f.fn order by n desc loop
      if (length(v_def) - length(replace(v_def, h.new, ''))) / length(h.new) <> 1 then
        raise exception '0391 rollback: hunk % of % is not in the live body exactly once: a later migration re-cut the text 0391 added; cut this rollback again from the live body', h.n, f.fn;
      end if;
      v_def := replace(v_def, h.new, h.old);
    end loop;
    -- a round trip: the hunks put back give the live body again
    v_back := v_def;
    for h in select * from hunks_back x where x.fn = f.fn order by n loop
      if (length(v_back) - length(replace(v_back, h.old, ''))) / length(h.old) <> 1 then
        raise exception '0391 rollback: hunk % of %: its OLD text is not in the reversed body exactly once', h.n, f.fn;
      end if;
      v_back := replace(v_back, h.old, h.new);
    end loop;
    if v_back <> v_live then
      raise exception '0391 rollback: % does not come back to the live body when the hunks are put back', f.fn;
    end if;
    execute v_def;
  end loop;
  drop function world.sea_zone_map();
  drop function public.far_powers();
  drop function public.sea_floor(uuid, jsonb);
  raise notice '0391 rollback ok: 8 bodies less 0391''s 10 hunks (a round trip on each), the 3 new functions gone';
end
$r$;
`)
