// gen-checks.mjs — writes before.sql and after.sql (the PROD CHECKS of 0338) from the migration's own hunks, so the texts they test are the very texts the file applies.
//   node scripts/ops/harness/the-brethren/gen-checks.mjs
// Each output is ONE read-only statement (docs/OPS_HEALTH.md; CLAUDE.md): npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/the-brethren/before.sql
// Every function called is STABLE or IMMUTABLE (pg_get_functiondef, to_regprocedure, replace, md5, treasury_balance, the three new readers once they exist, city_capital, convoy_ships_wanted); volatility.sql prints it first.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const HERE = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))
const sql = readFileSync(path.join(HERE, '..', '..', '..', '..', 'supabase', 'migrations', '20260818000338_the_brethren.sql'), 'utf8').replaceAll('\r', '')
const start = sql.indexOf('insert into hunks_0338 values')
if (start < 0) throw new Error('no hunks in the migration')
const block = sql.slice(start, sql.indexOf('-- every hunk is checked against its live body BEFORE'))
const hunks = [...block.matchAll(/\('([^']+)', (\d+),\n\$h\$([\s\S]*?)\$h\$,\n\$h\$([\s\S]*?)\$h\$\)/g)].map((m) => ({ fn: m[1], ord: Number(m[2]), old: m[3], new: m[4] }))
if (hunks.length !== 14) throw new Error(`${hunks.length} hunks parsed, the migration has 14`)
for (const h of hunks) if (h.old.includes('$h$') || h.new.includes('$h$')) throw new Error('a hunk holds the dollar tag')

const values = hunks.map((h) => `  ('${h.fn}'::text, ${h.ord}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')
const homes = `array['POR', 'LGA', 'GOT', 'DJE']`

const head = (name, what) => `-- 0338 PROD CHECK (${name}), read-only, ONE statement: npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/the-brethren/${name}.sql
-- ${what}
-- Generated by scripts/ops/harness/the-brethren/gen-checks.mjs from the migration's own hunks. Every function called is STABLE or IMMUTABLE (run volatility.sql first; it prints provolatile of each).
begin transaction read only;
with h(fn, ord, old, new) as (values
${values}
), x as (
  select h.fn, h.ord,
         (length(d.def) - length(replace(d.def, h.old, ''))) / length(h.old) as old_times,
         (length(d.def) - length(replace(d.def, h.new, ''))) / length(h.new) as new_times,
         md5(d.def) as now_md5,
         md5(replace(d.def, h.old, h.new)) as with_hunk_md5,
         md5(replace(d.def, h.new, h.old)) as without_hunk_md5,
         md5(coalesce(p.proacl::text, '') || p.provolatile::text || p.prosecdef::text || coalesce(p.proconfig::text, '') || p.proparallel::text || p.proowner::text || p.prolang::text) as attr_md5
    from h
    cross join lateral (select to_regprocedure(h.fn) as oid) o
    cross join lateral (select replace(pg_get_functiondef(o.oid), E'\\r', '') as def) d
    join pg_proc p on p.oid = o.oid
)`

