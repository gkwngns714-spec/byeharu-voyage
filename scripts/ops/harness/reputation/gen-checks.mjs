// gen-checks.mjs: writes the two PROD CHECK files that carry 0352's hunks (before-hunks.sql, after.sql) from the
// migration's own text, so the texts checked on prod are the texts the migration cuts. LOCAL ONLY; not in CI.
//   node scripts/ops/harness/reputation/gen-checks.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const MIG = path.resolve(HERE, '../../../../supabase/migrations/20260818000352_every_success_earns_reputation.sql')
const sql = readFileSync(MIG, 'utf8').replaceAll('\r', '')
const re = /\('([a-z_.]+\([a-z ,]*\))', (\d+),\n\$o\$([\s\S]*?)\$o\$,\n\$n\$([\s\S]*?)\$n\$\)/g
const hunks = [...sql.matchAll(re)].map((m) => ({ fn: m[1], n: m[2], old: m[3], new: m[4] }))
if (hunks.length !== 5) throw new Error(`expected 5 hunks in the migration, found ${hunks.length}`)
for (const h of hunks) if (h.old.includes('$h$') || h.new.includes('$h$')) throw new Error('a hunk holds the quote tag')
const values = hunks.map((h) => `  ('${h.fn}'::text, ${h.n}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')
const cte = `with h(fn, ord, old, new) as (values\n${values}\n), d as (\n  select h.*, replace(pg_get_functiondef(h.fn::regprocedure), chr(13), '') as def from h\n)`
const run = (f) => `npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/reputation/${f}`
const KNOBS = `(c.key = 'reputation_on' or (c.key like 'rep\\_%' and c.key not like 'repair%'))`
const FNS = `n.nspname = 'public' and p.proname like 'reputation\\_%'`

writeFileSync(
  path.join(HERE, 'before-hunks.sql'),
  `-- 0352 PROD CHECK (before), read-only, ONE statement: ${run('before-hunks.sql')}
-- Wanted: 5 rows; every old_times 1 and new_times 0; made 0 (no Reputation table, function or knob yet); head 20260818000351.
-- Generated by scripts/ops/harness/reputation/gen-checks.mjs from the migration's own hunks. Only the catalog and world_config's keys are read.
begin transaction read only;
${cte}
select fn, ord,
       (length(def) - length(replace(def, old, ''))) / length(old) as old_times,
       (length(def) - length(replace(def, new, ''))) / length(new) as new_times,
       (select count(*) from unnest(array['public.reputation_kinds', 'public.reputation_balance', 'public.reputation_book']) t where to_regclass(t) is not null)
         + (select count(*) from pg_proc p join pg_namespace n on n.oid = p.pronamespace where ${FNS})
         + (select count(*) from public.world_config c where ${KNOBS}) as made,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from d order by fn, ord;
commit;
`,
)

writeFileSync(
  path.join(HERE, 'after.sql'),
  `-- 0352 PROD CHECK (after), read-only, ONE statement: ${run('after.sql')}
-- Wanted: 5 rows; every new_times 1; tables 3 (each with row level security and no client privilege); kinds 12; fns 8 and client_fns 0;
-- triggers 4; reads "s/s" (reputation_card and world.player() both STABLE); head 20260818000352; knobs:
-- {"rep_battle":40,"rep_built":100,"rep_day_cap":600,"rep_landfall":25,"rep_lap":10,"rep_miles_max":40,"rep_nm_per_point":100,"rep_per_fight_point":2,
--  "rep_profit_per_point":250,"rep_request_max":100,"rep_request_min":5,"rep_request_per_point":250,"rep_sale_max":120,"reputation_on":true}
-- Generated by scripts/ops/harness/reputation/gen-checks.mjs from the migration's own hunks. The catalog, the 12 kinds and the 14 knobs are read; no book row.
begin transaction read only;
${cte}
select fn, ord,
       (length(def) - length(replace(def, new, ''))) / length(new) as new_times,
       (select count(*) from pg_class c
         where c.oid in (to_regclass('public.reputation_kinds'), to_regclass('public.reputation_balance'), to_regclass('public.reputation_book'))
           and c.relrowsecurity
           and not has_table_privilege('anon', c.oid, 'select,insert,update,delete')
           and not has_table_privilege('authenticated', c.oid, 'select,insert,update,delete')) as tables,
       (select count(*) from public.reputation_kinds) as kinds,
       (select count(*) from pg_proc p join pg_namespace n on n.oid = p.pronamespace where ${FNS}) as fns,
       (select count(*) from pg_proc p join pg_namespace n on n.oid = p.pronamespace where ${FNS}
           and (has_function_privilege('anon', p.oid, 'execute') or has_function_privilege('authenticated', p.oid, 'execute'))) as client_fns,
       (select count(*) from pg_trigger t where not t.tgisinternal and t.tgrelid in (to_regclass('public.reputation_balance'), to_regclass('public.reputation_book'))) as triggers,
       (select p.provolatile::text from pg_proc p where p.oid = to_regprocedure('public.reputation_card(uuid)')) || '/' ||
         (select p.provolatile::text from pg_proc p where p.oid = to_regprocedure('world.player()')) as reads,
       (select jsonb_object_agg(c.key, c.value order by c.key) from public.world_config c where ${KNOBS}) as knobs,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from d order by fn, ord;
commit;
`,
)
console.log('wrote before-hunks.sql and after.sql (5 hunks)')
