// gen-level-checks.mjs: writes the two PROD CHECK files that carry 0356's hunks (level-before-hunks.sql, level-after.sql)
// from the migration's own text, so the texts checked on prod are the texts the migration cuts. LOCAL ONLY; not in CI.
//   node scripts/ops/harness/reputation/gen-level-checks.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const MIG = path.resolve(HERE, '../../../../supabase/migrations/20260818000356_a_level_crossed_is_a_moment.sql')
const sql = readFileSync(MIG, 'utf8').replaceAll('\r', '')
const re = /\('([a-z_.]+\([a-z ,]*\))', (\d+),\n\$o\$([\s\S]*?)\$o\$,\n\$n\$([\s\S]*?)\$n\$\)/g
const hunks = [...sql.matchAll(re)].map((m) => ({ fn: m[1], n: m[2], old: m[3], new: m[4] }))
if (hunks.length !== 4) throw new Error(`expected 4 hunks in the migration, found ${hunks.length}`)
for (const h of hunks) if (h.old.includes('$h$') || h.new.includes('$h$')) throw new Error('a hunk holds the quote tag')
const values = hunks.map((h) => `  ('${h.fn}'::text, ${h.n}, $h$${h.old}$h$, $h$${h.new}$h$)`).join(',\n')
const cte = `with h(fn, ord, old, new) as (values\n${values}\n), d as (\n  select h.*, replace(pg_get_functiondef(h.fn::regprocedure), chr(13), '') as def from h\n)`
const run = (f) => `npx --yes supabase@2.120.0 db query --linked -f scripts/ops/harness/reputation/${f}`
const MADE = `(select count(*) from pg_class c where c.oid = to_regclass('public.house_level_marks'))
         + (select count(*) from pg_proc p join pg_namespace n on n.oid = p.pronamespace
             where (n.nspname, p.proname) in (('public', 'level_marks_settle'), ('cmd', 'level_up'), ('public', 'reputation_lap')))
         + (select count(*) from public.world_config c where c.key = 'rep_level_per_level')`

writeFileSync(
  path.join(HERE, 'level-before-hunks.sql'),
  `-- 0356 PROD CHECK (before), read-only, ONE statement: ${run('level-before-hunks.sql')}
-- Wanted: 4 rows; every old_times 1 and new_times 0; made 0 (no marks table, function or knob of 0356 yet); r1 "true/10" (reputation_on and rep_lap,
-- R1's, as 0352 left them); head 20260818000355 (0354 and 0355 deploy first; neither cuts one of these four texts).
-- Generated by scripts/ops/harness/reputation/gen-level-checks.mjs from the migration's own hunks. Only the catalog and two world_config keys are read.
begin transaction read only;
${cte}
select fn, ord,
       (length(def) - length(replace(def, old, ''))) / length(old) as old_times,
       (length(def) - length(replace(def, new, ''))) / length(new) as new_times,
       ${MADE} as made,
       (select c.value::text from public.world_config c where c.key = 'reputation_on') || '/' || (select c.value::text from public.world_config c where c.key = 'rep_lap') as r1,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from d order by fn, ord;
commit;
`,
)

writeFileSync(
  path.join(HERE, 'level-after.sql'),
  `-- 0356 PROD CHECK (after), read-only, ONE statement: ${run('level-after.sql')}
-- Wanted: 4 rows; every new_times 1; made 5 (the table, three functions, the knob); knob 10; table_ok true (row level security, no client privilege, the
-- foreign key to players with its cascade); door "false/true" (anon may not, authenticated may call cmd.level_up); server_fns 0 (no client may call the
-- settle or the lap helper); namers "public.level_marks_settle,public.reputation_card" (only they name the marks table); callers
-- "cmd.level_up,public.reputation_arrival"; registry 1; news 1; marked = humans at the deploy (every human then has her three marks; a house founded
-- since has none until it crosses a level); head 20260818000356. The levels themselves are level-after-seed.sql's.
-- Generated by scripts/ops/harness/reputation/gen-level-checks.mjs from the migration's own hunks. The catalog, one knob, one news key and the marks table's keys are read; no book row.
begin transaction read only;
${cte}
select fn, ord,
       (length(def) - length(replace(def, new, ''))) / length(new) as new_times,
       ${MADE} as made,
       (select c.value from public.world_config c where c.key = 'rep_level_per_level') as knob,
       (select c.relrowsecurity
               and not has_table_privilege('anon', c.oid, 'select,insert,update,delete')
               and not has_table_privilege('authenticated', c.oid, 'select,insert,update,delete')
               and exists (select 1 from pg_constraint k where k.conrelid = c.oid and k.contype = 'f' and k.confrelid = 'public.players'::regclass and k.confdeltype = 'c')
          from pg_class c where c.oid = to_regclass('public.house_level_marks')) as table_ok,
       has_function_privilege('anon', 'cmd.level_up()', 'execute')::text || '/' || has_function_privilege('authenticated', 'cmd.level_up()', 'execute')::text as door,
       (select count(*) from pg_proc p join pg_namespace n on n.oid = p.pronamespace
         where (n.nspname, p.proname) in (('public', 'level_marks_settle'), ('public', 'reputation_lap'))
           and (has_function_privilege('anon', p.oid, 'execute') or has_function_privilege('authenticated', p.oid, 'execute'))) as server_fns,
       (select string_agg(n.nspname || '.' || p.proname, ',' order by n.nspname, p.proname)
          from pg_proc p join pg_namespace n on n.oid = p.pronamespace where p.prokind in ('f', 'p') and p.prosrc like '%house_level_marks%') as namers,
       (select string_agg(n.nspname || '.' || p.proname, ',' order by n.nspname, p.proname)
          from pg_proc p join pg_namespace n on n.oid = p.pronamespace where p.prokind in ('f', 'p') and p.prosrc like '%level_marks_settle(%') as callers,
       (select count(*) from public.client_rpc_entry_points() e where e.schema_name = 'cmd' and e.function_name = 'level_up' and e.fn is not null) as registry,
       (select count(*) from public.world_news w where w.key = 'update:0356') as news,
       (select count(*) from public.players p where not p.is_npc) as humans,
       (select count(distinct m.player_id) from public.house_level_marks m) as marked,
       (select max(version) from supabase_migrations.schema_migrations) as head
  from d order by fn, ord;
commit;
`,
)
console.log('wrote level-before-hunks.sql and level-after.sql (4 hunks)')
