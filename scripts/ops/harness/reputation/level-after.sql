begin transaction read only;
with h(fn, ord, old, new) as (values
  ('public.reputation_arrival(uuid,uuid)'::text, 1, $h$  select v.total_nm, v.dest_port_id, v.departed_at into v_nm, v_dest, v_sailed
$h$, $h$  -- 0356 (R4): every level she has crossed and not been paid for fires here, at the arrival's own moment (public.level_marks_settle)
  perform public.level_marks_settle(p_player);
