import { readFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { defineConfig, type Plugin } from 'vite'
import react from '@vitejs/plugin-react'
import tailwindcss from '@tailwindcss/vite'

// base '/byeharu-voyage/' = served as a GitHub Pages project site at
// https://<owner>.github.io/byeharu-voyage/. BrowserRouter reads this via BASE_URL
// (src/app/App.tsx passes import.meta.env.BASE_URL as its basename), and public/404.html
// encodes deep links back through index.html's decoder.

// ═══════════════════════════════════════════════════════════════════════════════════════════════
// THE PRE-BUILT WORLD — generated by the build, never committed
// ═══════════════════════════════════════════════════════════════════════════════════════════════
//
// Replaying 45 migrations in the player's tab cost 78.8 s on a cold boot (docs/DEV_LOG.md:177).
// The chain is a pure function of the repository, so this plugin runs it ONCE, here, and emits the
// resulting PostgreSQL data directory as `dist/db/world-<fingerprint>.tar.gz`.
//
// WHY IT IS A BUILD STEP AND NOT A CHECKED-IN FILE. A committed image is a second copy of the
// world that a human must remember to regenerate, and this project has already lost a working day
// to precisely that (docs/DEV_LOG.md D23: an edited migration left production on 70 goods while
// every fresh rebuild got 243, and "nothing red happened anywhere"). Generated at build time from
// the chain in `supabase/migrations` at that moment, keyed by that chain's fingerprint, there is
// nothing to forget: change a migration and the next build makes a new image under a new name,
// which is the only name the client will ever ask for.
//
// The emitted name is deterministic — no content hash — because the client derives the URL from
// `fingerprintChain(files)` at run time (src/lib/db/worldImage.ts). If the two ever disagree the
// fetch is a 404 and the boot applies the chain, which is the behaviour this optimisation replaced.
//
// In `vite dev` nothing is generated (one chain apply is minutes of CPU and dev reloads
// constantly); the middleware below serves an image only if a previous `npm run build` or
// `npm run db:image` already put one in the cache for exactly this chain.
//
// EVERY IMPORT OF THE BUILDER IS DYNAMIC AND ITS PATH IS COMPUTED. Vite bundles this config file
// with esbuild into a temporary module, and a literal relative import would be INLINED into that
// temporary file — where `import.meta.url` no longer points at scripts/db/, and the builder's
// REPO_ROOT (and with it supabase/migrations and data/) would resolve somewhere else entirely. A
// computed specifier is left alone and loaded by Node from where it actually lives.
// ═══════════════════════════════════════════════════════════════════════════════════════════════
function worldImage(): Plugin {
  let root = process.cwd()
  let building = false

  const builder = async () => {
    const file = path.join(root, 'scripts', 'db', 'build-image.mjs')
    if (!existsSync(file)) throw new Error(`world image: ${file} is missing`)
    return (await import(pathToFileURL(file).href)) as typeof import('./scripts/db/build-image.mjs')
  }

  return {
    name: 'byeharu:world-image',
    configResolved(config) {
      root = config.root
      // Only a real build generates one. `vite dev` and `vite preview` read what a build left.
      building = config.command === 'build'
    },
    async buildStart() {
      if (!building) return
      const { ensureWorldImage, WORLD_IMAGE_DIR, worldImageFileName } = await builder()
      const image = await ensureWorldImage({ log: (...args) => this.info(args.join(' ')) })
      this.emitFile({
        type: 'asset',
        fileName: `${WORLD_IMAGE_DIR}/${worldImageFileName(image.fingerprint)}`,
        source: image.bytes,
      })
    },
    async configureServer(server) {
      const { IMAGE_CACHE_DIR, WORLD_IMAGE_DIR, chainAndFingerprint, worldImageFileName } =
        await builder()
      server.middlewares.use(async (req, res, next) => {
        const url = (req.url ?? '').split('?')[0]
        if (!url.includes(`/${WORLD_IMAGE_DIR}/world-`)) return next()
        const { fingerprint } = await chainAndFingerprint()
        const name = worldImageFileName(fingerprint)
        const file = path.join(IMAGE_CACHE_DIR, name)
        // A cache entry is named for the chain that built it, so this can only ever serve THIS
        // chain's image. Anything else is a 404, and a 404 makes the boot apply the chain.
        if (!url.endsWith(name) || !existsSync(file)) return next()
        res.setHeader('Content-Type', 'application/gzip')
        res.end(await readFile(file))
      })
    },
  }
}

// ═══════════════════════════════════════════════════════════════════════════════════════════════
// THE BUILD ID — which build a tab is running, and which one is published (2026-10-19)
// ═══════════════════════════════════════════════════════════════════════════════════════════════
//
// WHY. The owner kept a tab open across deploys, played an old build, and reported a defect that
// had already been fixed. Nothing in the app could tell him a newer build was live, because
// nothing in the app knew which build it was. So every build gets ONE id — the commit it was
// built from plus the moment it was built — written in TWO places by this plugin from the SAME
// value: into the bundle as the constant `__BUILD_ID__` (src/lib/version.ts reads it), and into
// `dist/version.json` beside index.html. A running tab fetches version.json and compares; when
// the two ids differ, a newer build is published and src/app/NewVersionToast.tsx says so.
//
// ONE VALUE, COMPUTED ONCE. The id is taken when the config loads, not per hook, so the constant
// the bundle carries and the file beside it cannot disagree within one build. `GITHUB_SHA` is the
// commit on a runner (actions/checkout leaves a full clone, but the variable is the cheaper and
// the surer read); `git rev-parse` is the commit on a dev machine. Neither available means the
// build cannot be named, and a build that cannot be named cannot be told apart from the next one
// — so that THROWS rather than stamping `unknown` (docs/NO_SPAGHETTI.md §7C: a fallback that hands
// over a different thing is not a fallback).
//
// WHY A SEPARATE FILE AND NOT THE BUNDLE'S OWN HASH. The tab needs to learn the PUBLISHED id
// without downloading the published bundle, and it needs an answer the CDN will not serve stale.
// GitHub Pages serves everything with `max-age=600`, so the client fetches version.json with
// `cache: 'no-store'` AND a cache-busting query (`?t=<now>`), which makes every check a distinct
// URL at the edge. The file is 60 bytes; the bundle is not.
//
// IN `vite dev` the same id is served from memory so the toast's code path runs there too; in
// `vite preview` dist/version.json is served like any other file.
// ═══════════════════════════════════════════════════════════════════════════════════════════════
export const VERSION_FILE = 'version.json'

function buildId(): string {
  const sha =
    process.env.GITHUB_SHA ??
    (() => {
      try {
        return execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim()
      } catch {
        return ''
      }
    })()
  if (!/^[0-9a-f]{40}$/.test(sha)) {
    throw new Error(
      'build id: no commit to name this build after (GITHUB_SHA is unset and `git rev-parse HEAD` gave nothing)',
    )
  }
  return `${sha.slice(0, 7)}+${new Date().toISOString()}`
}

function buildVersion(): Plugin {
  const id = buildId()
  const body = JSON.stringify({ id })
  return {
    name: 'byeharu:build-version',
    config: () => ({ define: { __BUILD_ID__: JSON.stringify(id) } }),
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: VERSION_FILE, source: body })
    },
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        if ((req.url ?? '').split('?')[0] !== `${server.config.base}${VERSION_FILE}`) return next()
        res.setHeader('Content-Type', 'application/json')
        res.setHeader('Cache-Control', 'no-store')
        res.end(body)
      })
    },
  }
}

export default defineConfig({
  base: '/byeharu-voyage/',
  plugins: [react(), tailwindcss(), worldImage(), buildVersion()],
})
