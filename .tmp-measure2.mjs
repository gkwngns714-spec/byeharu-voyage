import pw from '@playwright/test'
const { chromium } = pw
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 1440, height: 731 }, colorScheme: 'dark', locale: 'en-US' })
const p = await ctx.newPage()
await p.goto('http://localhost:4323/byeharu-voyage/command')
await p.waitForSelector('[data-testid="trade-good"]', { timeout: 180000 })
const rows = () => p.evaluate(() => [...document.querySelectorAll('[data-testid="trade-good"]')].slice(0, 10).map((e) => Math.round(e.getBoundingClientRect().top)))
await p.waitForTimeout(50)
const before = await rows()
await p.getByTestId('trade-buy').nth(2).click()
await p.waitForSelector('[data-testid="good-detail"]', { timeout: 60000 })
await p.waitForTimeout(600)
const after = await rows()
console.log('before', JSON.stringify(before))
console.log('after ', JSON.stringify(after))
const moved = before.map((v, i) => (v === after[i] ? null : i)).filter((x) => x !== null)
console.log('moved indexes', JSON.stringify(moved))
const info = await p.evaluate(() => {
  const cards = [...document.querySelectorAll('[data-testid="trade-good"]')].slice(0, 12)
  return cards.map((e, i) => ({ i, h: Math.round(e.getBoundingClientRect().height), top: Math.round(e.getBoundingClientRect().top), text: (e.textContent || '').replace(/\s+/g, ' ').slice(0, 40) }))
})
console.log(JSON.stringify(info))
await b.close()
